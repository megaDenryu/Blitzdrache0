//! 役割に包まれた関数のパスの受理する正規形の回帰試験。4つの条件のどれで落ちたかが読み分けられることを1件ずつ固定する。
//!
//! この試験が在るのは、広く読む抽出器が偽の設計関係を作るためである。関係が出ないことは検証器が未決定を返すだけで済むが、
//! 実在しない識別子の節点へ辺を張ると、その上で示した命題の成立が意味を持たなくなる。

use super::test_support::{原文から結末を組む, 役割の使用箇所の試験が使う型の定義, 抽出できなかった理由の説明一覧, 解釈の使用箇所, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";

fn 説明一覧と関係一覧(右辺: &str) -> (Vec<String>, Vec<String>) {
    let 結末 = 原文から結末を組む(&[(移動のパス, &解釈の使用箇所(右辺))]);
    (抽出できなかった理由の説明一覧(&結末), 関係の表記一覧(&結末))
}

#[test]
fn 呼び出し先が役割の生成するでない右辺は欠落になる() {
    let (説明一覧, 関係一覧) = 説明一覧と関係一覧("配線.解釈を取り出す()");
    assert!(説明一覧.iter().any(|説明| 説明.contains("の形でなく主語を決められない")), "{説明一覧:?}");
    assert!(!関係一覧.iter().any(|表記| 表記.contains("解釈を取り出す")), "{関係一覧:?}");
}

#[test]
fn 呼び出し先が別の型の生成するである右辺は欠落になる() {
    let (説明一覧, 関係一覧) = 説明一覧と関係一覧("別の役割::生成する(キーボード歩行入力::歩行入力を解釈する)");
    assert!(説明一覧.iter().any(|説明| 説明.contains("の形でなく主語を決められない")), "{説明一覧:?}");
    assert!(!関係一覧.iter().any(|表記| 表記.contains("歩行入力を解釈する")), "{関係一覧:?}");
}

#[test]
fn 戻り値の型に書いた役割は右辺を持たないため欠落になる() {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + "pub fn 歩行を解釈する() -> M解釈関数<キーボード歩行入力, 旅行者の意図> {\n    M解釈関数::生成する(解釈)\n}\n";
    let 結末 = 原文から結末を組む(&[(移動のパス, &原文)]);
    assert!(!関係の表記一覧(&結末).iter().any(|表記| 表記.contains("消費する")), "{:?}", 関係の表記一覧(&結末));
    assert!(抽出できなかった理由の説明一覧(&結末).iter().any(|説明| 説明.contains("の形でなく主語を決められない")), "{:?}", 抽出できなかった理由の説明一覧(&結末));
}

#[test]
fn クレートの起点から書いたパスは誤った現在のモジュールの配下として抽出せず欠落になる() {
    let (説明一覧, 関係一覧) = 説明一覧と関係一覧("M解釈関数::生成する(crate::foo::キーボード歩行入力::歩行入力を解釈する)");
    assert!(説明一覧.iter().any(|説明| 説明.contains("2区分であるべきだが4区分である")), "{説明一覧:?}");
    assert!(!関係一覧.iter().any(|表記| 表記.contains("歩行入力を解釈する")), "偽の識別子の節点へ辺が出ている: {関係一覧:?}");
}

