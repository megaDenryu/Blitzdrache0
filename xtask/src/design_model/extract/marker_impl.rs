//! 抽出の規則2: 設計解釈マーカーの実装から、マーカーの実装の事実を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは実装した型の節点と、マーカーの実装の事実を持つ成果である。設計関係は出さない。
//!
//! 行の集めは `クレート構文検査::設計解釈マーカーの実装一覧` をそのまま使う。同じ規則で集めるため、`cargo xtask conform` が正規形として通した実装は
//! ここでも1件として現れ、正規形でない実装はどちらにも現れない(そちらは違反として別に報告される)。
//!
//! この事実の集まりが、ある型が直に実装している設計解釈マーカーの集合である。上位トレイトの宣言で閉じた分類は、
//! グラフの組み立てが `節点の分類` として計算する。抽出器が閉包を先に取らないのは、公理の正本を上位トレイトの宣言の事実1つに保つためである。

use super::marker_concept::設計解釈マーカーの参照;
use super::outcome::抽出の成果;
use super::source_group::抽出対象のソース群;
use super::抽出できなかった行;
use crate::conform::design_ontology::trait_implementation::設計解釈マーカーの実装;
use crate::conform::design_ontology::設計解釈マーカーの一覧::設計解釈マーカー;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};
use blitz_design_verification::{マーカーの実装の事実, 事実の出どころ};

pub fn 設計解釈マーカーの実装から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for マーカー in 設計解釈マーカー::全部の一覧() {
        for 実装 in ソース群.構文検査().設計解釈マーカーの実装一覧(マーカー) {
            let (識別子, 欠落) = 実装の対象の識別子(ソース群, &実装);
            成果.抽出できなかった行一覧.extend(欠落);
            let 型の節点 = 設計概念::Rustの項目として生成する(識別子, Rustの項目の種類::型);
            成果.マーカーの実装一覧.push(マーカーの実装の事実 {
                型: 型の節点.参照を組む(),
                マーカー: 設計解釈マーカーの参照(マーカー.名前()),
                出どころ: 事実の出どころ {
                    パス: 実装.パス.clone(), 行番号: 実装.行番号
                },
            });
            成果.概念一覧.push(型の節点);
        }
    }
    成果
}

// 実装の対象の型の識別子。標準の `Result` への包括の実装だけは、`crates` 配下に定義が無いため表記そのものから組む。
fn 実装の対象の識別子(ソース群: &抽出対象のソース群, 実装: &設計解釈マーカーの実装) -> (設計概念の識別子, Option<抽出できなかった行>) {
    if 実装.正本の標準resultへの包括の実装か() {
        // 標準の `Result` は `crates` 配下に定義が無いため、定義をたどらず標準ライブラリの表記そのものから節点を組む。
        return (設計概念の識別子::Rustの項目として生成する("std::result", "Result"), None);
    }
    ソース群.型の識別子を求める(実装.型の在り処の問い())
}
