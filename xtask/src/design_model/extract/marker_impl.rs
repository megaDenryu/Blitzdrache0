//! 抽出の規則2: 設計解釈マーカーの実装から `下位型である` を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは実装した型の節点とマーカーの節点、および `下位型である` の関係を持つ成果である。
//!
//! 行の集めは `クレート構文検査::トレイト実装型一覧` をそのまま使う。同じ規則で集めるため、`cargo xtask conform` が正規形として通した実装は
//! ここでも1件として現れ、正規形でない実装はどちらにも現れない(そちらは違反として別に報告される)。
//!
//! この関係が、ある型が実装している設計解釈マーカーの集合そのものである。節点の属性として重ねて持たないのは、
//! 同じ集合の正本が2つになり、片方だけを更新する取りこぼしを型が止められないためである。集合を問うときは `目的語一覧(型, 下位型である)` を読む。

use super::marker_concept::設計解釈マーカーの識別子;
use super::outcome::抽出の成果;
use super::source_group::抽出対象のソース群;
use crate::conform::design_ontology::syntax_patterns::オントロジートレイト;
use crate::conform::design_ontology::trait_implementation::トレイト実装型;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};
use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計関係, 設計関係の種類};

pub fn 設計解釈マーカーの実装から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for マーカー in オントロジートレイト::全部の一覧() {
        for 実装 in ソース群.構文検査().トレイト実装型一覧(マーカー) {
            let 主語 = 実装の対象の識別子(ソース群, &実装);
            成果.概念一覧.push(設計概念::Rustの項目として生成する(主語.clone(), Rustの項目の種類::型));
            成果.関係一覧.push(設計関係 {
                主語,
                種類: 設計関係の種類::下位型である,
                目的語: 設計解釈マーカーの識別子(マーカー.名前()),
                出どころ: 抽出の出どころ {
                    パス: 実装.パス.clone(),
                    行番号: 実装.行番号,
                    構文: 抽出元の構文::設計解釈マーカーの実装,
                },
            });
        }
    }
    成果
}

// 実装の対象の型の識別子。標準の `Result` への包括の実装だけは、先頭の識別子が `std` になるため表記そのものから組む。
fn 実装の対象の識別子(ソース群: &抽出対象のソース群, 実装: &トレイト実装型) -> 設計概念の識別子 {
    if 実装.正本の標準resultへの包括の実装か() {
        // 標準の `Result` は `crates` 配下に定義が無いため、定義をたどらず標準ライブラリの表記そのものから節点を組む。
        return 設計概念の識別子::Rustの項目として生成する("std::result", "Result");
    }
    let (モジュールパス, 型名) = ソース群.構文検査().型の同一性(実装);
    設計概念の識別子::Rustの項目として生成する(モジュールパス.表記(), &型名)
}
