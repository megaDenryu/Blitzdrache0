//! 関数の役割の型を定義する場所の知識。役割ごとに、その型を定義するモジュールと、役割の型と同じ場所に定義された意味型を答える。
//!
//! 役割の名前と型引数の数は、関数の役割の宣言という事実の形を決めるため `blitz_design_verification` の `関数の役割` が持ち、
//! 型引数の位置ごとに出す設計の関係は役割の定義の知識として同じクレートの定義の式が持つ(Issue #193 の段階2)。
//! ここに残るのは、役割の型と意味型をドメインの型から見分けるための、定義の在り処の知識である(`_doc/設計/設計オントロジー.md` 2.1節・第3節)。
//! この知識はRustのソースのどこに型が在るかを答えるものであり、抽出器の側の関心事である。
//! 受け取る役割の型が外部クレート `blitz_design_verification` の型であり、xtask の側からメソッドを生やせないため、どれも自由関数にする。
//! 参照: `crates/blitz_design/src/function_role.rs`・`crates/blitz_esca/src/ontology.rs`。

use super::ontology_scope::設計語彙のクレート;
use crate::design_model::設計概念への参照;
use blitz_design_verification::関数の役割;

/// Esca が設計語彙へ足した `M遷移関数` と `遷移成功結果` と `遷移失敗結果` を定義するモジュールのパス。
const 遷移関数の役割を定義するモジュールのパス: &str = "blitz_esca::ontology";

/// その役割の型を定義するモジュールのパス。`M射影関数`・`M解釈関数` は `blitz_design::function_role`、`M遷移関数` は `blitz_esca::ontology` に在る。
pub fn 役割の型を定義するモジュールのパス(役割: 関数の役割) -> String {
    match 役割 {
        関数の役割::M解釈関数 | 関数の役割::M射影関数 => format!("{設計語彙のクレート}::function_role"),
        関数の役割::M遷移関数 => 遷移関数の役割を定義するモジュールのパス.to_string(),
    }
}

/// その役割の型と同じモジュールに定義された意味型の名前。意味型とは、型引数に設計解釈マーカーの境界を持ち、
/// その役割の戻り値の形を固定する型のことである(`遷移成功結果<状態: M状態, イベント: Mイベント>` と `遷移失敗結果<状態: M状態, 失敗: std::error::Error>`)。
pub const fn 伴う意味型の名前一覧(役割: 関数の役割) -> &'static [&'static str] {
    match 役割 {
        関数の役割::M解釈関数 | 関数の役割::M射影関数 => &[],
        関数の役割::M遷移関数 => &["遷移成功結果", "遷移失敗結果"],
    }
}

/// その参照が、関数の役割の型か、役割に伴う意味型の節点を指すか。この2つはドメインの型でなく、処理の役割の層に置かれた設計語彙である。
/// 名前だけで判定せず、定義のモジュールパスと種類まで一致させる。名前だけで判定すると、ドメインのクレートが同じ名前の型を定義したとき、
/// その型を設計語彙と取り違えるためである。
pub fn 関数の役割の型か意味型を指す参照か(参照: &設計概念への参照) -> bool {
    関数の役割::全部の一覧().into_iter().any(|役割| {
        let モジュールパス = 役割の型を定義するモジュールのパス(役割);
        std::iter::once(役割.名前())
            .chain(伴う意味型の名前一覧(役割).iter().copied())
            .any(|名前| *参照 == 設計概念への参照::型として生成する(&モジュールパス, 名前))
    })
}
