//! 関数の設計上の役割の語彙。役割ごとに、名前と取る型引数の数と、型引数の位置ごとに出す設計関係の種類を答える。
//!
//! この語彙を使用箇所の読み取りから分けるのは、触る状態が違うためである。こちらは役割そのものの定義(名前と型引数の意味)を所有し、
//! 読み取りの側は1行のRustの構文を所有する。役割を1つ足すときに直すのはこのファイルだけである。
//! 参照: `crates/blitz_design/src/function_role.rs`・`crates/blitz_esca/src/ontology.rs`。

use crate::design_model::設計関係の種類;

/// 関数の設計上の役割。`M射影関数`・`M解釈関数` は `blitz_design::function_role`、`M遷移関数` は `blitz_esca::ontology` に在る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 関数の役割 {
    M解釈関数,
    M射影関数,
    M遷移関数,
}

impl 関数の役割 {
    /// 3つの役割の全件。
    pub const fn 全部の一覧() -> [Self; 3] {
        [Self::M解釈関数, Self::M射影関数, Self::M遷移関数]
    }

    pub const fn 名前(self) -> &'static str {
        match self {
            Self::M解釈関数 => "M解釈関数",
            Self::M射影関数 => "M射影関数",
            Self::M遷移関数 => "M遷移関数",
        }
    }

    /// その役割が取る型引数の数。
    pub const fn 型引数の数(self) -> usize {
        match self {
            Self::M解釈関数 | Self::M射影関数 => 2,
            Self::M遷移関数 => 5,
        }
    }

    /// 型引数の位置と、その位置の型に対して出す関係の種類。同じ位置が2度現れてよい。`M遷移関数` の第1の型引数(状態)は
    /// 現在の状態として消費され、次の状態として生成されるため、`消費する` と `生成する` の2本を出す。
    /// `M遷移関数` の第5の型引数(失敗)からも `生成する` を出す。`Result<成功, 失敗>` の `Err(失敗)` はその処理が取りうる
    /// 明白な出力であり、毎回生成されるとは限らないことは除外の理由にならない(`Mイベント` も毎回は生成されないが `生成する` を出している)。
    pub const fn 型引数の位置ごとの関係(self) -> &'static [(usize, 設計関係の種類)] {
        match self {
            Self::M解釈関数 | Self::M射影関数 => &[(0, 設計関係の種類::消費する), (1, 設計関係の種類::生成する)],
            Self::M遷移関数 => &[
                (0, 設計関係の種類::消費する),
                (1, 設計関係の種類::消費する),
                (2, 設計関係の種類::参照する),
                (3, 設計関係の種類::生成する),
                (4, 設計関係の種類::生成する),
                (0, 設計関係の種類::生成する),
            ],
        }
    }

    /// その役割が型引数によらず常に受け取る固定の入力の型の名前と、その型に対して出す関係の種類。
    ///
    /// この宣言が役割の定義の側に在るのは、固定の入力が使用箇所の1行のどこにも表記として現れないためである。
    /// `M遷移関数` の `遷移パラメータ` は `遷移の関数ポインタ`(`crates/blitz_esca/src/ontology.rs`)の第4引数として
    /// 役割の定義が固定しており、`M遷移関数<状態, コマンド, 規則, イベント, 失敗>` という使用箇所の表記には出てこない。
    /// 使用箇所に表記が無いことは、その入力が設計関係のグラフに存在しないことを意味しない。
    pub const fn 固定で受け取る入力(self) -> &'static [(&'static str, 設計関係の種類)] {
        match self {
            Self::M解釈関数 | Self::M射影関数 => &[],
            Self::M遷移関数 => &[("遷移パラメータ", 設計関係の種類::消費する)],
        }
    }
}
