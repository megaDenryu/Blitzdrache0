//! 関数の設計上の役割の語彙。役割ごとに、名前と取る型引数の数と、型引数の位置ごとに出す設計関係の種類を答える。
//!
//! この語彙を使用箇所の読み取りから分けるのは、触る状態が違うためである。こちらは役割そのものの定義(名前と型引数の意味)を所有し、
//! 読み取りの側は1行のRustの構文を所有する。役割を1つ足すときに直すのはこのファイルだけである。
//! 役割の型を定義するモジュールと、役割の型と同じ場所に定義された意味型もここが持つ。どちらも、その型を設計語彙の層の型として
//! ドメインの型から見分けるために要る(`_doc/設計/設計オントロジー.md` 2.1節・第3節)。
//! 参照: `crates/blitz_design/src/function_role.rs`・`crates/blitz_esca/src/ontology.rs`。

use super::ontology_scope::設計語彙のクレート;
use crate::design_model::{設計概念への参照, 設計関係の種類};

/// Esca が設計語彙へ足した `M遷移関数` と `遷移成功結果` と `遷移失敗結果` を定義するモジュールのパス。
const 遷移関数の役割を定義するモジュールのパス: &str = "blitz_esca::ontology";

/// 関数の設計上の役割。`M射影関数`・`M解釈関数` は `blitz_design::function_role`、`M遷移関数` は `blitz_esca::ontology` に在る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 関数の役割 {
    M解釈関数,
    M射影関数,
    M遷移関数,
}

impl 関数の役割 {
    /// 3つの役割の全件。
    pub const fn 全部の一覧() -> [Self; 3] {
        [Self::M解釈関数, Self::M射影関数, Self::M遷移関数]
    }

    pub const fn 名前(self) -> &'static str {
        match self {
            Self::M解釈関数 => "M解釈関数",
            Self::M射影関数 => "M射影関数",
            Self::M遷移関数 => "M遷移関数",
        }
    }

    /// その役割が取る型引数の数。
    pub const fn 型引数の数(self) -> usize {
        match self {
            Self::M解釈関数 | Self::M射影関数 => 2,
            Self::M遷移関数 => 5,
        }
    }

    /// 型引数の位置と、その位置の型に対して出す関係の種類。同じ位置が2度現れてよい。`M遷移関数` の第1の型引数(状態)は
    /// 現在の状態として消費され、次の状態として生成されるため、`消費する` と `生成する` の2本を出す。
    /// `M遷移関数` の第5の型引数(失敗)からも `生成する` を出す。`Err(遷移失敗結果<状態, 失敗>)` が運ぶ失敗の理由はその処理が取りうる
    /// 明白な出力であり、毎回生成されるとは限らないことは除外の理由にならない(`Mイベント` も毎回は生成されないが `生成する` を出している)。
    pub const fn 型引数の位置ごとの関係(self) -> &'static [(usize, 設計関係の種類)] {
        match self {
            Self::M解釈関数 | Self::M射影関数 => &[(0, 設計関係の種類::消費する), (1, 設計関係の種類::生成する)],
            Self::M遷移関数 => &[
                (0, 設計関係の種類::消費する),
                (1, 設計関係の種類::消費する),
                (2, 設計関係の種類::参照する),
                (3, 設計関係の種類::生成する),
                (4, 設計関係の種類::生成する),
                (0, 設計関係の種類::生成する),
            ],
        }
    }

    /// その役割が型引数によらず常に受け取る固定の入力の型の名前と、その型に対して出す関係の種類。
    ///
    /// この宣言が役割の定義の側に在るのは、固定の入力が使用箇所の1行のどこにも表記として現れないためである。
    /// `M遷移関数` の `遷移パラメータ` は `遷移の関数ポインタ`(`crates/blitz_esca/src/ontology.rs`)の第4引数として
    /// 役割の定義が固定しており、`M遷移関数<状態, コマンド, 規則, イベント, 失敗>` という使用箇所の表記には出てこない。
    /// 使用箇所に表記が無いことは、その入力が設計関係のグラフに存在しないことを意味しない。
    pub const fn 固定で受け取る入力(self) -> &'static [(&'static str, 設計関係の種類)] {
        match self {
            Self::M解釈関数 | Self::M射影関数 => &[],
            Self::M遷移関数 => &[("遷移パラメータ", 設計関係の種類::消費する)],
        }
    }

    /// その役割の型を定義するモジュールのパス。
    pub fn 定義のモジュールパス(self) -> String {
        match self {
            Self::M解釈関数 | Self::M射影関数 => format!("{設計語彙のクレート}::function_role"),
            Self::M遷移関数 => 遷移関数の役割を定義するモジュールのパス.to_string(),
        }
    }

    /// その役割の型と同じモジュールに定義された意味型の名前。意味型とは、型引数に設計解釈マーカーの境界を持ち、
    /// その役割の戻り値の形を固定する型のことである(`遷移成功結果<状態: M状態, イベント: Mイベント>` と `遷移失敗結果<状態: M状態, 失敗: std::error::Error>`)。
    pub const fn 伴う意味型の名前一覧(self) -> &'static [&'static str] {
        match self {
            Self::M解釈関数 | Self::M射影関数 => &[],
            Self::M遷移関数 => &["遷移成功結果", "遷移失敗結果"],
        }
    }

    // その参照が、この役割の型か、この役割に伴う意味型の節点を指すか。名前だけで判定せず、定義のモジュールパスと種類まで一致させる。
    // 名前だけで判定すると、ドメインのクレートが同じ名前の型を定義したとき、その型を設計語彙と取り違えるためである。
    fn 役割の型か意味型を指すか(self, 参照: &設計概念への参照) -> bool {
        let モジュールパス = self.定義のモジュールパス();
        std::iter::once(self.名前())
            .chain(self.伴う意味型の名前一覧().iter().copied())
            .any(|名前| *参照 == 設計概念への参照::型として生成する(&モジュールパス, 名前))
    }
}

/// その参照が、関数の役割の型か、役割に伴う意味型の節点を指すか。この2つはドメインの型でなく、処理の役割の層に置かれた設計語彙である。
// 受け取る型が外部クレート `blitz_design_verification` の型であり、xtask の側からメソッドを生やせないため自由関数にする。
pub fn 関数の役割の型か意味型を指す参照か(参照: &設計概念への参照) -> bool {
    関数の役割::全部の一覧().into_iter().any(|役割| 役割.役割の型か意味型を指すか(参照))
}
