//! 抽出できなかった行とは、抽出の規則が当たる構文でありながら、抽出器がそこから設計関係を1件も組めなかったソースの行のことである。
//!
//! この型が在るのは、検査器が解析できなかった入力を黙って対象から外してはならないという規約のためである
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。
//! 抽出の結末はこの一覧を件数として持ち、命題の検証の利用者が「関係が0件である」と「その行を読めなかった」を読み分けられるようにする。
//!
//! 黙って対象から外してよいのは、外す条件を書き下せる入力だけである。抽出器がそれとして扱うのは2つだけであり、
//! 設計の概念でないプリミティブの型(`u32`・`String` 等)と、役割の型自身の実装の行である。どちらも理由の選択肢を持たない。
//! 規則が当たる位置に在りながら抽出器が構文を読めない綴りは、`保証範囲の外の構文` が名指して欠落へ倒す。黙って読み飛ばさない。
//!
//! **理由は3つの区分のどれかへ属する。** 区分が要るのは、検証器が辺の不在を根拠にしてよいかが区分で決まるためである。
//! 識別子だけが未解決の行と、設計概念でないため明示して除外した行は、設計関係そのものは失われていない。
//! 設計関係そのものを抽出できなかった行だけが、グラフに在るはずの辺を欠く。区分を答える口をこの型が持つのは、
//! どの選択肢がどの区分かを知っているのが、その選択肢を作った抽出器の側だからである。

use std::path::{Path, PathBuf};

use super::out_of_range_syntax::保証範囲の外の構文;

/// 抽出できなかった行の1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 抽出できなかった行 {
    pub パス: PathBuf,
    pub 行番号: usize, // 1始まり
    pub 理由: 抽出できなかった理由,
}

/// 抽出器がその行から設計関係を組めなかった理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 抽出できなかった理由 {
    /// フィールドの型が、その定義の宣言が導入した型引数の名前である。実在しない設計概念の節点を作らないために関係を出さない。
    型引数である { 型引数名: String },
    /// 型の定義をたどれず、節点のモジュールパスを空にした。節点そのものは落とさない。
    定義のモジュールパスを解決できなかった { 型名: String },
    /// 役割の型引数の中に入れ子の型引数(`<>`)があり、保証範囲の外である。
    役割の型引数に入れ子の型引数がある { 役割名: &'static str },
    /// 役割の型引数の数が、その役割が取る数と合わない。
    役割の型引数の数が合わない { 役割名: &'static str, 取る数: usize, 読めた数: usize },
    /// 役割の値の右辺が `<役割名>::生成する(...)` の形でなく、関係の主語を決められない(戻り値の型・フィールドの型注釈・`= 何か.何か()` の形)。
    役割の値の右辺が役割の生成する呼び出しでない { 役割名: &'static str },
    /// 役割の `生成する` へ渡した引数がRustのパスとして読めず、関係の主語を決められない。
    役割に包まれた関数の引数がパスでない { 役割名: &'static str },
    /// 役割に包まれた関数のパスを `::` で分けた区分が、所有する型1つとメソッド1つの2つでない。
    役割に包まれた関数のパスの区分が2つでない { 役割名: &'static str, 読めた区分の数: usize },
    /// 役割に包まれた関数のパスの1つ目の区分が `crate`・`self`・`super` のどれかであり、所有する型の名前でない。
    役割に包まれた関数のパスが起点の予約語で始まる { 役割名: &'static str, 先頭の区分: String },
    /// 役割に包まれた関数の所有者を対象にする `impl` の行が同じファイルに無く、所有者のモジュールパスを当てる根拠が無い。
    役割に包まれた関数の所有者の実装が同じファイルに無い { 役割名: &'static str, 所有者名: String },
    /// `impl Mエンティティ for 型` の本体に `type 識別子 =` の行が無く、識別する関係の主語を決められない。
    エンティティの識別子の関連型が無い { 型名: String },
    /// 関数の役割の型自身の宣言である。包んでいるのは関数ポインタであり、規則5が使用箇所から別に関係を出す。
    役割の型自身の宣言である { 役割名: &'static str },
    /// 抽出の規則が当たる位置に在りながら、抽出器がその綴りを読めない。
    保証範囲の外の構文である { 構文: 保証範囲の外の構文 },
}

/// 抽出できなかった理由が属する区分。検証器が辺の不在を根拠にしてよいかをこの区分が決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 抽出できなかった理由の区分 {
    /// 識別子だけが未解決である。関係そのものは保存されており、節点のモジュールパスが空になっただけである。
    識別子だけ未解決である,
    /// 設計概念でないため明示して除外した。除外の条件を書き下せており、落ちた設計関係は無い。
    設計概念でないため明示して除外した,
    /// 本来あり得る設計関係そのものを抽出できなかった。グラフに在るはずの辺を欠く。
    設計関係そのものを抽出できなかった,
}

impl 抽出できなかった行 {
    /// パスと行番号と理由から1件を組む。
    pub fn 生成する(パス: &Path, 行番号: usize, 理由: 抽出できなかった理由) -> Self {
        Self {
            パス: パス.to_path_buf(), 行番号, 理由
        }
    }

    /// 人が読む1行の表記。報告がこの表記を並べる。
    pub fn 表記(&self) -> String {
        format!("{}:{}: {}", self.パス.display(), self.行番号, self.理由.説明())
    }
}

impl 抽出できなかった理由 {
    /// この理由が属する区分。
    ///
    /// `定義のモジュールパスを解決できなかった` を識別子だけ未解決であるとするのは、抽出器がその行から関係を組んだうえで
    /// 節点のモジュールパスを空にしているためである。辺はグラフへ入っており、触れた原子命題は
    /// `未決定の理由::型の定義のモジュールパスが未解決である` が別に止める。
    ///
    /// `型引数である` と `役割の型自身の宣言である` を設計概念でないため明示して除外したとするのは、
    /// 型引数が実在する設計概念を指さず、役割の型自身が包む関数ポインタの関係を規則5が別に出しているためである。
    /// どちらもその位置に落ちた設計関係は無く、外す条件も書き下せている。
    ///
    /// `保証範囲の外の構文である` を設計関係そのものを抽出できなかったとするのは、抽出器がその綴りを読めず、
    /// そこに在るはずの辺をグラフへ入れられないためである。
    ///
    /// 残る8つを設計関係そのものを抽出できなかったとするのは、どれも主語か目的語を決められずに関係を1件も組めていないためである。
    /// 役割の受理の条件で落ちた5つと `エンティティの識別子の関連型が無い` は主語を決められず、
    /// `役割の型引数に入れ子の型引数がある` と `役割の型引数の数が合わない` は目的語を決められない。
    /// どの場合も、本来あり得た辺がグラフへ入らない。
    pub const fn 区分(&self) -> 抽出できなかった理由の区分 {
        match self {
            Self::定義のモジュールパスを解決できなかった { .. } => 抽出できなかった理由の区分::識別子だけ未解決である,
            Self::型引数である { .. } | Self::役割の型自身の宣言である { .. } => 抽出できなかった理由の区分::設計概念でないため明示して除外した,
            Self::保証範囲の外の構文である { .. }
            | Self::役割の型引数に入れ子の型引数がある { .. }
            | Self::役割の型引数の数が合わない { .. }
            | Self::役割の値の右辺が役割の生成する呼び出しでない { .. }
            | Self::役割に包まれた関数の引数がパスでない { .. }
            | Self::役割に包まれた関数のパスの区分が2つでない { .. }
            | Self::役割に包まれた関数のパスが起点の予約語で始まる { .. }
            | Self::役割に包まれた関数の所有者の実装が同じファイルに無い { .. }
            | Self::エンティティの識別子の関連型が無い { .. } => 抽出できなかった理由の区分::設計関係そのものを抽出できなかった,
        }
    }

    /// 選択肢の種別の呼び名。運ぶ値(型名・役割名)を含めないのは、この呼び名が同じ種別を束ねた件数の見出しになるためである。
    pub const fn 種別の呼び名(&self) -> &'static str {
        match self {
            Self::型引数である { .. } => "定義の宣言が導入した型引数である",
            Self::定義のモジュールパスを解決できなかった { .. } => "型の定義をたどれずモジュールパスを空にした",
            Self::役割の型引数に入れ子の型引数がある { .. } => "役割の型引数に入れ子の型引数がある",
            Self::役割の型引数の数が合わない { .. } => "役割の型引数の数が合わない",
            Self::役割の値の右辺が役割の生成する呼び出しでない { .. } => "役割の値の右辺が役割の生成する呼び出しでない",
            Self::役割に包まれた関数の引数がパスでない { .. } => "役割に包まれた関数の引数がパスでない",
            Self::役割に包まれた関数のパスの区分が2つでない { .. } => "役割に包まれた関数のパスの区分が2つでない",
            Self::役割に包まれた関数のパスが起点の予約語で始まる { .. } => "役割に包まれた関数のパスが起点の予約語で始まる",
            Self::役割に包まれた関数の所有者の実装が同じファイルに無い { .. } => "役割に包まれた関数の所有者の実装が同じファイルに無い",
            Self::エンティティの識別子の関連型が無い { .. } => "エンティティの識別子の関連型が無い",
            Self::役割の型自身の宣言である { .. } => "関数の役割の型自身の宣言である",
            Self::保証範囲の外の構文である { 構文 } => 構文.種別の呼び名(),
        }
    }

    /// その理由が名指す保証範囲の外の構文。`cargo xtask conform` がこの口から違反を組む。
    pub const fn 保証範囲の外の構文を採る(&self) -> Option<&保証範囲の外の構文> {
        if let Self::保証範囲の外の構文である { 構文 } = self { Some(構文) } else { None }
    }

    /// 人が読む説明。
    pub fn 説明(&self) -> String {
        match self {
            Self::型引数である { 型引数名 } => format!("`{型引数名}` は定義の宣言が導入した型引数であり設計概念ではない"),
            Self::定義のモジュールパスを解決できなかった { 型名 } => format!("`{型名}` の定義をたどれずモジュールパスを空にした"),
            Self::役割の型引数に入れ子の型引数がある { 役割名 } => format!("`{役割名}` の型引数に入れ子の型引数があり保証範囲の外である"),
            Self::役割の型引数の数が合わない { 役割名, 取る数, 読めた数 } => format!("`{役割名}` は型引数を{取る数}個取るが{読めた数}個しか読めなかった"),
            Self::役割の値の右辺が役割の生成する呼び出しでない { 役割名 } => format!("`{役割名}` の値の右辺が `{役割名}::生成する(...)` の形でなく主語を決められない"),
            Self::役割に包まれた関数の引数がパスでない { 役割名 } => format!("`{役割名}::生成する` へ渡した引数がRustのパスとして読めない"),
            Self::役割に包まれた関数のパスの区分が2つでない { 役割名, 読めた区分の数 } => format!("`{役割名}` に包まれた関数のパスは所有する型とメソッドの2区分であるべきだが{読めた区分の数}区分である"),
            Self::役割に包まれた関数のパスが起点の予約語で始まる { 役割名, 先頭の区分 } => format!("`{役割名}` に包まれた関数のパスが `{先頭の区分}` で始まり所有する型の名前でない"),
            Self::役割に包まれた関数の所有者の実装が同じファイルに無い { 役割名, 所有者名 } => format!("`{役割名}` に包まれた関数の所有者 `{所有者名}` の `impl` の行が同じファイルに無い"),
            Self::エンティティの識別子の関連型が無い { 型名 } => format!("`{型名}` の `Mエンティティ` の実装に `type 識別子 =` の行が無い"),
            Self::役割の型自身の宣言である { 役割名 } => format!("`{役割名}` は関数の役割の型自身の宣言であり、包む関数ポインタからは関係を出さない"),
            Self::保証範囲の外の構文である { 構文 } => 構文.説明(),
        }
    }
}
