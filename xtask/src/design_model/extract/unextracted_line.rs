//! 抽出できなかった行とは、抽出の規則が当たる構文でありながら、抽出器がそこから設計関係を1件も組めなかったソースの行のことである。
//!
//! この型が在るのは、検査器が解析できなかった入力を黙って対象から外してはならないという規約のためである
//! (`.claude/global-reference/全プロジェクト共通CLAUDE.md`「検査器は解析できなかった入力を黙って対象から外してはならない」)。
//! 抽出の結末はこの一覧を件数として持ち、命題の検証の利用者が「関係が0件である」と「その行を読めなかった」を読み分けられるようにする。
//!
//! 黙って対象から外してよいのは、外す条件を書き下せる入力だけである。抽出器がそれとして扱うのは2つだけであり、
//! 設計の概念でないプリミティブの型(`u32`・`String` 等)と、役割の型自身の宣言と実装の行である。どちらも理由の選択肢を持たない。
//!
//! **理由は3つの区分のどれかへ属する。** 区分が要るのは、検証器が辺の不在を根拠にしてよいかが区分で決まるためである。
//! 識別子だけが未解決の行と、設計概念でないため明示して除外した行は、設計関係そのものは失われていない。
//! 設計関係そのものを抽出できなかった行だけが、グラフに在るはずの辺を欠く。区分を答える口をこの型が持つのは、
//! どの選択肢がどの区分かを知っているのが、その選択肢を作った抽出器の側だからである。

use std::path::{Path, PathBuf};

/// 抽出できなかった行の1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 抽出できなかった行 {
    pub パス: PathBuf,
    pub 行番号: usize, // 1始まり
    pub 理由: 抽出できなかった理由,
}

/// 抽出器がその行から設計関係を組めなかった理由。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 抽出できなかった理由 {
    /// フィールドの型が、その定義の宣言が導入した型引数の名前である。実在しない設計概念の節点を作らないために関係を出さない。
    型引数である { 型引数名: String },
    /// 型の定義をたどれず、節点のモジュールパスを空にした。節点そのものは落とさない。
    定義のモジュールパスを解決できなかった { 型名: String },
    /// 役割の型引数の中に入れ子の型引数(`<>`)があり、保証範囲の外である。
    役割の型引数に入れ子の型引数がある { 役割名: &'static str },
    /// 役割の型引数の数が、その役割が取る数と合わない。
    役割の型引数の数が合わない { 役割名: &'static str, 取る数: usize, 読めた数: usize },
    /// 役割の値に包まれた具体の関数のパスが読めず、関係の主語を決められない(戻り値の型・フィールドの型注釈・`= 何か.何か()` の形)。
    役割に包まれた関数のパスを読めない { 役割名: &'static str },
    /// `impl Mエンティティ for 型` の本体に `type 識別子 =` の行が無く、識別する関係の主語を決められない。
    エンティティの識別子の関連型が無い { 型名: String },
}

/// 抽出できなかった理由が属する区分。検証器が辺の不在を根拠にしてよいかをこの区分が決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 抽出できなかった理由の区分 {
    /// 識別子だけが未解決である。関係そのものは保存されており、節点のモジュールパスが空になっただけである。
    識別子だけ未解決である,
    /// 設計概念でないため明示して除外した。除外の条件を書き下せており、落ちた設計関係は無い。
    設計概念でないため明示して除外した,
    /// 本来あり得る設計関係そのものを抽出できなかった。グラフに在るはずの辺を欠く。
    設計関係そのものを抽出できなかった,
}

impl 抽出できなかった行 {
    /// パスと行番号と理由から1件を組む。
    pub fn 生成する(パス: &Path, 行番号: usize, 理由: 抽出できなかった理由) -> Self {
        Self {
            パス: パス.to_path_buf(), 行番号, 理由
        }
    }

    /// 人が読む1行の表記。報告がこの表記を並べる。
    pub fn 表記(&self) -> String {
        format!("{}:{}: {}", self.パス.display(), self.行番号, self.理由.説明())
    }
}

impl 抽出できなかった理由 {
    /// この理由が属する区分。
    ///
    /// `定義のモジュールパスを解決できなかった` を識別子だけ未解決であるとするのは、抽出器がその行から関係を組んだうえで
    /// 節点のモジュールパスを空にしているためである。辺はグラフへ入っており、触れた原子命題は
    /// `未決定の理由::型の定義のモジュールパスが未解決である` が別に止める。
    ///
    /// `型引数である` を設計概念でないため明示して除外したとするのは、型引数が実在する設計概念を指さないためである。
    /// その位置に設計関係は初めから無く、外す条件も書き下せている。
    ///
    /// 残る4つを設計関係そのものを抽出できなかったとするのは、どれも主語か目的語を決められずに関係を1件も組めていないためである。
    /// `役割に包まれた関数のパスを読めない` と `エンティティの識別子の関連型が無い` は主語を決められず、
    /// `役割の型引数に入れ子の型引数がある` と `役割の型引数の数が合わない` は目的語を決められない。
    /// どの場合も、本来あり得た辺がグラフへ入らない。
    pub const fn 区分(&self) -> 抽出できなかった理由の区分 {
        match self {
            Self::定義のモジュールパスを解決できなかった { .. } => 抽出できなかった理由の区分::識別子だけ未解決である,
            Self::型引数である { .. } => 抽出できなかった理由の区分::設計概念でないため明示して除外した,
            Self::役割の型引数に入れ子の型引数がある { .. } | Self::役割の型引数の数が合わない { .. } | Self::役割に包まれた関数のパスを読めない { .. } | Self::エンティティの識別子の関連型が無い { .. } => {
                抽出できなかった理由の区分::設計関係そのものを抽出できなかった
            }
        }
    }

    /// 選択肢の種別の呼び名。運ぶ値(型名・役割名)を含めないのは、この呼び名が同じ種別を束ねた件数の見出しになるためである。
    pub const fn 種別の呼び名(&self) -> &'static str {
        match self {
            Self::型引数である { .. } => "定義の宣言が導入した型引数である",
            Self::定義のモジュールパスを解決できなかった { .. } => "型の定義をたどれずモジュールパスを空にした",
            Self::役割の型引数に入れ子の型引数がある { .. } => "役割の型引数に入れ子の型引数がある",
            Self::役割の型引数の数が合わない { .. } => "役割の型引数の数が合わない",
            Self::役割に包まれた関数のパスを読めない { .. } => "役割に包まれた関数のパスを読めない",
            Self::エンティティの識別子の関連型が無い { .. } => "エンティティの識別子の関連型が無い",
        }
    }

    /// 人が読む説明。
    pub fn 説明(&self) -> String {
        match self {
            Self::型引数である { 型引数名 } => format!("`{型引数名}` は定義の宣言が導入した型引数であり設計概念ではない"),
            Self::定義のモジュールパスを解決できなかった { 型名 } => format!("`{型名}` の定義をたどれずモジュールパスを空にした"),
            Self::役割の型引数に入れ子の型引数がある { 役割名 } => format!("`{役割名}` の型引数に入れ子の型引数があり保証範囲の外である"),
            Self::役割の型引数の数が合わない { 役割名, 取る数, 読めた数 } => format!("`{役割名}` は型引数を{取る数}個取るが{読めた数}個しか読めなかった"),
            Self::役割に包まれた関数のパスを読めない { 役割名 } => format!("`{役割名}` の値に包まれた関数のパスが読めず主語を決められない"),
            Self::エンティティの識別子の関連型が無い { 型名 } => format!("`{型名}` の `Mエンティティ` の実装に `type 識別子 =` の行が無い"),
        }
    }
}
