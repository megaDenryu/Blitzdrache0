//! 抽出対象のソース群とは、抽出の5つの規則が共通に読むソースの集まりと、そこから型の同一性を答える問い口のことである。
//!
//! 構文の読み取りと型の定義の探索は `conform::design_ontology` の構文解析器を借り、複製を作らない。同じ構文を2箇所で読むと、
//! 検査が見る型の同一性と抽出が作る節点の同一性が食い違い、検査を通ったコードについて抽出が別の型を指す事故が起きる。
//!
//! 全規則は適用範囲のクレートの入口から辿れる本番のソースだけを見る。

use std::path::{Component, Path, PathBuf};

use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use super::本番のソース::本番のソース;
use super::表記が名指す型::表記が名指す型;
use crate::conform::design_ontology::module_path::モジュールパス;
use crate::conform::design_ontology::syntax_checker::クレート構文検査;
use crate::conform::design_ontology::type_definition::{型の在り処の問い, 定義ブロックの結果};
use crate::conform::error::規約検査の破れ;
use crate::design_model::設計概念の識別子;
use crate::file_scan;

/// 抽出が読むソースの集まり。構文解析器を保持し、行の一覧と型の同一性をメソッドで答える。
pub struct 抽出対象のソース群 {
    構文検査: クレート構文検査,
    本番の選別の欠落: Vec<抽出できなかった行>,
}

impl 抽出対象のソース群 {
    /// `crates` 配下の各クレートの `src` の下の全 `.rs` を走査して組む。
    pub fn crates配下から走査して生成する() -> Result<Self, 規約検査の破れ> {
        let パス一覧 = file_scan::対象ファイル一覧を集める(&["crates"], &["rs"])?;
        let mut 原文一覧 = Vec::new();
        for パス in パス一覧.into_iter().filter(|パス| srcの下か(パス)) {
            let 内容 = std::fs::read_to_string(&パス).map_err(|誤り| 規約検査の破れ::ファイルを読めなかった(&パス, 誤り))?;
            原文一覧.push((パス, 内容));
        }
        Ok(Self::原文一覧から生成する(原文一覧))
    }

    /// パスと原文の対の一覧から組む。回帰試験が、リポジトリの実物に依存せず構文を組んで与えるための口である。
    pub fn 原文一覧から生成する(原文一覧: Vec<(PathBuf, String)>) -> Self {
        let 入口一覧 = 原文一覧
            .iter()
            .filter(|(パス, _)| パス.parent().and_then(Path::file_name).is_some_and(|名前| 名前 == "src"))
            .filter(|(パス, _)| matches!(パス.file_stem().and_then(|名前| 名前.to_str()), Some("lib" | "main")))
            .map(|(パス, _)| パス.clone())
            .collect();
        Self::入口を指定して生成する(原文一覧, 入口一覧)
    }

    pub(super) fn 入口を指定して生成する(原文一覧: Vec<(PathBuf, String)>, 入口一覧: Vec<PathBuf>) -> Self {
        let 本番 = 本番のソース::入口から集める(原文一覧, 入口一覧);
        Self {
            構文検査: クレート構文検査::生成する(本番.行一覧),
            本番の選別の欠落: 本番.欠落一覧,
        }
    }

    pub fn 本番の選別の欠落一覧(&self) -> &[抽出できなかった行] {
        &self.本番の選別の欠落
    }

    /// 借りている構文解析器。トレイトの実装の行の集めと型の定義ブロックの探索がここを通る。
    pub fn 構文検査(&self) -> &クレート構文検査 {
        &self.構文検査
    }

    /// 走査した全ファイルのパスとコードだけの行の一覧。
    pub fn ファイル一覧(&self) -> &[(PathBuf, Vec<String>)] {
        self.構文検査.ソース一覧()
    }

    /// そのファイルのコードだけの行の一覧。走査していないパスなら無しである。
    pub fn 行一覧(&self, パス: &Path) -> Option<&[String]> {
        self.ファイル一覧().iter().find(|(在るパス, _)| 在るパス == パス).map(|(_, 行一覧)| 行一覧.as_slice())
    }

    /// そのファイルのモジュールパスの表記。`crates` の下に無いファイルは空である。
    pub fn ファイルのモジュールパス(&self, パス: &Path) -> String {
        モジュールパス::ファイルのパスから求める(パス).表記().to_string()
    }

    /// 型の名前から節点の識別子を組む。定義をたどれればそのモジュールパスを、たどれなければ空を持たせ、たどれなかった1件を数える。
    /// モジュールパスが空であることが未解決を表す取り決めであり、節点そのものは落とさない。落とすと「関係が無い」と読まれ偽の反証が出る。
    pub fn 型の識別子を求める(&self, 問い: 型の在り処の問い<'_>) -> (設計概念の識別子, Option<抽出できなかった行>) {
        match 問い.型の定義を探す(self.ファイル一覧()) {
            定義ブロックの結果::見つかった { パス, .. } => (設計概念の識別子::Rustの項目として生成する(&self.ファイルのモジュールパス(&パス), 問い.型名), None),
            _ => {
                let 理由 = 抽出できなかった理由::定義のモジュールパスを解決できなかった { 型名: 問い.型名.to_string() };
                (設計概念の識別子::Rustの項目として生成する("", 問い.型名), Some(抽出できなかった行::生成する(問い.参照元のパス, 問い.参照元の行番号, 理由)))
            }
        }
    }

    /// 型の表記が名指す型から節点の識別子を組む。定義は座標系を落とした名前で探し、識別子の名前には座標系を含める。
    /// 定義をたどれないときの扱いは `型の識別子を求める` と同じであり、`blitz_math` のフレーム型はたどれずモジュールパスが空になる。
    pub fn 名指す型の識別子を求める(&self, 問い: 名指す型の在り処の問い<'_>) -> (設計概念の識別子, Option<抽出できなかった行>) {
        let (識別子, 解決できなかった行) = self.型の識別子を求める(問い.型の在り処の問いにする());
        (設計概念の識別子::Rustの項目として生成する(&識別子.モジュールパス, &問い.名指す型.同一性の名前()), 解決できなかった行)
    }
}

/// 型の表記が名指す型の定義がどこに在るかの問い。`型の在り処の問い` と同じく、名指す型と、それを書いている行の位置を1つに束ねる。
/// 型名の文字列でなく名指す型を持つのは、定義を探す名前と識別子に使う同一性の名前の2つを、同じ1つの表記から導くためである。
pub struct 名指す型の在り処の問い<'a> {
    pub 名指す型: &'a 表記が名指す型,
    pub 参照元のパス: &'a Path,
    pub 参照元の行番号: usize,
}

impl 名指す型の在り処の問い<'_> {
    // 定義は座標系を落とした名前で探すため、型名には定義を探す名前を渡す。
    fn 型の在り処の問いにする(&self) -> 型の在り処の問い<'_> {
        型の在り処の問い {
            型名: self.名指す型.定義を探す名前(),
            参照元のパス: self.参照元のパス,
            参照元の行番号: self.参照元の行番号,
        }
    }
}

fn srcの下か(パス: &Path) -> bool {
    パス.components().any(|部品| matches!(部品, Component::Normal(名前) if 名前 == "src"))
}
