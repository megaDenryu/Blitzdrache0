//! 抽出の規則1: 上位トレイトの宣言から `下位型である` を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのはトレイトの節点と `下位型である` の関係を持つ成果である。
//!
//! 対象は設計解釈マーカーの正本(`crates/blitz_design/src/marker.rs`)の `trait` の宣言と、他のファイルで
//! 設計解釈マーカーを上位トレイトに持つ `trait` の宣言である。後者へ広げるのは、ドメインが足した役割
//! (`blitz_esca` の遷移の役割等)が共通のマーカーの下位型であることを、グラフの経路として繋ぐためである。
//! `Clone`・`Eq`・`Hash`・`PartialEq`・`std::error::Error` のような標準のトレイトも目的語として出す。
//! 出さないと `M値オブジェクト` の `PartialEq` の要求がグラフから消え、法則を書く力が落ちる。

use super::marker_concept::{設計解釈マーカーの名前か, 設計解釈マーカーの識別子};
use super::outcome::抽出の成果;
use super::source_group::抽出対象のソース群;
use super::trait_declaration::トレイトの宣言を読む;
use crate::design_model::concept::{設計概念, 設計概念の種類, 設計概念の識別子};
use crate::design_model::relation::{抽出の出どころ, 抽出元の構文, 設計関係, 設計関係の種類};

pub fn 上位トレイトの宣言から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧() {
        let 正本のファイルか = パス.ends_with("blitz_design/src/marker.rs");
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        for (添字, 行) in 行一覧.iter().enumerate() {
            let Some(宣言) = トレイトの宣言を読む(行) else {
                continue;
            };
            let マーカーを継いでいるか = 宣言.上位トレイト一覧.iter().any(|上位| 設計解釈マーカーの名前か(&上位の名前(上位)));
            if !正本のファイルか && !マーカーを継いでいるか {
                continue;
            }
            let 主語 = 設計概念の識別子::生成する(&モジュールパス, &宣言.名前);
            成果.概念一覧.push(トレイトの節点(主語.clone()));
            for 上位 in &宣言.上位トレイト一覧 {
                let 目的語 = 上位トレイトの識別子(上位);
                成果.概念一覧.push(トレイトの節点(目的語.clone()));
                成果.関係一覧.push(設計関係 {
                    主語: 主語.clone(),
                    種類: 設計関係の種類::下位型である,
                    目的語,
                    出どころ: 抽出の出どころ {
                        パス: パス.clone(),
                        行番号: 添字 + 1,
                        構文: 抽出元の構文::上位トレイトの宣言,
                    },
                });
            }
        }
    }
    成果
}

fn トレイトの節点(識別子: 設計概念の識別子) -> 設計概念 {
    設計概念 {
        識別子, 種類: 設計概念の種類::トレイト
    }
}

// 上位トレイトの表記の末尾の名前(`std::error::Error` なら `Error`)。
fn 上位の名前(表記: &str) -> String {
    表記.rsplit("::").next().unwrap_or_default().trim().to_string()
}

// 上位トレイトの表記から節点の識別子を組む。マーカーは正本のモジュールパスへ、修飾を書いたものはその修飾へ、無修飾の標準のトレイトは空のモジュールパスへ落とす。
fn 上位トレイトの識別子(表記: &str) -> 設計概念の識別子 {
    let 名前 = 上位の名前(表記);
    if 設計解釈マーカーの名前か(&名前) {
        return 設計解釈マーカーの識別子(&名前);
    }
    match 表記.trim().rsplit_once("::") {
        Some((修飾, _)) => 設計概念の識別子::生成する(修飾.trim(), &名前),
        None => 設計概念の識別子::生成する("", &名前),
    }
}
