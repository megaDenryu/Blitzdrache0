//! 抽出の規則1: 上位トレイトの宣言から、上位トレイトの宣言の事実を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのはトレイトの節点と、上位トレイトの宣言の事実を持つ成果である。設計関係は出さない。
//! この事実は分類どうしの公理であり、グラフの組み立てが型の分類を閉じるときに読む。
//!
//! 対象は設計解釈マーカーの正本(`crates/blitz_design/src/marker.rs`)の `trait` の宣言と、他のファイルで
//! 設計解釈マーカーを上位トレイトに持つ `trait` の宣言である。後者へ広げるのは、ドメインが足した役割
//! (`blitz_esca` の遷移の役割等)が共通のマーカーの一種であることを、公理として同じ形で持つためである。
//! `Clone`・`Eq`・`Hash`・`PartialEq`・`std::error::Error` のような標準のトレイトを上位に持つ宣言も、書いてあるとおりの事実として出す。
//! 上位トレイトの宣言はコンパイラが知っている形の事実であり、抽出器はどれを分類に使うかを選ばない。
//! 分類は設計解釈マーカーの集合であるため、グラフの組み立てが閉包を設計解釈マーカーどうしの宣言だけで辿り、標準のトレイトを分類へ入れない。
//!
//! 保証範囲の外の宣言は、正本のファイルかどうかを問わず `抽出できなかった行` として数える。読めない宣言は上位トレイトを読めず、
//! 設計解釈マーカーを継いでいるかを判定できないため、対象の外だと言い切れないためである。

use super::marker_concept::{設計解釈マーカーの名前か, 設計解釈マーカーの識別子};
use super::outcome::抽出の成果;
use super::source_group::抽出対象のソース群;
use super::trait_declaration::{トレイトの宣言の読み取り, トレイトの宣言を読む};
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::conform::design_ontology::marker_canonical_file::設計解釈マーカーの正本のファイルか;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};
use blitz_design_verification::{上位トレイトの宣言の事実, 事実の出どころ};

pub fn 上位トレイトの宣言から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧() {
        let 正本のファイルか = 設計解釈マーカーの正本のファイルか(パス);
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        for (添字, 行) in 行一覧.iter().enumerate() {
            let 宣言 = match トレイトの宣言を読む(行) {
                トレイトの宣言の読み取り::宣言でない => continue,
                トレイトの宣言の読み取り::保証範囲の外(構文) => {
                    let 理由 = 抽出できなかった理由::保証範囲の外の構文である { 構文 };
                    成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(パス, 添字 + 1, 理由));
                    continue;
                }
                トレイトの宣言の読み取り::読めた(宣言) => 宣言,
            };
            let マーカーを継いでいるか = 宣言.上位トレイト一覧.iter().any(|上位| 設計解釈マーカーの名前か(&上位の名前(上位)));
            if !正本のファイルか && !マーカーを継いでいるか {
                continue;
            }
            let 宣言したトレイトの節点 = トレイトの節点(設計概念の識別子::Rustの項目として生成する(&モジュールパス, &宣言.名前));
            let トレイト = 宣言したトレイトの節点.参照を組む();
            成果.概念一覧.push(宣言したトレイトの節点);
            for 上位 in &宣言.上位トレイト一覧 {
                let 上位の節点 = トレイトの節点(上位トレイトの識別子(上位));
                成果.上位トレイトの宣言一覧.push(上位トレイトの宣言の事実 {
                    トレイト: トレイト.clone(),
                    上位トレイト: 上位の節点.参照を組む(),
                    出どころ: 事実の出どころ { パス: パス.clone(), 行番号: 添字 + 1 },
                });
                成果.概念一覧.push(上位の節点);
            }
        }
    }
    成果
}

fn トレイトの節点(識別子: 設計概念の識別子) -> 設計概念 {
    設計概念::Rustの項目として生成する(識別子, Rustの項目の種類::トレイト)
}

// 上位トレイトの表記の末尾の名前(`std::error::Error` なら `Error`)。
fn 上位の名前(表記: &str) -> String {
    表記.rsplit("::").next().unwrap_or_default().trim().to_string()
}

// 上位トレイトの表記から節点の識別子を組む。マーカーは正本のモジュールパスへ、修飾を書いたものはその修飾へ、無修飾の標準のトレイトは空のモジュールパスへ落とす。
fn 上位トレイトの識別子(表記: &str) -> 設計概念の識別子 {
    let 名前 = 上位の名前(表記);
    if 設計解釈マーカーの名前か(&名前) {
        return 設計解釈マーカーの識別子(&名前);
    }
    match 表記.trim().rsplit_once("::") {
        Some((修飾, _)) => 設計概念の識別子::Rustの項目として生成する(修飾.trim(), &名前),
        None => 設計概念の識別子::Rustの項目として生成する("", &名前),
    }
}
