//! 型の表記から設計概念の名前を採る正規化。依存を持たない純粋な関数だけを置く。
//! 受け取るのはソースに書かれた型の表記、返すのはその表記が名指す型か、設計概念ではないという答えか、保証範囲の外であるという答えである。
//!
//! 外側の包み(`Vec<T>`・`Option<T>`・`Box<T>`)を剥がして中身を採るのは、包みが設計上の関係を変えないためである。
//! `Vec<旅行者の出来事>` を保持することは旅行者の出来事を保持することであり、`Vec` という節点を作ってもグラフは何も言わない。
//! プリミティブを設計概念にしないのは、それが設計の概念ではなく数値と文字の表現だからである。この2つが、抽出器が黙って対象から外してよいと書き下せる条件である。
//!
//! 剥がす包みでないジェネリクスのうち、座標系を型引数に取る `blitz_math` のフレーム型(`変位<ワールド>` 等)だけは、型引数を含む表記の全体を1つの型として採る。
//! どの型をそう扱うかは `表記が名指す型` が一覧で持ち、型引数の形からは決めない。
//!
//! 残る表記(配列・タプル・関数ポインタ・一覧に無いジェネリクス・パスの修飾が付いた表記)は、黙って読み飛ばさずに保証範囲の外と答える。
//! パスの修飾を保証範囲の外にするのは、修飾を落として名前だけで定義を探すと、同じ名前の別の定義へ当たりうるためである。

use crate::conform::design_ontology::line_matching::先頭の識別子;

use super::out_of_range_syntax::保証範囲の外の構文;
use super::表記が名指す型::{フレーム型, 表記が名指す型};

/// 設計概念にしないプリミティブの型。数値と真偽と文字列であり、どれもドメインの概念を名乗らない。
const プリミティブ一覧: [&str; 11] = ["u8", "u32", "u64", "usize", "i32", "i64", "f32", "f64", "bool", "String", "str"];

/// 外側から剥がす包み。剥がしても設計上の関係が変わらないものだけを並べる。
const 剥がす包み一覧: [&str; 3] = ["Vec", "Option", "Box"];

/// 型の表記を読んだ答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 型の表記の読み取り {
    /// 設計概念である型を名指せた。
    設計概念である(表記が名指す型),
    /// 設計の概念でないプリミティブであり、明示して対象から外す。
    プリミティブである,
    /// 抽出器の保証範囲の外の表記である。
    保証範囲の外(保証範囲の外の構文),
}

/// 型の表記から設計概念の名前を採る。
pub fn 型の表記を読む(表記: &str) -> 型の表記の読み取り {
    match 包みを剥がす(表記, 参照を落とす(表記)) {
        Err(構文) => 型の表記の読み取り::保証範囲の外(構文),
        Ok(芯) => match 芯.split_once('<') {
            None => 名前として読む(表記, 芯),
            Some((前, 残り)) => 総称の型として読む(表記, 前.trim(), 残り),
        },
    }
}

// `Vec<T>`・`Option<T>`・`Box<T>` を、包みでなくなるまで剥がす。剥がす包みでないジェネリクスは芯としてそのまま返し、閉じない `<` は保証範囲の外である。
fn 包みを剥がす<'a>(元の表記: &str, 表記: &'a str) -> Result<&'a str, 保証範囲の外の構文> {
    let mut 芯 = 表記;
    loop {
        let Some((前, 残り)) = 芯.split_once('<') else {
            return Ok(芯);
        };
        if !剥がす包み一覧.contains(&前.rsplit("::").next().unwrap_or_default().trim()) {
            return Ok(芯);
        }
        let Some((中身, _)) = 残り.rsplit_once('>') else {
            return Err(保証範囲の外の構文::型の表記がRustのパスでない { 表記: 元の表記.trim().to_string() });
        };
        芯 = 参照を落とす(中身);
    }
}

// 包みを剥がした芯のうち型引数を持つものを、一覧に載ったフレーム型として読む。載っていない型、パスの修飾、読めない型引数は保証範囲の外である。
fn 総称の型として読む(元の表記: &str, 前: &str, 残り: &str) -> 型の表記の読み取り {
    let 表記 = 元の表記.trim().to_string();
    let Some(型) = フレーム型::名前から探す(前.rsplit("::").next().unwrap_or_default().trim()) else {
        return 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記が剥がす包みでないジェネリクスである { 表記 });
    };
    if 前.contains("::") {
        return 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記にパスの修飾がある { 表記 });
    }
    let Some(型引数の並び) = 残り.trim_end().strip_suffix('>') else {
        return 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記がRustのパスでない { 表記 });
    };
    match 表記が名指す型::フレーム型として読む(型, 型引数の並び) {
        Some(名指す型) => 型の表記の読み取り::設計概念である(名指す型),
        None => 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::フレーム型の型引数が座標系の名前の並びでない { 表記 }),
    }
}

// 包みを剥がした芯を、設計概念の名前として読む。パスの修飾が付いた表記と、識別子として読めない表記は保証範囲の外である。
fn 名前として読む(元の表記: &str, 芯: &str) -> 型の表記の読み取り {
    let 名前 = 芯.trim();
    if 名前.contains("::") {
        return 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記にパスの修飾がある { 表記: 元の表記.trim().to_string() });
    }
    if 名前.is_empty() || 先頭の識別子(名前) != 名前 {
        return 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記がRustのパスでない { 表記: 元の表記.trim().to_string() });
    }
    if プリミティブ一覧.contains(&名前) {
        return 型の表記の読み取り::プリミティブである;
    }
    型の表記の読み取り::設計概念である(表記が名指す型::名前から生成する(名前))
}

// 先頭の参照と寿命と `mut` を落とす。落とせるものが無くなるまで繰り返す。
fn 参照を落とす(表記: &str) -> &str {
    let mut 残り = 表記.trim();
    loop {
        let 落とした = 残り.strip_prefix('&').unwrap_or(残り).trim_start();
        let 落とした = 寿命を落とす(落とした);
        let 落とした = 落とした.strip_prefix("mut ").unwrap_or(落とした).trim_start();
        if 落とした == 残り {
            return 残り;
        }
        残り = 落とした;
    }
}

// `&'a 型` の `'a ` を落とす。寿命の名前の後ろに空白が無ければ、寿命ではないものとして何も落とさない。
fn 寿命を落とす(表記: &str) -> &str {
    let Some(残り) = 表記.strip_prefix('\'') else {
        return 表記;
    };
    残り.split_once(char::is_whitespace).map_or(表記, |(_, 後ろ)| 後ろ.trim_start())
}
