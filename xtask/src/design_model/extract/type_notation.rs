//! 型の表記から設計概念の名前を採る正規化。依存を持たない純粋な関数だけを置く。
//! 受け取るのはソースに書かれた型の表記、返すのはその表記が指す設計概念の名前か、設計概念ではないという答えである。
//!
//! 外側の包み(`Vec<T>`・`Option<T>`・`Box<T>`)を剥がして中身を採るのは、包みが設計上の関係を変えないためである。
//! `Vec<旅行者の出来事>` を保持することは旅行者の出来事を保持することであり、`Vec` という節点を作ってもグラフは何も言わない。
//! プリミティブを設計概念にしないのは、それが設計の概念ではなく数値と文字の表現だからである。この2つが、抽出器が黙って対象から外してよい条件である。

/// 設計概念にしないプリミティブの型。数値と真偽と文字列であり、どれもドメインの概念を名乗らない。
const プリミティブ一覧: [&str; 11] = ["u8", "u32", "u64", "usize", "i32", "i64", "f32", "f64", "bool", "String", "str"];

/// 外側の包みを剥がした表記。
const 剥がす包み一覧: [&str; 3] = ["Vec", "Option", "Box"];

/// 型の表記から設計概念の名前を採る。プリミティブなら無しである。
pub fn 設計概念の名前を採る(表記: &str) -> Option<String> {
    let 名前 = 先頭の型名を採る(表記);
    (!名前.is_empty() && !プリミティブ一覧.contains(&名前.as_str())).then_some(名前)
}

/// 包みを剥がし、パスの修飾と型引数を落として、先頭の型の名前を採る。空の表記からは空を返す。
pub fn 先頭の型名を採る(表記: &str) -> String {
    let 芯 = 包みを剥がす(表記.trim().trim_start_matches(['&', ' ']).trim_start_matches("mut ").trim());
    let 型引数の前 = 芯.split_once('<').map_or(芯, |(前, _)| 前);
    型引数の前.rsplit("::").next().unwrap_or_default().trim().to_string()
}

// `Vec<T>`・`Option<T>`・`Box<T>` を、包みでなくなるまで剥がす。剥がした中身の先頭の参照と空白も落とす。
fn 包みを剥がす(表記: &str) -> &str {
    let mut 芯 = 表記;
    loop {
        let Some((前, 残り)) = 芯.split_once('<') else {
            return 芯;
        };
        if !剥がす包み一覧.contains(&前.rsplit("::").next().unwrap_or_default().trim()) {
            return 芯;
        }
        芯 = 残り.rsplit_once('>').map_or(残り, |(中身, _)| 中身).trim().trim_start_matches(['&', ' ']).trim();
    }
}
