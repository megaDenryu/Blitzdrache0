//! 関数の役割の使用箇所を読む工程。受け取るのはコードだけの1行、返すのは役割と包まれた関数のパスと型引数の表記の一覧、または読めなかった理由である。
//!
//! 1つのファイルのコードだけの行の一覧を保持するのは、包まれた関数のパスの受理の条件4(所有者を対象にする `impl` の行が同じファイルに在ること)が
//! その一覧を見るためである。1行だけを受け取る自由関数にすると、行ごとの呼び出しに同じ一覧を持参させることになる。
//!
//! 役割の型自身の宣言と実装の行(`pub struct M射影関数<状態: M状態, ...>`・`impl<...> M遷移関数<...>`)は使用箇所ではないため対象外にする。
//! これは書き下せる対象外の条件であり、解析に失敗したことを対象外の条件にしているのではない。
//! 保証範囲: 使用箇所が1行に収まっていることと、型引数の中に入れ子の `<>` が無いことを前提にする。入れ子は読めなかった理由として数える。

use super::role::関数の役割;
use super::unextracted_line::抽出できなかった理由;
use super::wrapped_function_path::{役割に包まれた関数のパス, 役割に包まれた関数のパスの読み取り};

/// 1行から役割の使用箇所を読んだ結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 役割の使用箇所を読んだ結果 {
    使用箇所でない,
    読めた {
        役割: 関数の役割,
        包まれた関数のパス: 役割に包まれた関数のパス,
        型引数の表記一覧: Vec<String>,
    },
    読めなかった(抽出できなかった理由),
}

/// 1つのファイルの中で役割の使用箇所を読む工程。そのファイルのコードだけの行の一覧を保持する。
pub struct 役割の使用箇所の読み取り<'a> {
    同じファイルの行一覧: &'a [String],
}

impl<'a> 役割の使用箇所の読み取り<'a> {
    pub const fn 生成する(同じファイルの行一覧: &'a [String]) -> Self {
        Self { 同じファイルの行一覧 }
    }

    /// その行から役割の使用箇所を読む。
    pub fn 行から読む(&self, 行: &str) -> 役割の使用箇所を読んだ結果 {
        if 役割自身の宣言の行か(行) {
            return 役割の使用箇所を読んだ結果::使用箇所でない;
        }
        let Some((役割, 位置)) = 関数の役割::全部の一覧().into_iter().find_map(|役割| 行.find(&format!("{}<", 役割.名前())).map(|位置| (役割, 位置))) else {
            return 役割の使用箇所を読んだ結果::使用箇所でない;
        };
        let 型引数の始まり = 位置 + 役割.名前().len() + 1;
        let Some((型引数部, 型引数より後ろ)) = 行[型引数の始まり..].split_once('>').filter(|(中身, _)| !中身.contains('<')) else {
            return 役割の使用箇所を読んだ結果::読めなかった(抽出できなかった理由::役割の型引数に入れ子の型引数がある { 役割名: 役割.名前() });
        };
        let 型引数の表記一覧: Vec<String> = 型引数部.split(',').map(str::trim).filter(|表記| !表記.is_empty()).map(str::to_string).collect();
        if 型引数の表記一覧.len() != 役割.型引数の数() {
            return 役割の使用箇所を読んだ結果::読めなかった(抽出できなかった理由::役割の型引数の数が合わない {
                役割名: 役割.名前(),
                取る数: 役割.型引数の数(),
                読めた数: 型引数の表記一覧.len(),
            });
        }
        match 役割に包まれた関数のパスの読み取り::生成する(役割, self.同じファイルの行一覧).型引数より後ろから読む(型引数より後ろ) {
            Ok(包まれた関数のパス) => 役割の使用箇所を読んだ結果::読めた {
                役割, 包まれた関数のパス, 型引数の表記一覧
            },
            Err(理由) => 役割の使用箇所を読んだ結果::読めなかった(理由),
        }
    }
}

// 役割の型自身を宣言または実装する行か。使用箇所ではないため対象外にする。
fn 役割自身の宣言の行か(行: &str) -> bool {
    let mut 残り = 行.trim();
    for 前置き in ["pub(crate) ", "pub(super) ", "pub "] {
        残り = 残り.strip_prefix(前置き).unwrap_or(残り).trim_start();
    }
    ["struct ", "enum ", "trait ", "type ", "impl"].iter().any(|前置き| 残り.starts_with(前置き))
}
