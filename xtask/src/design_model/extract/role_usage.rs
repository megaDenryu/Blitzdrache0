//! 関数の役割の使用箇所を読む工程。依存を持たない純粋な関数だけを置く。受け取るのはコードだけの1行、返すのは役割と宣言の名前と型引数の表記の一覧、または読めなかった理由である。
//!
//! 役割の型自身の宣言と実装の行(`pub struct M射影関数<状態: M状態, ...>`・`impl<...> M遷移関数<...>`)は使用箇所ではないため対象外にする。
//! これは書き下せる対象外の条件であり、解析に失敗したことを対象外の条件にしているのではない。
//! 保証範囲: 使用箇所が1行に収まっていることと、型引数の中に入れ子の `<>` が無いことを前提にする。入れ子は読めなかった理由として数える。

use super::role::関数の役割;
use crate::conform::design_ontology::line_matching::先頭の識別子;

/// 1行から役割の使用箇所を読んだ結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 役割の使用箇所を読んだ結果 {
    使用箇所でない,
    読めた { 役割: 関数の役割, 宣言の名前: String, 型引数の表記一覧: Vec<String> },
    型引数に入れ子の型引数がある(関数の役割),
    型引数の数が合わない { 役割: 関数の役割, 読めた数: usize },
    宣言の名前を読めない(関数の役割),
}

/// その行から役割の使用箇所を読む。
pub fn 役割の使用箇所を読む(行: &str) -> 役割の使用箇所を読んだ結果 {
    if 役割自身の宣言の行か(行) {
        return 役割の使用箇所を読んだ結果::使用箇所でない;
    }
    let Some((役割, 位置)) = 関数の役割::全部の一覧().into_iter().find_map(|役割| 行.find(&format!("{}<", 役割.名前())).map(|位置| (役割, 位置))) else {
        return 役割の使用箇所を読んだ結果::使用箇所でない;
    };
    let 型引数の始まり = 位置 + 役割.名前().len() + 1;
    let Some(型引数部) = 行[型引数の始まり..].split_once('>').map(|(中身, _)| 中身).filter(|中身| !中身.contains('<')) else {
        return 役割の使用箇所を読んだ結果::型引数に入れ子の型引数がある(役割);
    };
    let 型引数の表記一覧: Vec<String> = 型引数部.split(',').map(str::trim).filter(|表記| !表記.is_empty()).map(str::to_string).collect();
    if 型引数の表記一覧.len() != 役割.型引数の数() {
        return 役割の使用箇所を読んだ結果::型引数の数が合わない {
            役割, 読めた数: 型引数の表記一覧.len()
        };
    }
    match 宣言の名前を読む(&行[..位置]) {
        Some(宣言の名前) => 役割の使用箇所を読んだ結果::読めた {
            役割, 宣言の名前, 型引数の表記一覧
        },
        None => 役割の使用箇所を読んだ結果::宣言の名前を読めない(役割),
    }
}

// 役割の型自身を宣言または実装する行か。使用箇所ではないため対象外にする。
fn 役割自身の宣言の行か(行: &str) -> bool {
    let mut 残り = 行.trim();
    for 前置き in ["pub(crate) ", "pub(super) ", "pub "] {
        残り = 残り.strip_prefix(前置き).unwrap_or(残り).trim_start();
    }
    ["struct ", "enum ", "trait ", "type ", "impl"].iter().any(|前置き| 残り.starts_with(前置き))
}

// 役割の表記より前の部分から、その役割の値を持つ宣言の名前を読む。`名前:` の形を先に見て、無ければ `fn 名前(...) -> ` の形を見る。`_` は名前ではない。
fn 宣言の名前を読む(役割の前: &str) -> Option<String> {
    let 型注釈の名前 = 役割の前.rsplit_once(':').and_then(|(左, _)| 妥当な識別子(左.split_whitespace().next_back()?));
    型注釈の名前.or_else(|| {
        let 戻り値の位置に在るか = 役割の前.contains("->");
        let 関数名 = 役割の前.split_once("fn ").map(|(_, 後ろ)| 先頭の識別子(後ろ.trim_start()))?;
        (戻り値の位置に在るか).then_some(()).and_then(|()| 妥当な識別子(&関数名))
    })
}

fn 妥当な識別子(表記: &str) -> Option<String> {
    let 表記 = 表記.trim();
    (表記 != "_" && !表記.is_empty() && 先頭の識別子(表記) == 表記).then(|| 表記.to_string())
}
