//! 関数の役割の使用箇所を読む工程。受け取るのはコードだけの1行、返すのは役割と包まれた関数のパスと型引数の表記の一覧、または読めなかった理由である。
//!
//! 1つのファイルのコードだけの行の一覧を保持するのは、包まれた関数のパスの受理の条件4(所有者を対象にする `impl` の行が同じファイルに在ること)が
//! その一覧を見るためである。1行だけを受け取る自由関数にすると、行ごとの呼び出しに同じ一覧を持参させることになる。
//!
//! 役割の型自身の宣言と実装の行(`pub struct M射影関数<状態: M状態, ...>`・`impl<...> M遷移関数<...>`)は使用箇所ではないため対象外にする。
//! これは書き下せる対象外の条件であり、解析に失敗したことを対象外の条件にしているのではない。
//! 保証範囲: 使用箇所が1行に収まっていることを前提にする。型引数の終わりは `<` と `>` の深さを数えて決め、型引数の区切りは
//! 入れ子の深さを数える `positional_types` の関数で決める。型引数の中の `変位<ワールド>` や `Vec<X>` を読めるようにするためであり、
//! 各表記を設計概念として読めるかは、保持する関係と同じ `型の表記を読む` が決める。関数ポインタの戻り値の矢印 `->` の `>` は
//! 深さに数えない(`positional_types` と同じ規則である)。型引数を区切れない行は、黙って読み飛ばさずに保証範囲の外の構文として数え、
//! 理由を2つに分ける。`<` に対応する `>` が同じ行に無い行は、その事実を名指す理由で数え、閉じた型引数の中の深さが合わない行は、
//! 型引数の表記がRustのパスとして読めない理由で数える。

use super::out_of_range_syntax::保証範囲の外の構文;
use super::positional_types::{位置で並べた型の一覧, 戻り値の矢印の不等号か};
use super::role::関数の役割;
use super::unextracted_line::抽出できなかった理由;
use super::wrapped_function_path::{役割に包まれた関数のパス, 役割に包まれた関数のパスを読む工程};

/// 1行から役割の使用箇所を読んだ結果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 役割の使用箇所を読んだ結果 {
    使用箇所でない,
    読めた {
        役割: 関数の役割,
        包まれた関数のパス: 役割に包まれた関数のパス,
        型引数の表記一覧: Vec<String>,
    },
    読めなかった(抽出できなかった理由),
}

/// 1つのファイルの中で役割の使用箇所を読む工程。そのファイルのコードだけの行の一覧を保持する。
pub struct 役割の使用箇所を読む工程<'a> {
    同じファイルの行一覧: &'a [String],
}

impl<'a> 役割の使用箇所を読む工程<'a> {
    pub const fn 生成する(同じファイルの行一覧: &'a [String]) -> Self {
        Self { 同じファイルの行一覧 }
    }

    /// その行から役割の使用箇所を読む。
    pub fn 行から読む(&self, 行: &str) -> 役割の使用箇所を読んだ結果 {
        if 役割自身の宣言の行か(行) {
            return 役割の使用箇所を読んだ結果::使用箇所でない;
        }
        let Some((役割, 位置)) = 関数の役割::全部の一覧().into_iter().find_map(|役割| 行.find(&format!("{}<", 役割.名前())).map(|位置| (役割, 位置))) else {
            return 役割の使用箇所を読んだ結果::使用箇所でない;
        };
        let 型引数の始まり = 位置 + 役割.名前().len() + 1;
        let 役割名の開き括弧より後ろ = &行[型引数の始まり..];
        let (型引数の表記一覧, 型引数より後ろ) = match 型引数を区切る(役割, 役割名の開き括弧より後ろ) {
            Ok(区切った結果) => 区切った結果,
            Err(構文) => return 役割の使用箇所を読んだ結果::読めなかった(抽出できなかった理由::保証範囲の外の構文である { 構文 }),
        };
        if 型引数の表記一覧.len() != 役割.型引数の数() {
            return 役割の使用箇所を読んだ結果::読めなかった(抽出できなかった理由::役割の型引数の数が合わない {
                役割名: 役割.名前(),
                取る数: 役割.型引数の数(),
                読めた数: 型引数の表記一覧.len(),
            });
        }
        match 役割に包まれた関数のパスを読む工程::生成する(役割, self.同じファイルの行一覧).型引数より後ろから読む(型引数より後ろ) {
            Ok(包まれた関数のパス) => 役割の使用箇所を読んだ結果::読めた {
                役割, 包まれた関数のパス, 型引数の表記一覧
            },
            Err(理由) => 役割の使用箇所を読んだ結果::読めなかった(理由),
        }
    }
}

// 役割の型自身を宣言または実装する行か。使用箇所ではないため対象外にする。
fn 役割自身の宣言の行か(行: &str) -> bool {
    let mut 残り = 行.trim();
    for 前置き in ["pub(crate) ", "pub(super) ", "pub "] {
        残り = 残り.strip_prefix(前置き).unwrap_or(残り).trim_start();
    }
    ["struct ", "enum ", "trait ", "type ", "impl"].iter().any(|前置き| 残り.starts_with(前置き))
}

// 役割の名前の `<` より後ろから、対応する `>` までの型引数を位置の順に区切り、`>` より後ろと組にして返す。
// 区切れなければ、対応する `>` が同じ行に無いか、閉じた型引数の中の深さが合わないかを名指す保証範囲の外の構文を返す。
fn 型引数を区切る(役割: 関数の役割, 役割名の開き括弧より後ろ: &str) -> Result<(Vec<String>, &str), 保証範囲の外の構文> {
    let mut 深さ = 1usize;
    for (位置, 文字) in 役割名の開き括弧より後ろ.char_indices() {
        match 文字 {
            '<' => 深さ += 1,
            '>' if 戻り値の矢印の不等号か(役割名の開き括弧より後ろ, 位置) => continue,
            '>' => 深さ -= 1,
            _ => continue,
        }
        if 深さ == 0 {
            let 型引数の中身 = &役割名の開き括弧より後ろ[..位置];
            let 一覧 = 位置で並べた型の一覧(型引数の中身).ok_or_else(|| 保証範囲の外の構文::型の表記がRustのパスでない { 表記: 型引数の中身.trim().to_string() })?;
            return Ok((一覧, &役割名の開き括弧より後ろ[位置 + 1..]));
        }
    }
    Err(保証範囲の外の構文::役割の型引数の不等号が同じ行で閉じない {
        役割名: 役割.名前(),
        表記: 役割名の開き括弧より後ろ.trim().to_string(),
    })
}
