//! 回帰試験が抽出器へ与えるソースを組む段取り。試験のファイルから重複を除くためだけに在り、試験の判定は持たない。
//!
//! 文字列としてのソースを与えるのは、リポジトリの実物が変わると「このRustの構文からこの関係が出る」という固定が壊れるためである。
//! 実物を走査する試験は `real_crates_tests.rs` が1件だけ持つ。

use std::path::PathBuf;

use super::outcome::抽出の結末;
use super::source_group::抽出対象のソース群;

/// パスと原文の対から抽出の結末を組む。
pub fn 原文から結末を組む(原文一覧: &[(&str, &str)]) -> 抽出の結末 {
    let 組んだ一覧: Vec<(PathBuf, String)> = 原文一覧.iter().map(|(パス, 原文)| (PathBuf::from(パス), (*原文).to_string())).collect();
    super::ソース群から抽出する(&抽出対象のソース群::原文一覧から生成する(組んだ一覧))
}

/// 結末が持つ設計関係を、人が読む1行の表記の一覧にする。
pub fn 関係の表記一覧(結末: &抽出の結末) -> Vec<String> {
    結末.グラフ.関係一覧().iter().map(|関係| 関係.表記()).collect()
}

/// 結末が持つ設計概念を、人が読む1行の表記の一覧にする。
pub fn 概念の表記一覧(結末: &抽出の結末) -> Vec<String> {
    結末.グラフ.概念一覧().iter().map(|概念| 概念.識別子().表記()).collect()
}

/// 結末が持つ抽出できなかった行の理由の説明の一覧。
pub fn 抽出できなかった理由の説明一覧(結末: &抽出の結末) -> Vec<String> {
    結末.抽出できなかった行一覧.iter().map(|行| 行.理由.説明()).collect()
}
