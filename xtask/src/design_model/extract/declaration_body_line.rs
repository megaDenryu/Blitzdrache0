//! `struct` と `enum` の本体の1行を読む工程。依存を持たない純粋な関数だけを置く。
//! 受け取るのはコードだけの1行、返すのはその行が持つフィールドの記述か、フィールドを持たない行であるという答えか、保証範囲の外であるという答えである。
//!
//! 宣言の見出しを読む工程(`struct_declaration`)と分けるのは、受け取る綴りが違うためである。あちらは `struct 名前<型引数> {` を、こちらは本体の1行を読む。
//!
//! フィールドを持たない行として明示して外すのは、属性の行(`#[...]`)・閉じ括弧だけの行・フィールドを持たない選択肢の名前だけの行の3つである。
//! どれも外す条件を書き下せており、その位置に設計関係は初めから無い。これに当たらない読めない行は、黙って読み飛ばさずに保証範囲の外と答える。

use crate::conform::design_ontology::line_matching::先頭の識別子;

use super::positional_types::位置で並べた型の一覧;
use super::struct_declaration::可視性を落とす;

/// 本体の1行を読んだ答え。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 本体の行の読み取り {
    /// 属性・閉じ括弧・フィールドを持たない選択肢のいずれかであり、設計関係を初めから持たない。
    フィールドを持たない,
    /// 名前と型の組を持つ。1行に複数件あるのは、1行に収めた選択肢の本体(`歩く { 方向: 歩行方向 }`)である。
    名前付きのフィールド(Vec<(String, String)>),
    /// 位置で並べた型の表記を持つ。タプルの選択肢(`歩く(歩行方向)`)である。
    位置で並べたフィールド(Vec<String>),
    /// 抽出器の保証範囲の外の行である。
    保証範囲の外,
}

/// 本体の1行を読む。宣言の行は、1行に収めた本体を読むために波括弧の後ろだけを見る。
pub fn 本体の行を読む(行: &str, 宣言の行か: bool) -> 本体の行の読み取り {
    let 文字列 = 行.trim();
    if 文字列.is_empty() || 文字列.starts_with('#') {
        return 本体の行の読み取り::フィールドを持たない;
    }
    if let Some((_, 波括弧の後ろ)) = 文字列.split_once('{') {
        return 波括弧の中身を読む(波括弧の後ろ);
    }
    if 宣言の行か {
        return 本体の行の読み取り::フィールドを持たない;
    }
    記述を読む(文字列.trim_end_matches(',').trim())
}

// 波括弧の後ろから閉じ括弧までを、読点で区切って1件ずつ読む。
fn 波括弧の中身を読む(波括弧の後ろ: &str) -> 本体の行の読み取り {
    let 中身 = 波括弧の後ろ.rsplit_once('}').map_or(波括弧の後ろ, |(中身, _)| 中身);
    let Some(記述一覧) = 位置で並べた型の一覧(中身) else {
        return 本体の行の読み取り::保証範囲の外;
    };
    let mut 組一覧 = Vec::new();
    for 記述 in 記述一覧 {
        match 記述を読む(&記述) {
            本体の行の読み取り::名前付きのフィールド(組) => 組一覧.extend(組),
            本体の行の読み取り::フィールドを持たない => {}
            本体の行の読み取り::位置で並べたフィールド(_) | 本体の行の読み取り::保証範囲の外 => return 本体の行の読み取り::保証範囲の外,
        }
    }
    本体の行の読み取り::名前付きのフィールド(組一覧)
}

// 1件の記述を読む。`名前: 型` と `名前(型, 型)` と名前だけの3つが保証範囲である。
fn 記述を読む(記述: &str) -> 本体の行の読み取り {
    let 記述 = 可視性を落とす(記述.trim());
    if 記述.is_empty() || 記述 == "}" || 記述 == ")" {
        return 本体の行の読み取り::フィールドを持たない;
    }
    if let Some((名前側, 型側)) = 記述.split_once(':') {
        let 名前 = 名前側.trim().to_string();
        if 名前.is_empty() || 先頭の識別子(&名前) != 名前 {
            return 本体の行の読み取り::保証範囲の外;
        }
        return 本体の行の読み取り::名前付きのフィールド(vec![(名前, 型側.trim().to_string())]);
    }
    let 名前 = 先頭の識別子(記述);
    let 名前の後ろ = 記述[名前.len()..].trim();
    if 名前.is_empty() {
        return 本体の行の読み取り::保証範囲の外;
    }
    if 名前の後ろ.is_empty() {
        return 本体の行の読み取り::フィールドを持たない;
    }
    選択肢の位置で並べた本体を読む(名前の後ろ)
}

// 選択肢の名前の後ろの `(型, 型)` を読む。括弧で始まり括弧で閉じない綴りは保証範囲の外である。
fn 選択肢の位置で並べた本体を読む(名前の後ろ: &str) -> 本体の行の読み取り {
    let 括弧の中身 = 名前の後ろ.strip_prefix('(').and_then(|残り| 残り.trim_end().strip_suffix(')'));
    let Some(括弧の中身) = 括弧の中身 else {
        return 本体の行の読み取り::保証範囲の外;
    };
    位置で並べた型の一覧(括弧の中身).map_or(本体の行の読み取り::保証範囲の外, 本体の行の読み取り::位置で並べたフィールド)
}
