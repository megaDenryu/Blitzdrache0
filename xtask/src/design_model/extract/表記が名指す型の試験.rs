//! フレーム型の受理の回帰試験。一覧の型ごとに「この表記を座標系を含む1つの型として読む」を固定し、
//! 構造体のフィールドに書いたフレーム型から `保持する` が出ることを固定する。一覧と `blitz_math` の実物との突き合わせは `フレーム型の一覧の実物との突き合わせの試験` が持つ。
//!
//! 一覧の型ごとの表記を一覧から導かずに書き下すのは、一覧から導くと、一覧へ誤った型を足しても試験が同じ誤りを写して通るためである。

use super::test_support::{原文から設計関係グラフと抽出の欠けを組む, 抽出できなかった理由の説明一覧, 概念の表記一覧, 関係の表記一覧};
use blitz_design_verification::{フレーム型, 型の表記の読み取り, 型の表記を読む};

// 一覧の型ごとに書き下した、座標系を与えた表記。整形済みの表記であり、読んだ型の同一性の名前はこの表記そのものになる。
const 型ごとの書き下した表記: [&str; 17] = [
    "位置<ワールド>",
    "変位<ワールド>",
    "方向<ワールド>",
    "二段の位置<ワールド>",
    "角の勾配<ワールド>",
    "面積ベクトル<ワールド>",
    "慣性テンソル<主軸>",
    "逆慣性テンソル<ワールド>",
    "速度<ワールド>",
    "角速度<ローカル>",
    "力<ワールド>",
    "回転力<ワールド>",
    "衝撃<ワールド>",
    "回転衝撃<ワールド>",
    "回転ベクトル<ワールド>",
    "変換<ローカル, ワールド>",
    "クォータニオン<ローカル, ワールド>",
];

#[test]
fn 一覧の型ごとに座標系を含む表記の全体を1つの型として読む() {
    for 表記 in 型ごとの書き下した表記 {
        let 型の表記の読み取り::設計概念である(名指す型) = 型の表記を読む(表記) else {
            panic!("`{表記}` をフレーム型として読めなかった: {:?}", 型の表記を読む(表記));
        };
        assert_eq!(名指す型.同一性の名前(), 表記, "{表記}");
        assert_eq!(Some(名指す型.定義を探す名前()), 表記.split('<').next(), "{表記}");
    }
    let 書き下した名前一覧: Vec<&str> = 型ごとの書き下した表記.iter().filter_map(|表記| 表記.split('<').next()).collect();
    let 書き下していない型一覧: Vec<&str> = フレーム型::一覧().map(|型| 型.名前()).filter(|名前| !書き下した名前一覧.contains(名前)).collect();
    assert!(書き下していない型一覧.is_empty(), "一覧に在って表記を書き下していない型がある: {書き下していない型一覧:?}");
}

#[test]
fn 座標系の並びの空白を整えた表記を同一性の名前にする() {
    let 型の表記の読み取り::設計概念である(名指す型) = 型の表記を読む("変換< ローカル,ワールド >") else {
        panic!("空白の異なる変換の表記をフレーム型として読めなかった");
    };
    assert_eq!(名指す型.同一性の名前(), "変換<ローカル, ワールド>");
}

#[test]
fn 構造体と列挙のフィールドに書いたフレーム型から座標系ごとに別の型への保持するが出る() {
    let 原文 = "pub struct 望みの動き {\n    変位: 変位<ワールド>,\n    戻る変位: Option<変位<ローカル>>,\n    法線一覧: Vec<方向<ワールド>>,\n}\n\npub enum 移動状態 {\n    接地中 { 接地面の単位法線: 方向<ワールド> },\n    前へ掃引する(変換<ローカル, ワールド>),\n}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/movement/desired_motion.rs", 原文)]);
    let 表記一覧 = 関係の表記一覧(&結果);
    for 期待 in [
        "blitz_game::movement::desired_motion::望みの動き 保持する 変位<ワールド>",
        "blitz_game::movement::desired_motion::望みの動き 保持する 変位<ローカル>",
        "blitz_game::movement::desired_motion::望みの動き 保持する 方向<ワールド>",
        "blitz_game::movement::desired_motion::移動状態 保持する 方向<ワールド>",
        "blitz_game::movement::desired_motion::移動状態 保持する 変換<ローカル, ワールド>",
    ] {
        assert!(表記一覧.contains(&期待.to_string()), "{期待} が無い: {表記一覧:?}");
    }
    let 概念一覧 = 概念の表記一覧(&結果);
    assert!(概念一覧.contains(&"変位<ワールド>".to_string()) && 概念一覧.contains(&"変位<ローカル>".to_string()), "{概念一覧:?}");
    assert!(!結果.関係を落とした抽出の欠落へ写す().在るか(), "{}", 結果.関係を落とした抽出の欠落へ写す().説明());
    let 説明一覧 = 抽出できなかった理由の説明一覧(&結果);
    assert_eq!(説明一覧.len(), 5, "定義をたどれない型の名指しは5件のはずである: {説明一覧:?}");
    assert!(説明一覧.iter().all(|説明| 説明.contains("定義をたどれずモジュールパスを空にした")), "{説明一覧:?}");
}

#[test]
fn フレーム型の座標系が宣言の型引数なら関係を出さず型引数として数える() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/movement/desired_motion.rs", "pub struct 包み<空間種: 空間> {\n    変位: 変位<空間種>,\n}\n")]);
    assert!(!関係の表記一覧(&結果).iter().any(|表記| 表記.contains("保持する")), "{:?}", 関係の表記一覧(&結果));
    assert_eq!(抽出できなかった理由の説明一覧(&結果), vec!["`空間種` は定義の宣言が導入した型引数であり設計概念ではない".to_string()]);
}

#[test]
fn 一覧に無い総称の型は保持するを出さず関係の欠落として数える() {
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[("crates/blitz_game/src/movement/desired_motion.rs", "pub struct 描画の材料 {\n    形: Handle<メッシュ>,\n}\n")]);
    assert!(!関係の表記一覧(&結果).iter().any(|表記| 表記.contains("保持する")), "{:?}", 関係の表記一覧(&結果));
    assert_eq!(結果.関係を落とした抽出の欠落へ写す().合計の件数(), 1, "{}", 結果.関係を落とした抽出の欠落へ写す().説明());
}
