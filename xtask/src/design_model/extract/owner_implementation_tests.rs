//! 役割に包まれた関数のパスの受理の条件4(所有者の固有の実装が同じファイルに在る)が、どの実装の見出しを所有者の固有の実装と読むかの回帰試験。
//! トレイトの実装(`unsafe impl` を含む)は所有者の根拠にならず、複数行の `where` と定数ジェネリクスの式を持つ見出しも正しく読むことを固定する。

use super::test_support::{原文から設計関係グラフと抽出の欠けを組む, 解釈の使用箇所, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";

#[test]
fn 定数ジェネリクスの式を持つトレイト実装は役割の所有者にならない() {
    let 原文 = 解釈の使用箇所("M解釈関数::生成する(所有者Trait::解釈する)") + "trait 所有者Trait<const N: usize> { fn 解釈する(); }\nimpl 所有者Trait<{ 1 }> for キーボード歩行入力 { fn 解釈する() {} }\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(移動のパス, &原文)]);
    assert!(!関係の表記一覧(&結果).iter().any(|表記| 表記.contains("所有者Trait::解釈する")));
    assert!(結果.関係を落とした抽出の欠落へ写す().在るか());
}

#[test]
fn 複数行の固有の実装は役割の所有者として受理する() {
    let 原文 = 解釈の使用箇所("M解釈関数::生成する(新しい所有者::歩行入力を解釈する)") + "pub struct 新しい所有者<T>(T);\nimpl<T> 新しい所有者<T>\nwhere\n    T: Clone,\n{\n    fn 歩行入力を解釈する() {}\n}\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(移動のパス, &原文)]);
    assert!(関係の表記一覧(&結果).iter().any(|表記| 表記.contains("新しい所有者::歩行入力を解釈する")));
}

