//! Issue #193 の段階2の受理の条件を確かめる試験の道具。抽出の結果を、節点・関係・分類の事実・抽出できなかった行・同一性の衝突・
//! 節点が無い端点の行の一覧へ写し、段階2の変更の前(先端 d1c668ac)の抽出器が組んだ一覧を固定したファイルと突き合わせる。
//!
//! 受理の条件は「変更の前と後で、導出された関係の集合が一致すること」である。関係だけでなく節点と欠けの行まで固定するのは、
//! 段階2が節点と欠けを出す場所(抽出器から定義の式の評価器へ)も動かすためであり、関係が一致しても節点の種類や欠けの件数が
//! 食い違えば検証器の答え(未決定へ倒すか)が変わるためである。行の並びを整列してから比べるのは、段階2が規則を当てる順序を変えても
//! 集合としての一致を問うためである。重複は落とさない。同じ関係が2本在ることも抽出の結果の一部である。
//! 段階2の後は、保持するが設計関係と別の高さ(`保持する関係`)へ移る。関係の行は語を含むため、高さを含めて比べる形になる。
//!
//! 固定した一覧は、入力の原文から求めた鍵ごとに並ぶ。文字列として組んだ試験のソースは内容で見分け、
//! 実物の `crates` は内容が変わるたびに鍵が変わると困るため、決まった鍵で固定する。一覧に鍵が無いときも、食い違ったときも、
//! いまの結果の全行を印の間に出して落ちる。固定した一覧はその出力から組む。

use std::path::{Component, Path, PathBuf};

use super::outcome::抽出した設計関係グラフと抽出の欠け;
use super::source_group::抽出対象のソース群;
use blitz_design_verification::保持する関係;

const 固定した一覧: &str = include_str!("変更の前の抽出の結果.txt");

/// 実物の `crates` の結果を固定した鍵。
pub const 実物のクレート群の鍵: &str = "実物のcrates";

/// 原文の一覧から入口を自分で決めて抽出し、入力の原文から求めた鍵で固定した一覧と突き合わせる。
pub fn 原文一覧から抽出して突き合わせる(原文一覧: Vec<(PathBuf, String)>) -> 抽出した設計関係グラフと抽出の欠け {
    let 鍵 = 入力の原文の鍵(&原文一覧, &[]);
    突き合わせて返す(&鍵, super::ソース群から抽出する(&抽出対象のソース群::原文一覧から生成する(原文一覧)))
}

/// 原文の一覧と入口の一覧から抽出し、入力の原文と入口から求めた鍵で固定した一覧と突き合わせる。
pub fn 入口を指定して抽出して突き合わせる(原文一覧: Vec<(PathBuf, String)>, 入口一覧: Vec<PathBuf>) -> 抽出した設計関係グラフと抽出の欠け {
    let 鍵 = 入力の原文の鍵(&原文一覧, &入口一覧);
    突き合わせて返す(&鍵, super::ソース群から抽出する(&抽出対象のソース群::入口を指定して生成する(原文一覧, 入口一覧)))
}

fn 突き合わせて返す(鍵: &str, 結果: 抽出した設計関係グラフと抽出の欠け) -> 抽出した設計関係グラフと抽出の欠け {
    固定した一覧と突き合わせる(鍵, &結果);
    結果
}

/// その鍵で固定した行の一覧と、結果を写した行の一覧が、整列したうえで一致することを確かめる。
pub fn 固定した一覧と突き合わせる(鍵: &str, 結果: &抽出した設計関係グラフと抽出の欠け) {
    let 実際 = 結果を行の一覧へ写す(結果);
    let 全行 = format!("<<<変更の前の抽出の結果\n== {鍵}\n{}\n>>>", 実際.join("\n"));
    let Some(固定) = 鍵の行の一覧(鍵) else {
        panic!("鍵 {鍵} の固定した一覧が無い。いまの結果:\n{全行}");
    };
    if 固定 != 実際 {
        let 消えた: Vec<&String> = 固定.iter().filter(|行| !実際.contains(行)).collect();
        let 増えた: Vec<&String> = 実際.iter().filter(|行| !固定.contains(行)).collect();
        panic!("鍵 {鍵} の結果が変更の前と食い違う。固定{}行・いま{}行。消えた行: {消えた:#?}\n増えた行: {増えた:#?}\nいまの結果:\n{全行}", 固定.len(), 実際.len());
    }
}

// 固定した一覧から、その鍵の区画の行を整列して返す。区画は `== 鍵` の行で始まり、次の `== ` の行か末尾で終わる。
fn 鍵の行の一覧(鍵: &str) -> Option<Vec<String>> {
    let 見出し = format!("== {鍵}");
    let mut 行一覧 = 固定した一覧.lines().skip_while(|行| *行 != 見出し);
    行一覧.next()?;
    let mut 区画: Vec<String> = 行一覧.take_while(|行| !行.starts_with("== ")).filter(|行| !行.is_empty()).map(str::to_string).collect();
    区画.sort();
    Some(区画)
}

// 抽出の結果を、比べる行の一覧へ写して整列する。
fn 結果を行の一覧へ写す(結果: &抽出した設計関係グラフと抽出の欠け) -> Vec<String> {
    let グラフ = &結果.グラフ;
    let mut 行一覧: Vec<String> = グラフ.概念一覧().iter().map(|概念| format!("概念 {:?}:{}", 概念.種類(), 概念.識別子().表記())).collect();
    行一覧.extend(
        グラフ
            .関係一覧()
            .iter()
            .map(|関係| format!("関係 {:?}:{} {} {:?}:{}", 関係.主語.種類(), 関係.主語.表記(), 関係.種類.語(), 関係.目的語.種類(), 関係.目的語.表記())),
    );
    行一覧.extend(
        グラフ
            .保持する関係一覧()
            .iter()
            .map(|関係| format!("関係 {:?}:{} {} {:?}:{}", 関係.主語.種類(), 関係.主語.表記(), 保持する関係::語(), 関係.目的語.種類(), 関係.目的語.表記())),
    );
    let 事実 = グラフ.分類を貸す().事実を貸す();
    行一覧.extend(事実.マーカーの実装一覧().iter().map(|実装| format!("分類 {}", 実装.表記())));
    行一覧.extend(事実.上位トレイトの宣言一覧().iter().map(|宣言| format!("分類 {}", 宣言.表記())));
    行一覧.extend(結果.抽出できなかった行一覧.iter().map(|行| format!("欠け {}:{}: {}", リポジトリからの表記(&行.パス), 行.行番号, 行.理由.説明())));
    行一覧.extend(結果.同一性の衝突一覧.iter().map(|衝突| format!("衝突 {} {:?} {:?}", 衝突.識別子.表記(), 衝突.先に現れた種類, 衝突.後から現れた種類)));
    行一覧.extend(グラフ.節点が無い端点一覧().iter().map(|端点| format!("端点 {:?}:{}", 端点.種類(), 端点.表記())));
    行一覧.sort();
    行一覧
}

// 入力の原文と入口から求めた鍵。本番の選別の後の行でなく原文から求めるのは、選別で落ちる行だけが違う2つの入力を見分けるためである。
// パスはリポジトリからの表記へ直してから混ぜ、試験を走らせる置き場に依存させない。
// FNV-1a の64ビットを使うのは、標準の散らし方が版をまたいで同じ値を返すと約束していないためである。
fn 入力の原文の鍵(原文一覧: &[(PathBuf, String)], 入口一覧: &[PathBuf]) -> String {
    let 原文の文字列 = 原文一覧.iter().flat_map(|(パス, 原文)| [リポジトリからの表記(パス), 原文.clone()]);
    let mut 値: u64 = 0xcbf2_9ce4_8422_2325;
    for 文字列 in 原文の文字列.chain(入口一覧.iter().map(|パス| リポジトリからの表記(パス))) {
        for バイト in 文字列.bytes().chain(std::iter::once(b'\n')) {
            値 ^= u64::from(バイト);
            値 = 値.wrapping_mul(0x0100_0000_01b3);
        }
    }
    format!("{値:016x}")
}

// `crates` の部品から後ろを `/` で繋いだ表記。`crates` を含まないパスはそのまま `/` で繋ぐ。
fn リポジトリからの表記(パス: &Path) -> String {
    let 部品一覧: Vec<String> = パス.components().filter_map(|部品| if let Component::Normal(名前) = 部品 { Some(名前.to_string_lossy().into_owned()) } else { None }).collect();
    let 始まり = 部品一覧.iter().rposition(|部品| 部品 == "crates").unwrap_or(0);
    部品一覧[始まり..].join("/")
}

