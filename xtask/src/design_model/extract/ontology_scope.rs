//! 設計オントロジーの適用範囲。どのクレートのソースを設計関係グラフの節点の供給元にするかを、クレート名の一覧で決める。
//!
//! 範囲をクレート名で持つのは、設計解釈マーカーを実装する型だけを節点にすると、マーカーを1つも実装しない中間の型で経路が切れ、
//! 「関係が無い」という偽の反証が出るためである(`crates/blitz_esca/src/walking_direction.rs` の `歩行方向` は `旅行者の意図` のフィールドだがマーカーを実装していない)。
//! 初版を `blitz_design` と `blitz_esca` の2つにするのは、この2つが設計解釈マーカーの正本とその最初の利用者であり、
//! 他のクレート(描画・物理・ECS)はまだマーカーを1つも実装していないためである。範囲を広げるときはこの定数へクレート名を足す。
//!
//! 騒がしさをこの段で潰さない。抽出の段で落とした情報は後段で復元できないが、後段の絞り込みは命題ごとに変えられる。

use std::path::Path;

use crate::conform::design_ontology::line_matching::クレート名;

/// 設計オントロジーを適用するクレートの名前。
const 設計オントロジーの適用範囲: [&str; 2] = ["blitz_design", "blitz_esca"];

/// そのパスが設計オントロジーの適用範囲のクレートに属するか。
pub fn 適用範囲のクレートのパスか(パス: &Path) -> bool {
    設計オントロジーの適用範囲.iter().any(|名前| クレート名(パス) == *名前)
}
