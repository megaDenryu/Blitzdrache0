//! 抽出の規則5(関数の役割の型引数と、役割の定義が固定で持つ入力)の回帰試験。役割ごとの型引数の位置と関係の種類の対応を固定し、
//! 主語が役割の右辺に包まれた具体の関数のパスであることも固定する。
//!
//! 受理する正規形の4つの条件そのものは `wrapped_function_path_tests.rs` が固定する。

use super::test_support::{原文から設計関係グラフと抽出の欠けを組む, 役割の使用箇所の試験が使う型の定義, 概念の表記一覧, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";
const 前置き: &str = "blitz_esca::traveler_movement::";

fn 遷移の使用箇所() -> String {
    役割の使用箇所の試験が使う型の定義() + "pub const 旅行者の移動: M遷移関数<旅行者の現在地, 旅行者の意図, 歩行の規則, 旅行者の出来事, 現在地の生成の失敗> = M遷移関数::生成する(旅行者の現在地::歩行を遷移する);\n"
}

#[test]
fn 遷移関数の5つの型引数から消費すると参照すると生成するが出る() {
    let 表記一覧 = 関係の表記一覧(&原文から設計関係グラフと抽出の欠けを組む(&[(移動のパス, &遷移の使用箇所())]));
    let 主語 = format!("{前置き}旅行者の現在地::歩行を遷移する");
    for 期待 in [
        format!("{主語} 消費する {前置き}旅行者の現在地"),
        format!("{主語} 消費する {前置き}旅行者の意図"),
        format!("{主語} 参照する {前置き}歩行の規則"),
        format!("{主語} 生成する {前置き}旅行者の出来事"),
    ] {
        assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
    }
}

