#[test]
fn 名前を持たない宣言からは関係を出さず抽出できなかった行として数える() {
    let 原文 = 型の定義() + "const _: M解釈関数<キーボード歩行入力, 旅行者の意図> = M解釈関数::生成する(解釈);\n";
    let 結末 = 原文から結末を組む(&[(移動のパス, &原文)]);
    assert!(!関係の表記一覧(&結末).iter().any(|表記| 表記.contains("消費する")), "{:?}", 関係の表記一覧(&結末));
    assert!(抽出できなかった理由の説明一覧(&結末).iter().any(|説明| 説明.contains("主語を決められない")), "{:?}", 抽出できなかった理由の説明一覧(&結末));
}

