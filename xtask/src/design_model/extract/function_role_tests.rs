//! 抽出の規則5(関数の役割の型引数)の回帰試験。役割ごとの型引数の位置と関係の種類の対応を固定し、
//! 主語の名前が読めない行を抽出できなかった行として数えることも固定する。

use super::test_support::{原文から結末を組む, 抽出できなかった理由の説明一覧, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";
const 主語の前置き: &str = "blitz_esca::traveler_movement::";

fn 型の定義() -> String {
    "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\npub enum 旅行者の意図 {\n    静止,\n}\n\npub struct 歩行の規則 {\n    速さ: f32,\n}\n\npub enum 旅行者の出来事 {\n    周囲を観察した,\n}\n\npub enum 現在地の生成の失敗 {\n    有限でない,\n}\n\npub struct キーボード歩行入力 {\n    前: bool,\n}\n\n".to_string()
}

#[test]
fn 遷移関数の5つの型引数から消費すると参照すると生成するが出る() {
    let 原文 = 型の定義() + "pub const 旅行者の移動: M遷移関数<旅行者の現在地, 旅行者の意図, 歩行の規則, 旅行者の出来事, 現在地の生成の失敗> = M遷移関数::生成する(歩行を遷移する);\n";
    let 表記一覧 = 関係の表記一覧(&原文から結末を組む(&[(移動のパス, &原文)]));
    for 期待 in [
        format!("{主語の前置き}旅行者の移動 消費する {主語の前置き}旅行者の現在地"),
        format!("{主語の前置き}旅行者の移動 消費する {主語の前置き}旅行者の意図"),
        format!("{主語の前置き}旅行者の移動 参照する {主語の前置き}歩行の規則"),
        format!("{主語の前置き}旅行者の移動 生成する {主語の前置き}旅行者の出来事"),
    ] {
        assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
    }
    assert!(!表記一覧.iter().any(|表記| 表記.contains("生成する") && 表記.contains("現在地の生成の失敗")), "{表記一覧:?}");
}

#[test]
