//! 抽出の規則5(関数の役割の型引数)の回帰試験。役割ごとの型引数の位置と関係の種類の対応を固定し、
//! 主語が役割の右辺に包まれた具体の関数のパスであることと、右辺を読めない行を抽出できなかった行として数えることも固定する。

use super::test_support::{原文から結末を組む, 抽出できなかった理由の説明一覧, 概念の表記一覧, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";
const 前置き: &str = "blitz_esca::traveler_movement::";

fn 型の定義() -> String {
    "pub struct 旅行者の現在地 {\n    東: f32,\n}\n\npub enum 旅行者の意図 {\n    静止,\n}\n\npub struct 歩行の規則 {\n    速さ: f32,\n}\n\npub enum 旅行者の出来事 {\n    周囲を観察した,\n}\n\npub enum 現在地の生成の失敗 {\n    有限でない,\n}\n\npub struct キーボード歩行入力 {\n    前: bool,\n}\n\n".to_string()
}

fn 遷移の使用箇所() -> String {
    型の定義() + "pub const 旅行者の移動: M遷移関数<旅行者の現在地, 旅行者の意図, 歩行の規則, 旅行者の出来事, 現在地の生成の失敗> = M遷移関数::生成する(旅行者の現在地::歩行を遷移する);\n"
}

#[test]
fn 遷移関数の5つの型引数から消費すると参照すると生成するが出る() {
    let 表記一覧 = 関係の表記一覧(&原文から結末を組む(&[(移動のパス, &遷移の使用箇所())]));
    let 主語 = format!("{前置き}旅行者の現在地::歩行を遷移する");
    for 期待 in [
        format!("{主語} 消費する {前置き}旅行者の現在地"),
        format!("{主語} 消費する {前置き}旅行者の意図"),
        format!("{主語} 参照する {前置き}歩行の規則"),
        format!("{主語} 生成する {前置き}旅行者の出来事"),
    ] {
        assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
    }
    assert!(!表記一覧.iter().any(|表記| 表記.contains("生成する") && 表記.contains("現在地の生成の失敗")), "{表記一覧:?}");
}

#[test]
fn 遷移関数の状態は消費すると生成するの両方に現れる() {
    let 表記一覧 = 関係の表記一覧(&原文から結末を組む(&[(移動のパス, &遷移の使用箇所())]));
    let 主語 = format!("{前置き}旅行者の現在地::歩行を遷移する");
    assert!(表記一覧.contains(&format!("{主語} 消費する {前置き}旅行者の現在地")), "{表記一覧:?}");
    assert!(表記一覧.contains(&format!("{主語} 生成する {前置き}旅行者の現在地")), "次の状態を生成する関係が出ていない: {表記一覧:?}");
}

#[test]
fn 主語は右辺に包まれた関数のパスであり宣言の名前ではない() {
    let 原文 = 型の定義() + "const _: M解釈関数<キーボード歩行入力, 旅行者の意図> = M解釈関数::生成する(キーボード歩行入力::歩行入力を解釈する);\n";
    let 結末 = 原文から結末を組む(&[(移動のパス, &原文)]);
    let 主語 = format!("{前置き}キーボード歩行入力::歩行入力を解釈する");
    assert!(概念の表記一覧(&結末).contains(&主語), "{:?}", 概念の表記一覧(&結末));
    assert!(関係の表記一覧(&結末).contains(&format!("{主語} 消費する {前置き}キーボード歩行入力")), "{:?}", 関係の表記一覧(&結末));
    assert!(関係の表記一覧(&結末).contains(&format!("{主語} 生成する {前置き}旅行者の意図")), "{:?}", 関係の表記一覧(&結末));
}

