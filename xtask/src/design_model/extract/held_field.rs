//! 抽出の規則3: 構造体のフィールドから `保持する` を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは型の節点と `保持する` の関係を持つ成果である。
//!
//! 走査の範囲を型でなくクレートで決める。設計解釈マーカーを実装する型だけを見ると、マーカーを1つも実装しない中間の型で経路が切れ、
//! 「関係が無い」という偽の反証が出る(`歩行方向` は `旅行者の意図` のフィールドだがマーカーを実装していない)。範囲は `ontology_scope` が持つ。
//! `enum` の選択肢が名前付きの本体を持つ形(`歩く { 方向: 歩行方向 }`)も、その `enum` が保持するものとして数える。
//!
//! フィールドの型がその定義の宣言の型引数と一致するときは関係を出さず、`抽出できなかった行` として数える。
//! 定義をたどれなかった型は節点から落とさず、モジュールパスを空にして入れたうえで1件数える。落とすと偽の反証が出る。

use super::ontology_scope::適用範囲のクレートのパスか;
use super::outcome::抽出の成果;
use super::source_group::{型の在り処の問い, 抽出対象のソース群};
use super::struct_declaration::{フィールドの名前と型, フィールドの記述一覧, 型定義の宣言を読む};
use super::type_notation::設計概念の名前を採る;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::conform::design_ontology::line_matching::波括弧が閉じる行;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};
use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計関係, 設計関係の種類};

pub fn 構造体のフィールドから抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧().iter().filter(|(パス, _)| 適用範囲のクレートのパスか(パス)) {
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        for (宣言の位置, 行) in 行一覧.iter().enumerate() {
            let Some(宣言) = 型定義の宣言を読む(行) else {
                continue;
            };
            let 主語 = 設計概念の識別子::Rustの項目として生成する(&モジュールパス, &宣言.名前);
            成果.概念一覧.push(設計概念::Rustの項目として生成する(主語.clone(), Rustの項目の種類::型));
            let 終了 = 波括弧が閉じる行(行一覧, 宣言の位置);
            for (位置, 本体の行) in 行一覧.iter().enumerate().take(終了 + 1).skip(宣言の位置) {
                for 記述 in フィールドの記述一覧(本体の行, 位置 == 宣言の位置) {
                    let 工程 = フィールド1件の工程 {
                        ソース群,
                        宣言: &宣言,
                        主語: &主語,
                        パス,
                        行番号: 位置 + 1,
                    };
                    工程.記述から抽出する(&記述, &mut 成果);
                }
            }
        }
    }
    成果
}

// フィールド1件から関係を出す工程。触るのは自分が受け取った1件のフィールドと成果の末尾だけである。
struct フィールド1件の工程<'a> {
    ソース群: &'a 抽出対象のソース群,
    宣言: &'a super::struct_declaration::型定義の宣言,
    主語: &'a 設計概念の識別子,
    パス: &'a std::path::Path,
    行番号: usize,
}

impl フィールド1件の工程<'_> {
    fn 記述から抽出する(&self, 記述: &str, 成果: &mut 抽出の成果) {
        let Some((_, 型の表記)) = フィールドの名前と型(記述) else {
            return;
        };
        let Some(型名) = 設計概念の名前を採る(&型の表記) else {
            return;
        };
        if self.宣言.型引数名一覧.contains(&型名) {
            let 理由 = 抽出できなかった理由::型引数である { 型引数名: 型名 };
            成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(self.パス, self.行番号, 理由));
            return;
        }
        let 問い = 型の在り処の問い {
            型名: &型名,
            参照元のパス: self.パス,
            参照元の行番号: self.行番号,
        };
        let (目的語, 解決できなかった行) = self.ソース群.型の識別子を求める(問い);
        成果.抽出できなかった行一覧.extend(解決できなかった行);
        成果.概念一覧.push(設計概念::Rustの項目として生成する(目的語.clone(), Rustの項目の種類::型));
        成果.関係一覧.push(設計関係 {
            主語: self.主語.clone(),
            種類: 設計関係の種類::保持する,
            目的語,
            出どころ: 抽出の出どころ {
                パス: self.パス.to_path_buf(),
                行番号: self.行番号,
                構文: 抽出元の構文::構造体のフィールド,
            },
        });
    }
}
