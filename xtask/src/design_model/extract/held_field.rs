//! 抽出の規則3: 構造体のフィールドから `保持する` を抽出する工程の入口。
//! 受け取るのは抽出対象のソース群、返すのは型の節点と `保持する` の関係を持つ成果である。
//!
//! 走査の範囲を型でなくクレートで決める。設計解釈マーカーを実装する型だけを見ると、マーカーを1つも実装しない中間の型で経路が切れ、
//! 「関係が無い」という偽の反証が出る(`歩行方向` は `旅行者の意図` のフィールドだがマーカーを実装していない)。範囲は `ontology_scope` が持つ。
//! `enum` の選択肢が名前付きの本体を持つ形(`歩く { 方向: 歩行方向 }`)も、その `enum` が保持するものとして数える。
//!
//! 関数の役割の newtype(`M射影関数`・`M解釈関数`・`M遷移関数`)の宣言は、位置で並べた本体を読まずに明示して外す。
//! 包んでいるのは関数ポインタであり、その関数が何を消費して何を生成するかは規則5が役割の使用箇所から別に出しているためである。
//! これは書き下せる対象外の条件であり、解析に失敗したことを対象外の条件にしているのではない。
//!
//! 宣言1件ごとの抽出は `held_declaration` が持つ。入口が所有するのはファイルと宣言の走査だけである。

use super::held_declaration::宣言1件の工程;
use super::ontology_scope::適用範囲のクレートのパスか;
use super::outcome::抽出の成果;
use super::role::関数の役割;
use super::source_group::抽出対象のソース群;
use super::struct_declaration::型定義の宣言を読む;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};

pub fn 構造体のフィールドから抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧().iter().filter(|(パス, _)| 適用範囲のクレートのパスか(パス)) {
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        for (宣言の位置, 行) in 行一覧.iter().enumerate() {
            let Some(宣言) = 型定義の宣言を読む(行) else {
                continue;
            };
            let 主語の節点 = 設計概念::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(&モジュールパス, &宣言.名前), Rustの項目の種類::型);
            let 主語 = 主語の節点.参照を組む();
            成果.概念一覧.push(主語の節点);
            if let Some(役割) = 役割のnewtypeか(&宣言.名前) {
                let 理由 = 抽出できなかった理由::役割のnewtypeの宣言である { 役割名: 役割.名前() };
                成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(パス, 宣言の位置 + 1, 理由));
                continue;
            }
            let 工程 = 宣言1件の工程 {
                ソース群, 宣言: &宣言, 主語: &主語, パス
            };
            工程.本体から抽出する(行一覧, 宣言の位置, &mut 成果);
        }
    }
    成果
}

// その名前が関数の役割の newtype の名前か。当たれば位置で並べた本体を読まずに明示して外す。
fn 役割のnewtypeか(名前: &str) -> Option<関数の役割> {
    関数の役割::全部の一覧().into_iter().find(|役割| 役割.名前() == 名前)
}
