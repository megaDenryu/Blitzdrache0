//! 抽出した設計関係グラフと抽出の欠けが答える件数の試験。保証範囲の外の構文の件数が、抽出できなかった行のうち保証範囲の外の構文の理由を持つ行だけを数えることを固定する。
//!
//! 設計関係への参加の計測(`cargo xtask design-verify`)がこの件数を欠落の内訳として表示する。他の理由の行まで数えると、
//! 読み手は抽出器の保証範囲の外に在る構文の件数を読み誤る。

use std::path::PathBuf;

use super::out_of_range_syntax::保証範囲の外の構文;
use super::outcome::抽出した設計関係グラフと抽出の欠け;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};

#[test]
fn 保証範囲の外の構文の件数は他の理由で抽出できなかった行を数えない() {
    let パス = PathBuf::from("crates/blitz_esca/src/試験の抽出できなかった行.rs");
    let 範囲の外 = 抽出できなかった理由::保証範囲の外の構文である {
        構文: 保証範囲の外の構文::トレイトの宣言がwhere節を持つ { トレイト名: "M状態".to_string() },
    };
    let 未解決 = 抽出できなかった理由::定義のモジュールパスを解決できなかった { 型名: "歩行方向".to_string() };
    let 抽出したもの = 抽出した設計関係グラフと抽出の欠け {
        抽出できなかった行一覧: vec![抽出できなかった行::生成する(&パス, 1, 範囲の外), 抽出できなかった行::生成する(&パス, 2, 未解決)],
        ..抽出した設計関係グラフと抽出の欠け::default()
    };
    assert_eq!(抽出したもの.保証範囲の外の構文の件数(), 1);
}
