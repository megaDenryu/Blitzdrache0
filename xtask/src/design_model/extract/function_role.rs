//! 抽出の規則5: 関数の役割の型引数から `消費する`・`生成する`・`参照する` を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは処理の節点と、データの流れの3語の関係を持つ成果である。
//!
//! 主語は、役割の値の右辺に包まれている具体の関数のパスであり、種類は処理である。この1つの決め方だけを持ち、宣言の名前へは退避しない。
//! 右辺の関数を主語にするのは、データの流れが「どの処理が何を消費して何を生成するか」であり、役割の値を持つ宣言が
//! その関数の型契約をコンパイラに確かめさせる証人でしかないためである。宣言の名前を主語にすると、証人の値が処理として節点に立つ。
//! 右辺を読めない形(戻り値の型・フィールドの型注釈・`= 何か.何か()`)からは主語が決まらないため関係を出さず、`抽出できなかった行` として数える。
//!
//! 型引数は生の `fn f(a: A) -> B` から読まない。読むと関数の引数と戻り値という言語の形がそのまま設計の意味になり、
//! 設計として説明可能かを問う力を失う。読むのは役割の型の使用箇所の型引数だけである。

use super::outcome::抽出の成果;
use super::role_usage::{役割の使用箇所を読む, 役割の使用箇所を読んだ結果};
use super::source_group::{型の在り処の問い, 抽出対象のソース群};
use super::type_notation::先頭の型名を採る;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::design_model::{Rustの項目の種類, 設計概念};
use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計関係};

pub fn 関数の役割の型引数から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧() {
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        for (添字, 行) in 行一覧.iter().enumerate() {
            let 使用箇所 = 使用箇所1件の工程 {
                ソース群,
                モジュールパス: &モジュールパス,
                パス,
                行番号: 添字 + 1,
            };
            使用箇所.行から抽出する(行, &mut 成果);
        }
    }
    成果
}

// 役割の使用箇所1件から関係を出す工程。触るのは自分が受け取った1行と成果の末尾だけである。
struct 使用箇所1件の工程<'a> {
    ソース群: &'a 抽出対象のソース群,
    モジュールパス: &'a str,
    パス: &'a std::path::Path,
    行番号: usize,
}

impl 使用箇所1件の工程<'_> {
    fn 行から抽出する(&self, 行: &str, 成果: &mut 抽出の成果) {
        let (役割, 包まれた関数のパス, 型引数の表記一覧) = match 役割の使用箇所を読む(行) {
            役割の使用箇所を読んだ結果::使用箇所でない => return,
            役割の使用箇所を読んだ結果::読めた {
                役割, 包まれた関数のパス, 型引数の表記一覧
            } => (役割, 包まれた関数のパス, 型引数の表記一覧),
            読めなかった => return self.読めなかった1件を数える(読めなかった, 成果),
        };
        let 主語の節点 = 設計概念::Rustの項目として生成する(包まれた関数のパス.処理の識別子を組む(self.モジュールパス), Rustの項目の種類::処理);
        let 主語 = 主語の節点.参照を組む();
        成果.概念一覧.push(主語の節点);
        for (位置, 関係の種類) in 役割.型引数の位置ごとの関係() {
            let Some(型名) = 型引数の表記一覧.get(*位置).map(|表記| 先頭の型名を採る(表記)).filter(|型名| !型名.is_empty()) else {
                continue;
            };
            let 問い = 型の在り処の問い {
                型名: &型名,
                参照元のパス: self.パス,
                参照元の行番号: self.行番号,
            };
            let (目的語の識別子, 解決できなかった行) = self.ソース群.型の識別子を求める(問い);
            成果.抽出できなかった行一覧.extend(解決できなかった行);
            let 目的語の節点 = 設計概念::Rustの項目として生成する(目的語の識別子, Rustの項目の種類::型);
            let 目的語 = 目的語の節点.参照を組む();
            成果.概念一覧.push(目的語の節点);
            成果.関係一覧.push(設計関係 {
                主語: 主語.clone(),
                種類: *関係の種類,
                目的語,
                出どころ: 抽出の出どころ {
                    パス: self.パス.to_path_buf(),
                    行番号: self.行番号,
                    構文: 抽出元の構文::関数の役割の型引数,
                },
            });
        }
    }

    fn 読めなかった1件を数える(&self, 結果: 役割の使用箇所を読んだ結果, 成果: &mut 抽出の成果) {
        let 理由 = match 結果 {
            役割の使用箇所を読んだ結果::型引数に入れ子の型引数がある(役割) => 抽出できなかった理由::役割の型引数に入れ子の型引数がある { 役割名: 役割.名前() },
            役割の使用箇所を読んだ結果::型引数の数が合わない { 役割, 読めた数 } => 抽出できなかった理由::役割の型引数の数が合わない {
                役割名: 役割.名前(),
                取る数: 役割.型引数の数(),
                読めた数,
            },
            役割の使用箇所を読んだ結果::包まれた関数のパスを読めない(役割) => 抽出できなかった理由::役割に包まれた関数のパスを読めない { 役割名: 役割.名前() },
            役割の使用箇所を読んだ結果::使用箇所でない | 役割の使用箇所を読んだ結果::読めた { .. } => return,
        };
        成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(self.パス, self.行番号, 理由));
    }
}
