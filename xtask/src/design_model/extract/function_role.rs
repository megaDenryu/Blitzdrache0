//! 抽出の規則5: 関数の役割の使用箇所から、関数の役割の宣言の事実を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは関数の役割の宣言の事実を持つ成果である。関係は出さない(Issue #193 の段階2)。
//!
//! 事実が持つのは、役割と、型引数の表記を位置の順に並べた一覧と、包まれた関数の節点である。どの位置の型引数を消費し何を生成するか、
//! 役割の定義が固定で受け取る入力(`M遷移関数` の `遷移パラメータ`)は、役割の定義の知識として定義の式(`blitz_design_verification`)が持つ。
//!
//! 包まれた関数の節点は、役割の値の右辺に包まれている具体の関数のパスから組み、種類は処理である。この1つの決め方だけを持ち、宣言の名前へは退避しない。
//! 右辺の関数を処理にするのは、データの流れが「どの処理が何を消費して何を生成するか」であり、役割の値を持つ宣言が
//! その関数が役割の型契約を満たすことをコンパイラに確かめさせるだけの、関数の役割の宣言でしかないためである。宣言の名前を使うと、関数の役割の宣言が処理として節点に立つ。
//! 右辺を読めない形(戻り値の型・フィールドの型注釈・`= 何か.何か()`)からは処理が決まらないため事実を出さず、`抽出できなかった行` として数える。
//! 受理する右辺の正規形は `wrapped_function_path` が4つの条件で書き下しており、どれかを満たさない行も `抽出できなかった行` として数える。
//!
//! 型引数は生の `fn f(a: A) -> B` から読まない。読むと関数の引数と戻り値という言語の形がそのまま設計の意味になり、
//! 設計として説明可能かを問う力を失う。読むのは役割の型の使用箇所の型引数だけである。

use super::outcome::抽出の成果;
use super::role_usage::{役割の使用箇所を読む工程, 役割の使用箇所を読んだ結果};
use super::source_group::抽出対象のソース群;
use super::unextracted_line::抽出できなかった行;
use crate::design_model::{Rustの項目の種類, 設計概念};
use blitz_design_verification::{事実の出どころ, 型の表記, 関数の役割の宣言の事実};

pub fn 関数の役割の型引数から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for (パス, 行一覧) in ソース群.ファイル一覧() {
        let モジュールパス = ソース群.ファイルのモジュールパス(パス);
        let 読む工程 = 役割の使用箇所を読む工程::生成する(行一覧);
        for (添字, 行) in 行一覧.iter().enumerate() {
            match 読む工程.行から読む(行) {
                役割の使用箇所を読んだ結果::使用箇所でない => {}
                役割の使用箇所を読んだ結果::読めた {
                    役割, 包まれた関数のパス, 型引数の表記一覧
                } => 成果.事実.関数の役割の宣言一覧.push(関数の役割の宣言の事実 {
                    処理: 設計概念::Rustの項目として生成する(包まれた関数のパス.処理の識別子を組む(&モジュールパス), Rustの項目の種類::処理),
                    役割,
                    型引数の表記一覧: 型引数の表記一覧.iter().map(|表記| 型の表記::型引数の無い場所で生成する(表記)).collect(),
                    出どころ: 事実の出どころ { パス: パス.clone(), 行番号: 添字 + 1 },
                }),
                役割の使用箇所を読んだ結果::読めなかった(理由) => 成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(パス, 添字 + 1, 理由)),
            }
        }
    }
    成果
}
