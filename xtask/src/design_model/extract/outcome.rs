//! 抽出の成果と抽出の結末。5つの抽出の規則が同じ形の成果を返し、入口がそれを1つへ併せて結末にする。
//!
//! 2つの型を分けるのは寿命が違うためである。成果は規則1つぶんの途中の値であり、規則を跨いで併せる操作を持つ。
//! 結末は入口が1度だけ返す答えであり、節点の重複を畳んだグラフを持つ。
//!
//! 概念を成果が運ぶのは、その節点がトレイトか処理か型かを知っているのが抽出した規則の側だからである
//! (上位トレイトの宣言はトレイトを、役割の型引数は処理を、構造体のフィールドは型を作る)。入口は種類を決め直さず、
//! 規則1から順に併せて、先に現れた種類を残す。

use super::unextracted_line::抽出できなかった行;
use crate::design_model::設計関係グラフ;
use crate::design_model::設計概念;
use crate::design_model::設計関係;

/// 抽出の規則1つぶんの成果。
#[derive(Debug, Clone, Default)]
pub struct 抽出の成果 {
    pub 概念一覧: Vec<設計概念>,
    pub 関係一覧: Vec<設計関係>,
    pub 抽出できなかった行一覧: Vec<抽出できなかった行>,
}

/// 抽出器が返す答え。グラフと、抽出できなかった行の一覧の対である。
#[derive(Debug, Clone, Default)]
pub struct 抽出の結末 {
    pub グラフ: 設計関係グラフ,
    pub 抽出できなかった行一覧: Vec<抽出できなかった行>,
}

impl 抽出の成果 {
    /// 他の規則の成果を自分の後ろへ併せる。節点の種類は先に併せたものを残す(畳むのはグラフの生成である)。
    pub fn 併せる(&mut self, 他: Self) {
        self.概念一覧.extend(他.概念一覧);
        self.関係一覧.extend(他.関係一覧);
        self.抽出できなかった行一覧.extend(他.抽出できなかった行一覧);
    }

    /// 成果をグラフへ畳んで結末にする。
    pub fn 結末にする(self) -> 抽出の結末 {
        抽出の結末 {
            グラフ: 設計関係グラフ::生成する(self.概念一覧, self.関係一覧),
            抽出できなかった行一覧: self.抽出できなかった行一覧,
        }
    }
}
