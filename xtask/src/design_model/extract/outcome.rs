//! 抽出の成果と、抽出した設計関係グラフと抽出の欠け。5つの抽出の規則が同じ形の成果を返し、入口がそれを1つへ併せて
//! 設計関係グラフと抽出の欠けへ組む。成果は関係を持たず、プリミティブな事実を持つ。関係は組むときに定義の式を評価して導く(Issue #193 の段階2)。
//!
//! 2つの型を分けるのは寿命が違うためである。成果は規則1つぶんの途中の値であり、規則を跨いで併せる操作を持つ。
//! 抽出した設計関係グラフと抽出の欠けは入口が1度だけ返す答えであり、節点の重複を1つにまとめたグラフを持つ。
//!
//! 成果はプリミティブな事実と別に分類の事実(マーカーの実装と上位トレイトの宣言)も運ぶ。分類は辺ではなく、グラフが節点のラベルとして閉じて持つためである。
//! 概念を成果が運ぶのは、分類の事実の端点がトレイトか型かを知っているのが抽出した規則の側だからである。
//! 型の定義と関数の役割の宣言が立てる節点は事実が、導いた関係の端点は定義の式の評価器が運ぶ。入口は種類を決め直さない。
//! 定義の式の評価器が導けなかった箇所(導出の欠け)は、抽出できなかった行へ写して同じ一覧で数える。
//! 同じ識別子へ種類の違う概念が来たときは、グラフの組み立てが両方を節点として残して衝突に数え、この値がその一覧を運ぶ。
//! この値が衝突を運ぶのは、入口の表示が件数と例を出すためと、検証器へ渡す `関係を落とした抽出の欠落` をこの値から組むためである。
//! 表示だけでは証明の健全性が回復しない。辺がグラフへ入らないまま「辺が無い」を根拠に反証すると、否定の下でその反証が
//! 反転して証明済みになるため、この値は欠落を検証器へ渡せる形へ写すメソッドを持つ。

use super::marker_concept::設計解釈マーカーの参照一覧;
use super::out_of_range_syntax::保証範囲の外の構文;
use super::source_group::抽出対象のソース群;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった理由の区分, 抽出できなかった行};
use crate::design_model::同一性の衝突;
use crate::design_model::設計概念;
use crate::design_model::設計関係グラフ;
use blitz_design_verification::{
    プリミティブな事実, マーカーの実装の事実, 上位トレイトの宣言の事実, 分類の事実, 定義の式, 導出の欠け, 導出の欠けの理由, 落とした理由ごとの件数, 関係を落とした抽出の欠落
};

/// 抽出の規則1つぶんの成果。
#[derive(Debug, Clone, Default)]
pub struct 抽出の成果 {
    pub 概念一覧: Vec<設計概念>, // 分類の事実の端点の節点
    pub 事実: プリミティブな事実,
    pub マーカーの実装一覧: Vec<マーカーの実装の事実>,
    pub 上位トレイトの宣言一覧: Vec<上位トレイトの宣言の事実>,
    pub 抽出できなかった行一覧: Vec<抽出できなかった行>,
}

/// 抽出器が返す答え。グラフと、抽出できなかった行の一覧と、同一性の衝突の一覧である。
#[derive(Debug, Clone, Default)]
pub struct 抽出した設計関係グラフと抽出の欠け {
    pub グラフ: 設計関係グラフ,
    pub 抽出できなかった行一覧: Vec<抽出できなかった行>,
    pub 同一性の衝突一覧: Vec<同一性の衝突>,
}

impl 抽出した設計関係グラフと抽出の欠け {
    /// 検証器へ渡す欠落へ写す。区分が `設計関係そのものを抽出できなかった` の行だけを種別ごとに数える。この区分は分類の事実を落とした行も含む。
    ///
    /// 残る2つの区分を数えないのは、どちらも設計関係を失っていないためである。識別子だけ未解決である行は辺をグラフへ入れており、
    /// 設計概念でないため明示して除外した行はその位置に設計関係を初めから持たない。数えると、不在を根拠にしてよい問いまで
    /// 未決定へ倒れ、検証器が何も答えられなくなる。
    ///
    /// 同一性の衝突は `関係を落とした抽出の欠落::生成する` が数える。節点が2つへ割れると辺が割れた両方へ散り、
    /// 片方へ問うと在るはずの辺が見つからないため、関係を落としたのと同じ帰結になる。
    pub fn 関係を落とした抽出の欠落へ写す(&self) -> 関係を落とした抽出の欠落 {
        let mut 種別ごと: Vec<落とした理由ごとの件数> = Vec::new();
        for 行 in &self.抽出できなかった行一覧 {
            if 行.理由.区分() != 抽出できなかった理由の区分::設計関係そのものを抽出できなかった {
                continue;
            }
            let 呼び名 = 行.理由.種別の呼び名();
            match 種別ごと.iter_mut().find(|件| 件.理由の説明 == 呼び名) {
                Some(件) => 件.件数 += 1,
                None => 種別ごと.push(落とした理由ごとの件数 {
                    理由の説明: 呼び名.to_string(), 件数: 1
                }),
            }
        }
        関係を落とした抽出の欠落::生成する(種別ごと, &self.同一性の衝突一覧).グラフの端点を検査する(&self.グラフ)
    }

    /// 抽出できなかった行のうち、抽出器の保証範囲の外の構文だった行の件数。欠落の合計の内訳として読み手へ出す。
    pub fn 保証範囲の外の構文の件数(&self) -> usize {
        self.抽出できなかった行一覧.iter().filter(|行| 行.理由.保証範囲の外の構文を採る().is_some()).count()
    }
}

impl 抽出の成果 {
    /// 他の規則の成果を自分の後ろへ併せる。重複と種類の食い違いはここでは見ず、グラフの組み立てが重複のまとめと衝突の検出を行う。
    pub fn 併せる(&mut self, 他: Self) {
        self.概念一覧.extend(他.概念一覧);
        self.事実.併せる(他.事実);
        self.マーカーの実装一覧.extend(他.マーカーの実装一覧);
        self.上位トレイトの宣言一覧.extend(他.上位トレイトの宣言一覧);
        self.抽出できなかった行一覧.extend(他.抽出できなかった行一覧);
    }

    /// 成果の事実の上で定義の式を評価して関係を導き、設計関係グラフと抽出の欠けへ組む。型の名前の解決はソース群へ問う。
    /// 節点は、分類の事実の端点・事実が立てる節点・導いた関係の端点の順に並べる。組み立てが見つけた同一性の衝突は、この値が運んで入口の表示まで届ける。
    pub fn 設計関係グラフと抽出の欠けを組む(self, ソース群: &抽出対象のソース群) -> 抽出した設計関係グラフと抽出の欠け {
        let 導出 = 定義の式::設計の関係と保持するの定義().評価する(&self.事実, ソース群);
        let mut 概念一覧 = self.概念一覧;
        概念一覧.extend(self.事実.事実が立てる概念一覧());
        概念一覧.extend(導出.端点の概念一覧);
        let mut 抽出できなかった行一覧 = self.抽出できなかった行一覧;
        抽出できなかった行一覧.extend(導出.欠け一覧.into_iter().map(導出の欠けを抽出できなかった行へ写す));
        let 分類の事実 = 分類の事実::生成する(設計解釈マーカーの参照一覧(), self.マーカーの実装一覧, self.上位トレイトの宣言一覧);
        let 組み立て = 設計関係グラフ::生成する(概念一覧, 導出.設計関係一覧, 導出.保持する関係一覧, 分類の事実);
        抽出した設計関係グラフと抽出の欠け {
            グラフ: 組み立て.グラフ,
            抽出できなかった行一覧,
            同一性の衝突一覧: 組み立て.同一性の衝突一覧,
        }
    }
}

// 定義の式の評価器が導けなかった箇所を、抽出できなかった行へ写す。4つの理由は、段階2(Issue #193)の前に抽出器が自分で数えていた理由へそのまま写り、
// 区分(関係そのものを落としたか)も同じになる。役割の型引数の数が合わない宣言は抽出器が事実にしないため、本番では評価器から届かない。
fn 導出の欠けを抽出できなかった行へ写す(欠け: 導出の欠け) -> 抽出できなかった行 {
    let 理由 = match 欠け.理由 {
        導出の欠けの理由::役割の型引数の数が合わない { 役割, 読めた数, .. } => 抽出できなかった理由::役割の型引数の数が合わない {
            役割名: 役割.名前(),
            取る数: 役割.型引数の数(),
            読めた数,
        },
        導出の欠けの理由::型の表記を読めない(読めない理由) => 抽出できなかった理由::保証範囲の外の構文である {
            構文: 保証範囲の外の構文::型の表記を読めない(読めない理由),
        },
        導出の欠けの理由::型引数である { 型引数名 } => 抽出できなかった理由::型引数である { 型引数名 },
        導出の欠けの理由::定義のモジュールパスを解決できなかった { 型名 } => 抽出できなかった理由::定義のモジュールパスを解決できなかった { 型名 },
    };
    抽出できなかった行::生成する(&欠け.出どころ.パス, 欠け.出どころ.行番号, 理由)
}
