//! 関数の役割の型引数に `<>` が入れ子になった使用箇所の回帰試験。型引数の区切りを入れ子の深さで決め、各表記を
//! 保持する関係と同じ `型の表記を読む` で読むことを固定する。フレーム型は1つの型として関係の目的語になり、剥がす包みは剥がし、
//! 一覧に無い総称の型と閉じない型引数は黙って落とさず関係の欠落として数える。関数ポインタの戻り値の矢印 `->` の `>` は型引数を閉じない。

use super::out_of_range_syntax::保証範囲の外の構文;
use super::test_support::{原文から結果を組む, 役割の使用箇所の試験が使う型の定義, 抽出できなかった理由の説明一覧, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/traveler_movement.rs";
const 前置き: &str = "blitz_esca::traveler_movement::";

#[test]
fn 型引数の可変長の配列は保持する関係と同じく剥がして中身へ関係を出す() {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + "pub const 出来事の射影: M射影関数<旅行者の現在地, Vec<旅行者の出来事>> = M射影関数::生成する(旅行者の現在地::射影する);\n";
    let 表記一覧 = 関係の表記一覧(&原文から結果を組む(&[(移動のパス, &原文)]));
    let 期待 = format!("{前置き}旅行者の現在地::射影する 生成する {前置き}旅行者の出来事");
    assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
}

#[test]
fn 型引数にフレーム型を書いた役割から消費すると生成するが出る() {
    let 原文 = 役割の使用箇所の試験が使う型の定義()
        + "const _: M射影関数<旅行者の現在地, 変位<ワールド>> = M射影関数::生成する(旅行者の現在地::変位を射影する);\n"
        + "const _: M解釈関数<方向<ワールド>, 旅行者の意図> = M解釈関数::生成する(キーボード歩行入力::向きを解釈する);\n";
    let 結果 = 原文から結果を組む(&[(移動のパス, &原文)]);
    let 表記一覧 = 関係の表記一覧(&結果);
    for 期待 in [
        format!("{前置き}旅行者の現在地::変位を射影する 消費する {前置き}旅行者の現在地"),
        format!("{前置き}旅行者の現在地::変位を射影する 生成する 変位<ワールド>"),
        format!("{前置き}キーボード歩行入力::向きを解釈する 消費する 方向<ワールド>"),
        format!("{前置き}キーボード歩行入力::向きを解釈する 生成する {前置き}旅行者の意図"),
    ] {
        assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
    }
    assert!(!結果.関係を落とした抽出の欠落へ写す().在るか(), "{}", 結果.関係を落とした抽出の欠落へ写す().説明());
}

#[test]
fn 一覧に無い総称の型を型引数に書いた行は黙って落とさず欠落として数える() {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + "const _: M射影関数<旅行者の現在地, 包み<旅行者の出来事>> = M射影関数::生成する(旅行者の現在地::包みを射影する);\n";
    let 結果 = 原文から結果を組む(&[(移動のパス, &原文)]);
    let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
    assert_eq!(欠落.合計の件数(), 1, "{}", 欠落.説明());
    assert!(抽出できなかった理由の説明一覧(&結果).iter().any(|説明| 説明.contains("`包み<旅行者の出来事>`")), "{:?}", 抽出できなかった理由の説明一覧(&結果));
    assert!(!関係の表記一覧(&結果).iter().any(|表記| 表記.contains("包みを射影する 生成する")), "{:?}", 関係の表記一覧(&結果));
}

#[test]
fn 型引数の不等号が同じ行で閉じない行は黙って落とさず閉じないことを理由に欠落として数える() {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + "const _: M射影関数<旅行者の現在地, 変位<ワールド> = M射影関数::生成する(旅行者の現在地::変位を射影する);\n";
    let 結果 = 原文から結果を組む(&[(移動のパス, &原文)]);
    let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
    assert_eq!(欠落.合計の件数(), 1, "{}", 欠落.説明());
    let 構文一覧: Vec<&保証範囲の外の構文> = 結果.抽出できなかった行一覧.iter().filter_map(|行| 行.理由.保証範囲の外の構文を採る()).collect();
    assert!(matches!(構文一覧.as_slice(), [保証範囲の外の構文::役割の型引数の不等号が同じ行で閉じない { 役割名: "M射影関数", .. }]), "{構文一覧:?}");
    assert!(抽出できなかった理由の説明一覧(&結果).iter().any(|説明| 説明.contains("対応する `>` が同じ行に無く")), "{:?}", 抽出できなかった理由の説明一覧(&結果));
}

#[test]
fn 型引数の中の戻り値の矢印は型引数を閉じず関数ポインタの表記だけを欠落として数える() {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + "const _: M射影関数<旅行者の現在地, fn(&旅行者の現在地) -> 旅行者の出来事> = M射影関数::生成する(旅行者の現在地::関数を射影する);\n";
    let 結果 = 原文から結果を組む(&[(移動のパス, &原文)]);
    let 表記一覧 = 関係の表記一覧(&結果);
    let 期待 = format!("{前置き}旅行者の現在地::関数を射影する 消費する {前置き}旅行者の現在地");
    assert!(表記一覧.contains(&期待), "{期待} が無い: {表記一覧:?}");
    assert!(!表記一覧.iter().any(|表記| 表記.contains("関数を射影する 生成する")), "{表記一覧:?}");
    let 欠落 = 結果.関係を落とした抽出の欠落へ写す();
    assert_eq!(欠落.合計の件数(), 1, "{}", 欠落.説明());
    let 構文一覧: Vec<&保証範囲の外の構文> = 結果.抽出できなかった行一覧.iter().filter_map(|行| 行.理由.保証範囲の外の構文を採る()).collect();
    assert_eq!(
        構文一覧,
        vec![&保証範囲の外の構文::型の表記がRustのパスでない {
            表記: "fn(&旅行者の現在地) -> 旅行者の出来事".to_string()
        }]
    );
}
