//! 型の表記の読み取りの回帰試験。「この表記をこう読む」を固定し、保証範囲の外の表記が黙って名前へ化けないことを固定する。

use super::out_of_range_syntax::保証範囲の外の構文;
use super::type_notation::{型の表記の読み取り, 型の表記を読む};

#[test]
fn 包みを剥がした先の名前を設計概念として採る() {
    for 表記 in ["歩行方向", "Vec<歩行方向>", "Option<Box<歩行方向>>", "&'a 歩行方向", "&mut 歩行方向"] {
        assert_eq!(型の表記を読む(表記), 型の表記の読み取り::設計概念である("歩行方向".to_string()), "{表記}");
    }
}

#[test]
fn プリミティブは設計概念にしない() {
    for 表記 in ["u32", "f32", "bool", "String", "Vec<u8>"] {
        assert_eq!(型の表記を読む(表記), 型の表記の読み取り::プリミティブである, "{表記}");
    }
}

#[test]
fn 配列とタプルと関数ポインタと特性の表記は保証範囲の外である() {
    for 表記 in ["[f32; 3]", "(メートル, メートル)", "fn(&状態) -> 射影DTO", "dyn 表示器", "impl 表示器", "*const メートル"] {
        assert_eq!(型の表記を読む(表記), 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記がRustのパスでない { 表記: 表記.to_string() }), "{表記}");
    }
}

#[test]
fn 剥がす包みでないジェネリクスは保証範囲の外である() {
    let 表記 = "HashMap<旅行者ID, 旅行者>";
    assert_eq!(型の表記を読む(表記), 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記が剥がす包みでないジェネリクスである { 表記: 表記.to_string() }));
}

#[test]
fn パスの修飾が付いた表記は保証範囲の外である() {
    for 表記 in ["blitz_math::メートル", "Vec<crate::traveler::旅行者の意図>"] {
        assert_eq!(型の表記を読む(表記), 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記にパスの修飾がある { 表記: 表記.to_string() }), "{表記}");
    }
}

#[test]
fn 閉じない型引数は保証範囲の外である() {
    let 表記 = "Vec<歩行方向";
    assert_eq!(型の表記を読む(表記), 型の表記の読み取り::保証範囲の外(保証範囲の外の構文::型の表記がRustのパスでない { 表記: 表記.to_string() }));
}
