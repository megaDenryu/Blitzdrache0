//! フレーム型の一覧が `blitz_math` の実物の座標系を型引数に取る型と過不足なく一致することを、実物のソースを走査して確かめる試験。
//!
//! 一覧は定義の式の側(`blitz_design_verification` の `フレーム型`)が `blitz_math` の外から書き写した名前であり、`blitz_math` へフレーム型を足しても一覧は自動では増えない。
//! 足し忘れると、足した型の表記が保証範囲の外へ落ちて、その型を保持する関係が欠落する。この試験はその食い違いを先に落とす。
//! 実物の原文の読み取りは `フレーム型の定義の原文の読み取り` が持ち、この試験は2つの一覧を突き合わせるだけである。

use super::フレーム型の定義の原文の読み取り::{フレーム型の名前と座標系の数, フレーム型の定義の置き場};
use blitz_design_verification::フレーム型;

#[test]
fn フレーム型の一覧はblitz_mathの座標系を型引数に取る型と過不足なく一致する() {
    let mut 実物の型一覧 = フレーム型の定義の置き場::blitz_mathのframeを指す().座標系を型引数に取る型を集める();
    let mut 一覧の型一覧: Vec<フレーム型の名前と座標系の数> = フレーム型::一覧().map(|型| フレーム型の名前と座標系の数::生成する(型.名前(), 型.座標系の数())).collect();
    実物の型一覧.sort();
    一覧の型一覧.sort();
    assert_eq!(一覧の型一覧, 実物の型一覧, "フレーム型の一覧が blitz_math の実物と一致しない");
}
