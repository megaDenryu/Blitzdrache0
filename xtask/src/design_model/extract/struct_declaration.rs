//! `struct` と `enum` の宣言の行を読む工程。依存を持たない純粋な関数だけを置く。
//! 受け取るのはコードだけの1行、返すのは型の名前と型引数の名前の一覧と、本体のフィールドの並べ方である。
//!
//! この読み取りを規則3の本体から分けるのは、抽象度の層が違うためである。規則3は「どの型のどのフィールドから何の関係を出すか」を書き、こちらは Rust の構文を読む。
//! 型引数の名前を宣言から読むのは、フィールドの型がその名前と一致するときに関係を出さないためである。出すと実在しない設計概念の節点ができ、
//! 同じモジュールの別の宣言の型引数が同じ表記へ潰れて1つの節点へ合流し、グラフが意味を失う。
//!
//! 宣言が1行に収まっていない形と、型引数に入れ子の型引数がある形は、黙って読み飛ばさずに保証範囲の外と答える。
//! 本体の1行の読み取りは `declaration_body_line` が持つ。受け取る文字列が宣言の見出しと本体の行で違うためである。

use crate::conform::design_ontology::line_matching::先頭の識別子;

use super::out_of_range_syntax::保証範囲の外の構文;
use super::positional_types::位置で並べた型の一覧;

/// `struct` または `enum` の宣言1件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 型定義の宣言 {
    pub 名前: String,
    pub 型引数名一覧: Vec<String>, // `<状態: M状態, イベント: Mイベント>` なら `状態` と `イベント`
    pub 本体の並べ方: 本体の並べ方,
}

/// 宣言の行が示す、本体のフィールドの並べ方。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 本体の並べ方 {
    /// `{` で本体を開き、名前付きのフィールドを並べる。
    名前付きのフィールド,
    /// `(型, 型)` の形で位置ごとに型を並べる。持つのはその型の表記を位置の順に並べた一覧である。
    位置で並べたフィールド(Vec<String>),
    /// `struct 名前;` のように本体を持たない。
    フィールドを持たない,
    /// 抽出器の保証範囲の外である。
    保証範囲の外(保証範囲の外の構文),
}

/// その行が `struct` または `enum` の宣言なら、名前と型引数の名前と本体の並べ方を読む。
pub fn 型定義の宣言を読む(行: &str) -> Option<型定義の宣言> {
    let 前置きを落とした = 可視性を落とす(行.trim());
    let 残り = ["struct ", "enum "].iter().find_map(|種別| 前置きを落とした.strip_prefix(種別))?.trim_start();
    let 名前 = 先頭の識別子(残り);
    if 名前.is_empty() {
        return None;
    }
    let 名前の後ろ = 残り[名前.len()..].trim_start();
    Some(match 型引数を読む(&名前, 名前の後ろ) {
        Err(構文) => 型定義の宣言 {
            名前,
            型引数名一覧: Vec::new(),
            本体の並べ方: 本体の並べ方::保証範囲の外(構文),
        },
        Ok((型引数名一覧, 型引数の後ろ)) => 型定義の宣言 {
            本体の並べ方: 本体の並べ方を読む(&名前, 型引数の後ろ),
            名前,
            型引数名一覧,
        },
    })
}

/// `pub`・`pub(crate)`・`pub(super)` の前置きを落とす。本体の行のフィールドの可視性も同じ前置きを持つ。
pub fn 可視性を落とす(記述: &str) -> &str {
    let mut 残り = 記述;
    for 前置き in ["pub(crate) ", "pub(super) ", "pub "] {
        残り = 残り.strip_prefix(前置き).unwrap_or(残り).trim_start();
    }
    残り
}

// 名前の後ろから、型引数の名前の一覧と、型引数より後ろの文字列を読む。
fn 型引数を読む<'a>(名前: &str, 名前の後ろ: &'a str) -> Result<(Vec<String>, &'a str), 保証範囲の外の構文> {
    let Some(型引数) = 名前の後ろ.strip_prefix('<') else {
        return Ok((Vec::new(), 名前の後ろ));
    };
    let Some((中身, 後ろ)) = 型引数.split_once('>') else {
        return Err(保証範囲の外の構文::型定義の宣言が1行に収まっていない { 型名: 名前.to_string() });
    };
    if 中身.contains('<') {
        return Err(保証範囲の外の構文::型定義の型引数に入れ子の型引数がある { 型名: 名前.to_string() });
    }
    Ok((型引数名一覧を読む(中身), 後ろ))
}

// 型引数より後ろの文字列から本体の並べ方を読む。`{` で開くか、`(...)` と `;` で閉じるか、`;` だけで閉じるかの3つが保証範囲である。
fn 本体の並べ方を読む(名前: &str, 型引数の後ろ: &str) -> 本体の並べ方 {
    let 文字列 = 型引数の後ろ.trim();
    if 文字列.starts_with('{') {
        return 本体の並べ方::名前付きのフィールド;
    }
    if 文字列 == ";" {
        return 本体の並べ方::フィールドを持たない;
    }
    let 括弧の中身 = 文字列.strip_prefix('(').and_then(|残り| 残り.trim_end().strip_suffix(';')).and_then(|残り| 残り.trim_end().strip_suffix(')'));
    let Some(括弧の中身) = 括弧の中身 else {
        return 本体の並べ方::保証範囲の外(保証範囲の外の構文::型定義の宣言が1行に収まっていない { 型名: 名前.to_string() });
    };
    位置で並べた型の一覧(括弧の中身).map_or_else(|| 本体の並べ方::保証範囲の外(保証範囲の外の構文::位置で並べた本体の型を区切れない { 型名: 名前.to_string() }), 本体の並べ方::位置で並べたフィールド)
}

// `<状態: M状態, イベント: Mイベント>` の中身から型引数の名前だけを読む。
fn 型引数名一覧を読む(中身: &str) -> Vec<String> {
    中身.split(',').map(|項| 項.split_once(':').map_or(項, |(名前, _)| 名前).trim()).filter(|名前| !名前.is_empty()).map(str::to_string).collect()
}
