//! 役割に包まれた関数のパスとは、関数の役割の値を生成するときにその中へ渡された、具体の関数を指すRustのパスのことである。
//! 依存を持たない純粋な関数だけを置く。受け取るのは役割の型引数より後ろの表記、返すのはそのパスか、読めないという答えである。
//!
//! この型が在るのは、データの流れの関係の主語が「実際に処理を行う関数」でなければならないためである。
//! 役割の値を持つ宣言(`const _: M解釈関数<...> = ...`)は、その関数が役割の型契約を満たすことをコンパイラに確かめさせる証人であり、
//! 処理そのものではない。宣言の名前を主語にすると、証人の値がデータの流れの主語になり、オントロジーが答えたい問いと逆になる。
//!
//! 所有者の並びを持つのは、`旅行者の現在地::更新する` と `世界::更新する` が名前だけでは同じになるためである。
//! 関連関数のパスは所有する型の名前まで含めて初めて処理の同一性になる。

use crate::design_model::設計概念の識別子;

/// 役割の値に包まれた具体の関数のパス。`キーボード歩行入力::歩行入力を解釈する` なら所有者の並びは `["キーボード歩行入力"]`、名前は `歩行入力を解釈する` である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 役割に包まれた関数のパス {
    所有者の並び: Vec<String>,
    名前: String,
}

impl 役割に包まれた関数のパス {
    /// 役割の型引数を閉じる `>` より後ろの表記から読む。`= 呼び出し先(関数のパス)` の形でなければ無しである。
    pub fn 型引数より後ろから読む(型引数より後ろ: &str) -> Option<Self> {
        let 右辺 = 代入の右辺を採る(型引数より後ろ)?;
        let (呼び出し先, 開き括弧の後ろ) = 右辺.split_once('(')?;
        if !パスとして読めるか(呼び出し先) {
            return None;
        }
        let (引数, _) = 開き括弧の後ろ.rsplit_once(')')?;
        let mut 区分一覧 = パスの区分一覧に分ける(引数)?;
        let 名前 = 区分一覧.pop()?;
        Some(Self { 所有者の並び: 区分一覧, 名前 })
    }

    /// そのパスが指す処理の同一性を組む。モジュールパスには、その使用箇所が書かれたファイルのモジュールパスを渡す。
    pub fn 処理の識別子を組む(&self, モジュールパス: &str) -> 設計概念の識別子 {
        設計概念の識別子::Rustの項目として生成する(モジュールパス, &self.名前).所有者を添える(self.所有者の並び.clone())
    }
}

// 型引数より後ろの表記から代入の右辺を採る。`=` で始まらない形(戻り値の型・フィールドの型注釈・説明の注釈)は右辺を持たない。
fn 代入の右辺を採る(型引数より後ろ: &str) -> Option<&str> {
    let 残り = 型引数より後ろ.trim_start().strip_prefix('=')?;
    (!残り.starts_with(['=', '>'])).then_some(残り)
}

// `::` で区切った区分がすべて識別子である表記か。`配線.解釈を取り出す` のように区分に識別子でない文字が混じればパスではない。
fn パスとして読めるか(表記: &str) -> bool {
    表記.trim().split("::").all(|区分| 識別子か(区分.trim()))
}

// `::` で区切ったRustのパスを区分の一覧にする。パスとして読めなければ無しである。
fn パスの区分一覧に分ける(表記: &str) -> Option<Vec<String>> {
    パスとして読めるか(表記).then(|| 表記.trim().split("::").map(|区分| 区分.trim().to_string()).collect())
}

// Rustの識別子として読める表記か。日本語の識別子を受けるため、判定は英数字であることでなく文字であることで行う。
fn 識別子か(表記: &str) -> bool {
    !表記.is_empty() && !表記.starts_with(|文字: char| 文字.is_ascii_digit()) && 表記.chars().all(|文字| 文字.is_alphanumeric() || 文字 == '_')
}
