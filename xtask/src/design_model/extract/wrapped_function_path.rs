//! 役割に包まれた関数のパスとは、関数の役割の値を生成するときにその中へ渡された、具体の関数を指すRustのパスのことである。
//! 受け取るのは役割の型引数より後ろの表記、返すのはそのパスか、受理の条件のどれで落ちたかという答えである。
//!
//! この型が在るのは、データの流れの関係の主語が「実際に処理を行う関数」でなければならないためである。
//! 役割の値を持つ宣言(`const _: M解釈関数<...> = ...`)は、その関数が役割の型契約を満たすことをコンパイラに確かめさせる証人であり、
//! 処理そのものではない。宣言の名前を主語にすると、証人の値がデータの流れの主語になり、オントロジーが答えたい問いと逆になる。
//!
//! **受理する正規形を狭く書き下す。** 4つの条件を全部満たす行だけを読めた扱いにする。
//! 1. 呼び出し先の表記が `<その役割名>::生成する` と一致する。
//! 2. 引数のパスを `::` で分けた区分がちょうど2つである(所有する型が1つ、メソッドが1つ)。
//! 3. 1つ目の区分が `crate`・`self`・`super` のどれでもない。
//! 4. 同じファイルに、その型の固有の `impl` の宣言が在る。複数行の `where` も読める。トレイトの実装は含めない。
//!
//! 狭く書き下すのは、広く読むと偽の設計関係を作るためである。`::` で分かれた最後以外を全部所有者として扱い、
//! 使用箇所のモジュールパスをその前へ付ける読み方は、`crate::foo::旅行者::解釈する` から
//! `<使用箇所のモジュール>::crate::foo::旅行者::解釈する` という存在しない識別子を組める。
//! 条件4が同じファイルの `impl` の宣言を見るのは、所有者のモジュールパスとして使用箇所のモジュールパスを当ててよい根拠を、
//! そのファイルの走査で確かめるためである。型の定義の位置で判定しないのは、`旅行者の現在地` の定義が `traveler.rs` に在り
//! 使用箇所が `traveler_movement.rs` に在るように、定義と使用箇所のファイルが分かれる形が実在するためである。
//!
//! 所有者を持つのは、`旅行者の現在地::更新する` と `世界::更新する` が名前だけでは同じになるためである。
//! 関連関数のパスは所有する型の名前まで含めて初めて処理の同一性になる。

use super::role::関数の役割;
use super::unextracted_line::抽出できなかった理由;
use crate::design_model::設計概念の識別子;

/// 役割の値に包まれた具体の関数のパス。`キーボード歩行入力::歩行入力を解釈する` なら所有者は `キーボード歩行入力`、名前は `歩行入力を解釈する` である。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 役割に包まれた関数のパス {
    所有者: String,
    名前: String,
}

impl 役割に包まれた関数のパス {
    /// そのパスが指す処理の同一性を組む。モジュールパスには、その使用箇所が書かれたファイルのモジュールパスを渡す。
    pub fn 処理の識別子を組む(&self, モジュールパス: &str) -> 設計概念の識別子 {
        設計概念の識別子::Rustの項目として生成する(モジュールパス, &self.名前).所有者を添える(vec![self.所有者.clone()])
    }
}

/// 1つのファイルの中で、役割の値に包まれた関数のパスを受理の条件に照らして読む工程。
/// 役割と、その使用箇所が書かれたファイルのコードだけの行の一覧を保持する。行の一覧を保持するのは、条件4がそれを見るためである。
pub struct 役割に包まれた関数のパスを読む工程<'a> {
    役割: 関数の役割,
    同じファイルの行一覧: &'a [String],
}

impl<'a> 役割に包まれた関数のパスを読む工程<'a> {
    pub const fn 生成する(役割: 関数の役割, 同じファイルの行一覧: &'a [String]) -> Self {
        Self { 役割, 同じファイルの行一覧 }
    }

    /// 役割の型引数を閉じる `>` より後ろの表記から読む。4つの受理の条件を1つでも満たさなければ、どの条件で落ちたかを答える。
    pub fn 型引数より後ろから読む(&self, 型引数より後ろ: &str) -> Result<役割に包まれた関数のパス, 抽出できなかった理由> {
        let 引数 = self.生成する呼び出しの引数を採る(型引数より後ろ)?;
        let 区分一覧 = パスの区分一覧に分ける(&引数).ok_or_else(|| 抽出できなかった理由::役割に包まれた関数の引数がパスでない { 役割名: self.役割.名前() })?;
        let [所有者, 名前] = <[String; 2]>::try_from(区分一覧).map_err(|読めた: Vec<String>| 抽出できなかった理由::役割に包まれた関数のパスの区分が2つでない {
            役割名: self.役割.名前(),
            読めた区分の数: 読めた.len(),
        })?;
        if パスの起点の予約語か(&所有者) {
            return Err(抽出できなかった理由::役割に包まれた関数のパスが起点の予約語で始まる {
                役割名: self.役割.名前(), 先頭の区分: 所有者
            });
        }
        if !self.所有者の実装が同じファイルに在るか(&所有者) {
            return Err(抽出できなかった理由::役割に包まれた関数の所有者の実装が同じファイルに無い {
                役割名: self.役割.名前(), 所有者名: 所有者
            });
        }
        Ok(役割に包まれた関数のパス { 所有者, 名前 })
    }

    // 条件1。`= <役割名>::生成する(...)` の形からだけ引数の表記を採る。右辺を持たない形(戻り値の型・フィールドの型注釈・説明の注釈)と、
    // 呼び出し先が役割の `生成する` でない形(`= 配線.解釈を取り出す()`・`= 別の型::生成する(...)`)はここで落ちる。
    fn 生成する呼び出しの引数を採る(&self, 型引数より後ろ: &str) -> Result<String, 抽出できなかった理由> {
        let 落ちた = || 抽出できなかった理由::役割の値の右辺が役割の生成する呼び出しでない { 役割名: self.役割.名前() };
        let 右辺 = 型引数より後ろ.trim_start().strip_prefix('=').filter(|残り| !残り.starts_with(['=', '>'])).ok_or_else(落ちた)?;
        let (呼び出し先, 開き括弧の後ろ) = 右辺.split_once('(').ok_or_else(落ちた)?;
        if 呼び出し先.trim() != format!("{}::生成する", self.役割.名前()) {
            return Err(落ちた());
        }
        let (引数, _) = 開き括弧の後ろ.rsplit_once(')').ok_or_else(落ちた)?;
        Ok(引数.trim().to_string())
    }

    // 条件4。所有者の型を対象にする `impl` の宣言が同じファイルに在るか。
    fn 所有者の実装が同じファイルに在るか(&self, 所有者: &str) -> bool {
        self.同じファイルの行一覧
            .iter()
            .enumerate()
            .filter_map(|(開始, _)| crate::conform::design_ontology::impl_header::implの見出しを読む(self.同じファイルの行一覧, 開始)?.構文を読む())
            .any(|構文| 構文.名前だけで書いた型の固有の実装か(所有者))
    }
}

// 条件3。Rustのパスの起点を表す予約語か。普通の識別子として通すと、実在しないモジュールパスを前へ付けた識別子を組める。
fn パスの起点の予約語か(区分: &str) -> bool {
    matches!(区分, "crate" | "self" | "super")
}

// `::` で区切ったRustのパスを区分の一覧にする。パスとして読めなければ無しである。
fn パスの区分一覧に分ける(表記: &str) -> Option<Vec<String>> {
    表記.trim().split("::").map(|区分| 識別子か(区分.trim()).then(|| 区分.trim().to_string())).collect()
}

// Rustの識別子として読める表記か。日本語の識別子を受けるため、判定は英数字であることでなく文字であることで行う。
fn 識別子か(表記: &str) -> bool {
    !表記.is_empty() && !表記.starts_with(|文字: char| 文字.is_ascii_digit()) && 表記.chars().all(識別子の文字か)
}

// Rustの識別子を構成してよい1文字か。
fn 識別子の文字か(文字: char) -> bool {
    文字.is_alphanumeric() || 文字 == '_'
}
