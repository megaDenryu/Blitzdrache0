//! 宣言1件から `保持する` を出す工程。受け取るのは1つの型定義の宣言とその本体の行、返すのは成果の末尾へ足した節点と関係である。
//!
//! 規則3の入口(`held_field`)と分けるのは、触る状態が違うためである。入口はファイルと宣言の走査を所有し、こちらは宣言1件と成果の末尾だけを触る。
//!
//! 本体の並べ方ごとに振り分けるのは、名前付きのフィールドが本体の行に並ぶのに対し、位置で並べたフィールドが宣言の行そのものに並ぶためである。
//! フィールドの型がその定義の宣言の型引数と一致するときは関係を出さず、`抽出できなかった行` として数える。
//! 定義をたどれなかった型は節点から落とさず、モジュールパスを空にして入れたうえで1件数える。落とすと偽の反証が出る。

use std::path::Path;

use super::declaration_body_line::{本体の行の読み取り, 本体の行を読む};
use super::out_of_range_syntax::保証範囲の外の構文;
use super::outcome::抽出の成果;
use super::source_group::抽出対象のソース群;
use super::struct_declaration::{型定義の宣言, 本体の並べ方};
use super::type_notation::{型の表記の読み取り, 型の表記を読む};
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use super::表記が名指す型::表記が名指す型;
use crate::conform::design_ontology::line_matching::波括弧が閉じる行;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念への参照};
use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計関係, 設計関係の種類};

/// 宣言1件から `保持する` を出す工程。
pub struct 宣言1件の工程<'a> {
    pub ソース群: &'a 抽出対象のソース群,
    pub 宣言: &'a 型定義の宣言,
    pub 主語: &'a 設計概念への参照,
    pub パス: &'a Path,
}

impl 宣言1件の工程<'_> {
    /// 本体の並べ方に従って、この宣言が保持する型へ関係を出す。
    pub fn 本体から抽出する(&self, 行一覧: &[String], 宣言の位置: usize, 成果: &mut 抽出の成果) {
        match &self.宣言.本体の並べ方 {
            本体の並べ方::フィールドを持たない => {}
            本体の並べ方::保証範囲の外(構文) => self.保証範囲の外を数える(構文.clone(), 宣言の位置 + 1, 成果),
            本体の並べ方::位置で並べたフィールド(型の表記一覧) => {
                for 表記 in 型の表記一覧 {
                    self.型の表記から1本を出す(表記, 宣言の位置 + 1, 成果);
                }
            }
            本体の並べ方::名前付きのフィールド => self.名前付きの本体から抽出する(行一覧, 宣言の位置, 成果),
        }
    }

    // 波括弧で開いた本体の行を1行ずつ読み、フィールドの型へ関係を出す。
    fn 名前付きの本体から抽出する(&self, 行一覧: &[String], 宣言の位置: usize, 成果: &mut 抽出の成果) {
        let 終了 = 波括弧が閉じる行(行一覧, 宣言の位置);
        for (位置, 本体の行) in 行一覧.iter().enumerate().take(終了 + 1).skip(宣言の位置) {
            match 本体の行を読む(本体の行, 位置 == 宣言の位置) {
                本体の行の読み取り::フィールドを持たない => {}
                本体の行の読み取り::名前付きのフィールド(組一覧) => {
                    for (_, 型の表記) in 組一覧 {
                        self.型の表記から1本を出す(&型の表記, 位置 + 1, 成果);
                    }
                }
                本体の行の読み取り::位置で並べたフィールド(表記一覧) => {
                    for 表記 in 表記一覧 {
                        self.型の表記から1本を出す(&表記, 位置 + 1, 成果);
                    }
                }
                本体の行の読み取り::保証範囲の外 => {
                    let 構文 = 保証範囲の外の構文::型定義の本体の行がフィールドの記述でない {
                        型名: self.宣言.名前.clone(),
                        行の表記: 本体の行.trim().to_string(),
                    };
                    self.保証範囲の外を数える(構文, 位置 + 1, 成果);
                }
            }
        }
    }

    // 1つの型の表記から `保持する` を1本出す。プリミティブは明示して外し、型引数と保証範囲の外は抽出できなかった行として数える。
    // フレーム型の座標系が宣言の型引数であるとき(`変位<空間種>`)も、実在しない型の節点を作らないために型引数として数える。
    fn 型の表記から1本を出す(&self, 型の表記: &str, 行番号: usize, 成果: &mut 抽出の成果) {
        let 名指す型 = match 型の表記を読む(型の表記) {
            型の表記の読み取り::プリミティブである => return,
            型の表記の読み取り::保証範囲の外(構文) => return self.保証範囲の外を数える(構文, 行番号, 成果),
            型の表記の読み取り::設計概念である(名指す型) => 名指す型,
        };
        if let Some(型引数名) = 名指す型.宣言の型引数と一致する名前(&self.宣言.型引数名一覧) {
            let 理由 = 抽出できなかった理由::型引数である { 型引数名 };
            成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(self.パス, 行番号, 理由));
            return;
        }
        self.解決した型へ1本を出す(&名指す型, 行番号, 成果);
    }

    // 名指す型から定義の在り処を求め、節点と `保持する` の辺を成果へ足す。
    fn 解決した型へ1本を出す(&self, 名指す型: &表記が名指す型, 行番号: usize, 成果: &mut 抽出の成果) {
        let (目的語の識別子, 解決できなかった行) = self.ソース群.名指す型の識別子を求める(名指す型, self.パス, 行番号);
        成果.抽出できなかった行一覧.extend(解決できなかった行);
        let 目的語の節点 = 設計概念::Rustの項目として生成する(目的語の識別子, Rustの項目の種類::型);
        let 目的語 = 目的語の節点.参照を組む();
        成果.概念一覧.push(目的語の節点);
        成果.関係一覧.push(設計関係 {
            主語: self.主語.clone(),
            種類: 設計関係の種類::保持する,
            目的語,
            出どころ: 抽出の出どころ {
                パス: self.パス.to_path_buf(),
                行番号,
                構文: 抽出元の構文::構造体のフィールド,
            },
        });
    }

    fn 保証範囲の外を数える(&self, 構文: 保証範囲の外の構文, 行番号: usize, 成果: &mut 抽出の成果) {
        let 理由 = 抽出できなかった理由::保証範囲の外の構文である { 構文 };
        成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(self.パス, 行番号, 理由));
    }
}
