//! 宣言1件からフィールドの型の表記の事実を出す工程。受け取るのは1つの型定義の宣言とその本体の行、返すのは成果の末尾へ足した事実である。
//!
//! 規則3の入口(`held_field`)と分けるのは、触る状態が違うためである。入口はファイルと宣言の走査を所有し、こちらは宣言1件と成果の末尾だけを触る。
//!
//! 本体の並べ方ごとに振り分けるのは、名前付きのフィールドが本体の行に並ぶのに対し、位置で並べたフィールドが宣言の行そのものに並ぶためである。
//! 事実の表記は包みを剥がす前の綴りのままであり、宣言が導入した型引数の名前を添える。表記がその型引数の名前であるか、プリミティブであるか、
//! 読めない綴りであるか、定義をたどれるかは、定義の式(`blitz_design_verification`)が表記を読むときに決める(Issue #193 の段階2)。

use std::path::Path;

use super::declaration_body_line::{本体の行の読み取り, 本体の行を読む};
use super::out_of_range_syntax::保証範囲の外の構文;
use super::outcome::抽出の成果;
use super::struct_declaration::{型定義の宣言, 本体の並べ方};
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::conform::design_ontology::line_matching::波括弧が閉じる行;
use crate::design_model::設計概念への参照;
use blitz_design_verification::{フィールドの型の表記の事実, 事実の出どころ, 型の表記};

/// 宣言1件からフィールドの型の表記の事実を出す工程。
pub struct 宣言1件の工程<'a> {
    pub 宣言: &'a 型定義の宣言,
    pub 持ち主: &'a 設計概念への参照,
    pub パス: &'a Path,
}

impl 宣言1件の工程<'_> {
    /// 本体の並べ方に従って、この宣言のフィールドの型の表記の事実を出す。
    pub fn 本体から抽出する(&self, 行一覧: &[String], 宣言の位置: usize, 成果: &mut 抽出の成果) {
        match &self.宣言.本体の並べ方 {
            本体の並べ方::フィールドを持たない => {}
            本体の並べ方::保証範囲の外(構文) => self.保証範囲の外を数える(構文.clone(), 宣言の位置 + 1, 成果),
            本体の並べ方::位置で並べたフィールド(型の表記一覧) => {
                for 表記 in 型の表記一覧 {
                    self.表記の事実を出す(表記, 宣言の位置 + 1, 成果);
                }
            }
            本体の並べ方::名前付きのフィールド => self.名前付きの本体から抽出する(行一覧, 宣言の位置, 成果),
        }
    }

    // 波括弧で開いた本体の行を1行ずつ読み、フィールドの型の表記の事実を出す。
    fn 名前付きの本体から抽出する(&self, 行一覧: &[String], 宣言の位置: usize, 成果: &mut 抽出の成果) {
        let 終了 = 波括弧が閉じる行(行一覧, 宣言の位置);
        for (位置, 本体の行) in 行一覧.iter().enumerate().take(終了 + 1).skip(宣言の位置) {
            match 本体の行を読む(本体の行, 位置 == 宣言の位置) {
                本体の行の読み取り::フィールドを持たない => {}
                本体の行の読み取り::名前付きのフィールド(組一覧) => {
                    for (_, 型の表記) in 組一覧 {
                        self.表記の事実を出す(&型の表記, 位置 + 1, 成果);
                    }
                }
                本体の行の読み取り::位置で並べたフィールド(表記一覧) => {
                    for 表記 in 表記一覧 {
                        self.表記の事実を出す(&表記, 位置 + 1, 成果);
                    }
                }
                本体の行の読み取り::保証範囲の外 => {
                    let 構文 = 保証範囲の外の構文::型定義の本体の行がフィールドの記述でない {
                        型名: self.宣言.名前.clone(),
                        行の表記: 本体の行.trim().to_string(),
                    };
                    self.保証範囲の外を数える(構文, 位置 + 1, 成果);
                }
            }
        }
    }

    // フィールド1つの型の表記を、宣言が導入した型引数の名前を添えて事実にする。
    fn 表記の事実を出す(&self, 型の表記: &str, 行番号: usize, 成果: &mut 抽出の成果) {
        成果.事実.フィールドの型の表記一覧.push(フィールドの型の表記の事実 {
            持ち主: self.持ち主.clone(),
            表記: 型の表記::生成する(型の表記, self.宣言.型引数名一覧.clone()),
            出どころ: 事実の出どころ { パス: self.パス.to_path_buf(), 行番号 },
        });
    }

    fn 保証範囲の外を数える(&self, 構文: 保証範囲の外の構文, 行番号: usize, 成果: &mut 抽出の成果) {
        let 理由 = 抽出できなかった理由::保証範囲の外の構文である { 構文 };
        成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(self.パス, 行番号, 理由));
    }
}
