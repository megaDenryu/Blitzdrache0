//! `struct` と `enum` の宣言の行の読み取りの回帰試験。本体の並べ方を4つに読み分けることと、
//! 保証範囲の外の宣言が「フィールドを持たない」へ化けないことを固定する。

use super::out_of_range_syntax::保証範囲の外の構文;
use super::struct_declaration::{型定義の宣言を読む, 本体の並べ方};

// その行の本体の並べ方を読む。宣言でない行は試験が組まないため、読めなかったときは判定を落とす。
fn 本体の並べ方を採る(行: &str) -> 本体の並べ方 {
    match 型定義の宣言を読む(行) {
        Some(宣言) => 宣言.本体の並べ方,
        None => panic!("宣言として読めなかった: {行}"),
    }
}

#[test]
fn タプル構造体の宣言から位置で並べた型を読む() {
    assert_eq!(本体の並べ方を採る("pub struct 経過時間(秒);"), 本体の並べ方::位置で並べたフィールド(vec!["秒".to_string()]));
    assert_eq!(本体の並べ方を採る("struct 位置の組(メートル, メートル);"), 本体の並べ方::位置で並べたフィールド(vec!["メートル".to_string(), "メートル".to_string()]));
}

#[test]
fn 波括弧で開く宣言は名前付きのフィールドである() {
    assert_eq!(本体の並べ方を採る("pub struct 旅行者の現在地 {"), 本体の並べ方::名前付きのフィールド);
    assert_eq!(本体の並べ方を採る("pub enum 旅行者の意図 {"), 本体の並べ方::名前付きのフィールド);
}

#[test]
fn 本体を持たない宣言はフィールドを持たない() {
    assert_eq!(本体の並べ方を採る("pub struct 目印;"), 本体の並べ方::フィールドを持たない);
}

#[test]
fn 宣言の型引数の名前を読み型引数の後ろから本体の並べ方を読む() {
    let Some(宣言) = 型定義の宣言を読む("pub struct 遷移成功結果<状態: M状態, イベント: Mイベント> {") else {
        panic!("宣言として読めなかった");
    };
    assert_eq!(宣言.型引数名一覧, vec!["状態".to_string(), "イベント".to_string()]);
    assert_eq!(宣言.本体の並べ方, 本体の並べ方::名前付きのフィールド);
}

#[test]
fn 閉じない型引数の宣言は保証範囲の外である() {
    assert_eq!(
        本体の並べ方を採る("pub struct 遷移成功結果<状態: M状態,"),
        本体の並べ方::保証範囲の外(保証範囲の外の構文::型定義の宣言が1行に収まっていない { 型名: "遷移成功結果".to_string() })
    );
}

#[test]
fn 型引数に入れ子の型引数がある宣言は保証範囲の外である() {
    assert_eq!(
        本体の並べ方を採る("pub struct 包み<T: Into<メートル>> {"),
        本体の並べ方::保証範囲の外(保証範囲の外の構文::型定義の型引数に入れ子の型引数がある { 型名: "包み".to_string() })
    );
}

#[test]
fn 関数ポインタを包むタプル構造体の本体は戻り値の矢印を含めて1つの型の表記として区切る() {
    assert_eq!(
        本体の並べ方を採る("pub struct M射影関数<状態: M状態, 射影DTO: M不変データ>(fn(&状態) -> 射影DTO);"),
        本体の並べ方::位置で並べたフィールド(vec!["fn(&状態) -> 射影DTO".to_string()])
    );
}

#[test]
fn 宣言の行が本体の開きにも終わりにも届かない形は保証範囲の外である() {
    assert_eq!(
        本体の並べ方を採る("pub struct 旅行者"),
        本体の並べ方::保証範囲の外(保証範囲の外の構文::型定義の宣言が1行に収まっていない { 型名: "旅行者".to_string() })
    );
}

#[test]
fn 深さの合わない位置で並べた本体は区切れないと答える() {
    assert_eq!(
        本体の並べ方を採る("pub struct 包みの閉じ忘れ(Vec<メートル);"),
        本体の並べ方::保証範囲の外(保証範囲の外の構文::位置で並べた本体の型を区切れない { 型名: "包みの閉じ忘れ".to_string() })
    );
}
