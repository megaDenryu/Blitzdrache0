//! 抽出の規則5の回帰試験のうち、形を縮めた遷移の2つの役割と問い合わせを伴う3つの役割の使用箇所の試験。
//! 抽出器がこの5つの役割の名前を読み、宣言の型引数を事実にすることと、問い合わせを伴う役割の問い合わせ先(トレイトのオブジェクト)と
//! 失敗(パスで修飾した標準の型)の位置が、関係も抽出できなかった行も出さないことを固定する。位置ごとの関係の対応そのものは
//! `crates/blitz_design_verification/src/導出/導出の試験/役割の型引数の位置の規則の試験.rs` が固定する。

use super::test_support::{原文から設計関係グラフと抽出の欠けを組む, 役割の使用箇所の試験が使う型の定義, 抽出できなかった理由の説明一覧, 関係の表記一覧};

const 移動のパス: &str = "crates/blitz_esca/src/歩行の遷移.rs";
const 前置き: &str = "blitz_esca::歩行の遷移::";
const 代表の問い合わせ先: &str = "dyn 世界の形を尋ねる口<問い合わせエラー = std::convert::Infallible>";

// 役割の宣言1行を試験が使う型の定義の後ろへ置いて抽出し、関係の表記の一覧を返す。抽出できなかった行が出たら試験を止める。
fn 宣言1行から抽出した関係の表記一覧(宣言: &str) -> Vec<String> {
    let 原文 = 役割の使用箇所の試験が使う型の定義() + 宣言 + "\n";
    let 結果 = 原文から設計関係グラフと抽出の欠けを組む(&[(移動のパス, &原文)]);
    assert!(結果.抽出できなかった行一覧.is_empty(), "{:?}", 抽出できなかった理由の説明一覧(&結果));
    関係の表記一覧(&結果)
}

// 関係の表記の一覧が、主語の関数からの期待の関係を全部含み、期待の件数ちょうどであることを確かめる。
fn 期待の関係だけを持つ(表記一覧: &[String], 主語の関数: &str, 残り一覧: &[&str]) {
    let 主語 = format!("{前置き}{主語の関数}");
    let 主語の関係: Vec<&String> = 表記一覧.iter().filter(|表記| 表記.starts_with(&format!("{主語} "))).collect();
    for 残り in 残り一覧 {
        let 期待 = format!("{主語} {残り}").replace("型:", 前置き);
        assert!(主語の関係.contains(&&期待), "{期待} が無い: {表記一覧:?}");
    }
    assert_eq!(主語の関係.len(), 残り一覧.len(), "期待していない関係がある: {主語の関係:?}");
}

#[test]
fn 遷移が受け取る命令で決まる遷移関数の宣言を読む() {
    let 表記一覧 = 宣言1行から抽出した関係の表記一覧("const _: M遷移が受け取る命令で決まる遷移関数<旅行者の現在地, 旅行者の意図> = M遷移が受け取る命令で決まる遷移関数::生成する(旅行者の現在地::意図で動かす);");
    期待の関係だけを持つ(&表記一覧, "旅行者の現在地::意図で動かす", &["消費する 型:旅行者の現在地", "生成する 型:旅行者の現在地", "消費する 型:旅行者の意図"]);
}

