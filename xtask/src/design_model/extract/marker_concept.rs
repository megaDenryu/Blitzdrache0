//! 設計解釈マーカーの節点。マーカーの正本は `crates/blitz_design/src/marker.rs` であり、その1つのモジュールパスを節点の識別子へ与える。
//!
//! マーカーの識別子をここ1箇所で組むのは、上位トレイトの宣言(規則1)とマーカーの実装(規則2)が同じマーカーを指す必要があるためである。
//! 別々に組むと、修飾を書いた実装から出た節点と、無修飾の宣言から出た節点が別の節点になり、`M状態 下位型である M不変データ` の経路が繋がらない。
//! 設計語彙のクレートの名前は `ontology_scope` だけが持ち、ここではその名前にモジュールの名前を足してモジュールパスを組む。

use super::ontology_scope::設計語彙のクレート;
use crate::conform::design_ontology::syntax_patterns::設計解釈マーカー;
use crate::design_model::{設計概念, 設計概念の識別子, 設計概念への参照};

/// 設計語彙のクレートの中で、設計解釈マーカーの正本を定義するモジュールの名前。
const マーカーの正本のモジュール: &str = "marker";

/// 設計解釈マーカーの正本のモジュールパス。
pub fn 設計解釈マーカーの正本のモジュールパス() -> String {
    format!("{設計語彙のクレート}::{マーカーの正本のモジュール}")
}

/// マーカーの名前から節点の識別子を組む。
pub fn 設計解釈マーカーの識別子(名前: &str) -> 設計概念の識別子 {
    設計概念の識別子::Rustの項目として生成する(&設計解釈マーカーの正本のモジュールパス(), 名前)
}

/// マーカーの名前から、その節点を指す参照を組む。マーカーはトレイトであるため種類はトレイトである。
pub fn 設計解釈マーカーの参照(名前: &str) -> 設計概念への参照 {
    設計概念への参照::トレイトとして生成する(&設計解釈マーカーの正本のモジュールパス(), 名前)
}

/// その参照が設計解釈マーカーの節点を指すか。名前がマーカーの名前であり、識別子と種類がこのファイルの組む参照と一致するときだけ真である。
/// 名前だけで判定しないのは、ドメインのクレートが同じ名前の型を定義したとき、その型をマーカーと取り違えるためである。
// 受け取る型が外部クレート `blitz_design_verification` の型であり、xtask の側からメソッドを生やせないため自由関数にする。
pub fn 設計解釈マーカーを指す参照か(参照: &設計概念への参照) -> bool {
    let 名前 = &参照.識別子().名前;
    設計解釈マーカーの名前か(名前) && *参照 == 設計解釈マーカーの参照(名前)
}

/// その名前が設計解釈マーカーの名前か。
pub fn 設計解釈マーカーの名前か(名前: &str) -> bool {
    設計解釈マーカー::全部の一覧().iter().any(|マーカー| マーカー.名前() == 名前)
}

/// 全ての設計解釈マーカーをトレイトの節点として並べる。関係へ1件も現れないマーカーも節点として在る。
pub fn 設計解釈マーカーの概念一覧() -> Vec<設計概念> {
    let モジュールパス = 設計解釈マーカーの正本のモジュールパス();
    設計解釈マーカー::全部の一覧().into_iter().map(|マーカー| 設計概念::トレイトとして生成する(&モジュールパス, マーカー.名前())).collect()
}
