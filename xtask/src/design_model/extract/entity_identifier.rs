//! 抽出の規則4: エンティティの識別子の関連型から、エンティティの識別子の関連型の事実を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのはその事実を持つ成果である。関係は出さない(Issue #193 の段階2)。
//!
//! 事実が持つのは、`Mエンティティ` を実装した型と、関連型 `識別子` の右辺の表記である。右辺が名指す型を主語にして
//! エンティティを識別する関係は、定義の式(`blitz_design_verification`)が導く。識別子の側を主語にするのは、同一性を与えるのが識別子の役目であり、
//! エンティティがそれを保持していることは保持する関係が別に言うためである。
//!
//! `type 識別子 =` の行が無い実装は `抽出できなかった行` として数える。`Mエンティティ` はメソッドを持つ唯一のマーカーであり、
//! 実装に本体が在るため、関連型を書き忘れた実装が構文としては存在しうる。右辺の表記を読めるかは定義の式が決め、読めなければ定義の式の欠けとして数える。

use super::outcome::抽出の成果;
use super::source_group::抽出対象のソース群;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::conform::design_ontology::line_matching::波括弧が閉じる行;
use crate::conform::design_ontology::syntax_patterns::設計解釈マーカー;
use crate::design_model::{Rustの項目の種類, 設計概念への参照};
use blitz_design_verification::{エンティティの識別子の関連型の事実, 事実の出どころ, 型の表記};

/// 関連型の宣言の前置き。`type 識別子 = 旅行者ID;` の左辺である。
const 識別子の関連型の前置き: &str = "type 識別子";

pub fn エンティティの識別子の関連型から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for 実装 in ソース群.構文検査().設計解釈マーカーの実装一覧(設計解釈マーカー::Mエンティティ) {
        let Some(行一覧) = ソース群.行一覧(&実装.パス) else {
            continue;
        };
        let Some((位置, 右辺)) = 識別子の関連型を探す(行一覧, 実装.行番号.saturating_sub(1)) else {
            let 理由 = 抽出できなかった理由::エンティティの識別子の関連型が無い { 型名: 実装.型名.clone() };
            成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(&実装.パス, 実装.行番号, 理由));
            continue;
        };
        let (識別子, 欠落) = ソース群.型の識別子を求める(実装.型の在り処の問い());
        成果.抽出できなかった行一覧.extend(欠落);
        成果.事実.エンティティの識別子の関連型一覧.push(エンティティの識別子の関連型の事実 {
            エンティティ: 設計概念への参照::Rustの項目として生成する(識別子, Rustの項目の種類::型),
            表記: 型の表記::型引数の無い場所で生成する(右辺),
            出どころ: 事実の出どころ {
                パス: 実装.パス.clone(), 行番号: 位置 + 1
            },
        });
    }
    成果
}

// `impl Mエンティティ for 型` の本体から、`type 識別子 = 表記;` の最初の行の位置と、右辺の表記を探す。
fn 識別子の関連型を探す(行一覧: &[String], 開始: usize) -> Option<(usize, &str)> {
    let 終了 = 波括弧が閉じる行(行一覧, 開始);
    (開始..=終了).find_map(|位置| {
        let 右辺 = 行一覧[位置].trim().strip_prefix(識別子の関連型の前置き)?.trim_start().strip_prefix('=')?;
        Some((位置, 右辺.trim().trim_end_matches(';').trim()))
    })
}
