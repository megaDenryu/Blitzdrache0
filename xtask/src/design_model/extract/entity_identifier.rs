//! 抽出の規則4: エンティティの識別子の関連型から `識別する` を抽出する工程。
//! 受け取るのは抽出対象のソース群、返すのは識別子の型の節点と `識別する` の関係を持つ成果である。
//!
//! 向きは識別子が主語である(`旅行者ID 識別する 旅行者`)。識別子の側を主語にするのは、同一性を与えるのが識別子の役目であり、
//! エンティティがそれを保持していることは規則3の `保持する` が別に言うためである。2つの関係が同じ向きだと、この2つを命題で区別できない。
//!
//! `type 識別子 =` の行が無い実装は `抽出できなかった行` として数える。`Mエンティティ` はメソッドを持つ唯一のマーカーであり、
//! 実装に本体が在るため、関連型を書き忘れた実装が構文としては存在しうる。

use super::outcome::抽出の成果;
use super::source_group::{型の在り処の問い, 抽出対象のソース群};
use super::type_notation::先頭の型名を採る;
use super::unextracted_line::{抽出できなかった理由, 抽出できなかった行};
use crate::conform::design_ontology::line_matching::波括弧が閉じる行;
use crate::conform::design_ontology::syntax_patterns::オントロジートレイト;
use crate::design_model::{Rustの項目の種類, 設計概念, 設計概念の識別子};
use crate::design_model::{抽出の出どころ, 抽出元の構文, 設計関係, 設計関係の種類};

/// 関連型の宣言の前置き。`type 識別子 = 旅行者ID;` の左辺である。
const 識別子の関連型の前置き: &str = "type 識別子";

pub fn エンティティの識別子の関連型から抽出する(ソース群: &抽出対象のソース群) -> 抽出の成果 {
    let mut 成果 = 抽出の成果::default();
    for 実装 in ソース群.構文検査().トレイト実装型一覧(オントロジートレイト::Mエンティティ) {
        let Some(行一覧) = ソース群.行一覧(&実装.パス) else {
            continue;
        };
        let 開始 = 実装.行番号.saturating_sub(1);
        let Some((位置, 識別子の型名)) = 識別子の関連型を探す(行一覧, 開始) else {
            let 理由 = 抽出できなかった理由::エンティティの識別子の関連型が無い { 型名: 実装.型名.clone() };
            成果.抽出できなかった行一覧.push(抽出できなかった行::生成する(&実装.パス, 実装.行番号, 理由));
            continue;
        };
        let (モジュールパス, 型名) = ソース群.構文検査().型の同一性(&実装);
        let 目的語の節点 = 設計概念::Rustの項目として生成する(設計概念の識別子::Rustの項目として生成する(モジュールパス.表記(), &型名), Rustの項目の種類::型);
        let 目的語 = 目的語の節点.参照を組む();
        let 問い = 型の在り処の問い {
            型名: &識別子の型名,
            参照元のパス: &実装.パス,
            参照元の行番号: 位置 + 1,
        };
        let (主語の識別子, 解決できなかった行) = ソース群.型の識別子を求める(問い);
        成果.抽出できなかった行一覧.extend(解決できなかった行);
        let 主語の節点 = 設計概念::Rustの項目として生成する(主語の識別子, Rustの項目の種類::型);
        let 主語 = 主語の節点.参照を組む();
        成果.概念一覧.push(主語の節点);
        成果.概念一覧.push(目的語の節点);
        成果.関係一覧.push(設計関係 {
            主語,
            種類: 設計関係の種類::識別する,
            目的語,
            出どころ: 抽出の出どころ {
                パス: 実装.パス.clone(),
                行番号: 位置 + 1,
                構文: 抽出元の構文::エンティティの識別子の関連型,
            },
        });
    }
    成果
}

// `impl Mエンティティ for 型` の本体から `type 識別子 = 型;` の行の位置と右辺の型の名前を探す。
fn 識別子の関連型を探す(行一覧: &[String], 開始: usize) -> Option<(usize, String)> {
    let 終了 = 波括弧が閉じる行(行一覧, 開始);
    (開始..=終了).find_map(|位置| {
        let 右辺 = 行一覧[位置].trim().strip_prefix(識別子の関連型の前置き)?.trim_start().strip_prefix('=')?;
        let 型名 = 先頭の型名を採る(右辺.trim().trim_end_matches(';'));
        (!型名.is_empty()).then_some((位置, 型名))
    })
}
