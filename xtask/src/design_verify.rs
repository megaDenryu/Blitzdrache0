//! `cargo xtask design-verify` の入口。設計の命題を検証し、結末ごとの件数を出す(Issue #173「実行入口と検証入口」)。
//!
//! この入口は世界を実行せず、世界について命題を問う。検証の側がゲームロジックを再実装しないため、
//! 問う相手は実装から組んだモデル(設計関係グラフと遷移モデル)だけである。
//! **反証済みが1件でもあれば終了コードを非0にする。未決定は非0にしないが、件数を必ず出す。**
//! 未決定を0件として隠さないのは、検査器が解けなかった入力を黙って対象から外してはならないためである
//! (グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」)。

use std::process::ExitCode;

use crate::design_model::設計関係グラフを抽出する;
use crate::design_proposition::{命題の検証器, 検証の集計, 検証結果, 構造の検証器};
use crate::design_transition::{対戦進行の題材, 有限全数の検証器};

mod extraction_report;
mod structural_law;

/// 結末ごとの件数。検証した命題を数え、終了コードを答える。
#[derive(Debug, Clone, Copy, Default)]
struct 結末の件数 {
    証明済み: usize,
    反証済み: usize,
    未決定: usize,
    導けなかった命題: usize,
}

pub fn 設計の命題を検証する() -> ExitCode {
    let mut 件数 = 結末の件数::default();
    match 設計関係グラフを抽出する() {
        Ok(結末) => {
            println!("[xtask] design-verify: 設計関係グラフの内訳");
            extraction_report::抽出の内訳を表示する(&結末);
            let グラフの検証器 = 構造の検証器::生成する(&結末.グラフ);
            let 集計 = structural_law::構造の法則の命題の集合を組む().全件を検証する(&グラフの検証器);
            println!("  構造の法則: {}", 集計.表記());
            for (名前, 反例) in &集計.反証済みの一覧 {
                println!("    反証済み: {名前}: {}", 反例.説明);
            }
            件数.構造の集計を取り込む(&集計);
        }
        Err(破れ) => {
            eprintln!("[xtask] design-verify: 設計関係グラフを抽出できなかった: {破れ}");
            return ExitCode::FAILURE;
        }
    }
    let 題材 = 対戦進行の題材::生成する();
    let 遷移モデル = 題材.遷移モデルを組む();
    println!("[xtask] design-verify: 代表ケースの遷移モデルは状態{}件・遷移{}件である", 遷移モデル.到達可能な状態一覧を組む().件数(), 遷移モデル.遷移一覧().len());
    let 検証器 = 有限全数の検証器::生成する(遷移モデル);
    件数.結末を1件数える("名指した対戦相手の第5回戦の勝利で専用の事象が発生する", &検証器.検証する(&題材.専用の事象が起きる命題を組む()));
    match 題材.通常の勝利の事象が起きない命題を導く() {
        Some(否定の命題) => 件数.結末を1件数える("名指した対戦相手の第5回戦の勝利で通常の勝利の事象は発生しない(排他の推論規則から導いた)", &検証器.検証する(&否定の命題)),
        None => {
            println!("  導けなかった: 排他の推論規則が正の命題から否定の命題を導けなかった");
            件数.導けなかった命題 += 1;
        }
    }
    件数.結末を表示して終了コードを答える()
}

impl 結末の件数 {
    /// 1件の検証の結末を数え、その1行を表示する。
    fn 結末を1件数える(&mut self, 命題の呼び名: &str, 結末: &検証結果) {
        match 結末 {
            検証結果::証明済み(_) => self.証明済み += 1,
            検証結果::反証済み(_) => self.反証済み += 1,
            検証結果::未決定(_) => self.未決定 += 1,
        }
        println!("  {命題の呼び名}: {}", 結末.表記());
    }

    /// 構造の法則の集計をこの件数へ足す。命題の集合が数えた結末を、入口の集計と別に持たない。
    fn 構造の集計を取り込む(&mut self, 集計: &検証の集計) {
        self.証明済み += 集計.証明済みの件数;
        self.反証済み += 集計.反証済みの件数;
        self.未決定 += 集計.未決定の件数;
    }

    /// 結末ごとの件数を表示し、反証済みが1件でもあれば失敗の終了コードを答える。
    fn 結末を表示して終了コードを答える(&self) -> ExitCode {
        println!(
            "[xtask] design-verify: 証明済み{}件・反証済み{}件・未決定{}件・導けなかった命題{}件",
            self.証明済み, self.反証済み, self.未決定, self.導けなかった命題
        );
        if self.反証済み > 0 || self.導けなかった命題 > 0 {
            return ExitCode::FAILURE;
        }
        ExitCode::SUCCESS
    }
}
