//! `cargo xtask design-verify` の入口。設計関係グラフを抽出し、その上で構造の法則の命題を検証する(Issue #173「実行入口と検証入口」)。
//!
//! この入口は世界を実行せず、世界について命題を問う。検証の側がゲームロジックを再実装しないため、
//! 問う相手は実装から組んだ設計関係グラフだけである。
//! **振る舞いの命題はこの入口が検証しない。** 振る舞いの命題は実物の遷移関数を呼ばなければ検証できず、
//! 呼ぶには `xtask` がドメインのクレートへ依存する必要がある。振る舞いの命題を検証するのはドメインのクレートの試験であり、
//! そのための語彙は `blitz_design_verification` の `有限に数え上げられる領域` が渡す(Issue #174 のオーナー裁定)。
//! **反証済みが1件でもあれば終了コードを非0にする。** この入口が固定するのはここまでであり、
//! **未決定が合否へどう効くかは Issue #175 の設計の受理が決める。** 未決定を失敗として扱うか警告として扱うかは
//! 命題の重要度によって分かれる判断であり、この入口が先取りして確定しない。現在の写し方(未決定は終了コードを変えない)は
//! #175 の裁定までの暫定であり、試験もその暫定を確定事項として固定しない。
//! **命題を1件も検証しなかった実行は非0にする。** これは受理の規則ではなく、検査器が1件も検査していない実行を
//! 合格として答えないという別の規約である。何も検証していないことを合格として答えると、命題の集合が空になった事故が
//! 検証に通った状態と見分けられない。
//! 未決定を0件として隠さないのは、検査器が解けなかった入力を黙って対象から外してはならないためである
//! (グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」)。
//! 抽出の内訳の後に表示する設計関係への参加の計測は、命題の母集団を裁定するための材料であり、命題へ接続しない(Issue #187)。
//! 構造の法則の検証の結果は、計測の区画と別の見出しの下に出す。

use std::process::ExitCode;

use blitz_design_verification::{検証の集計, 構造の検証器};

use crate::design_model::設計関係グラフを抽出する;

mod extraction_report;
#[cfg(test)]
mod outcome_count_tests;
mod structural_law;
#[path = "design_verify/設計関係への参加の計測.rs"]
mod 設計関係への参加の計測;

/// 結果ごとの件数。検証した命題を数え、終了コードを答える。
#[derive(Debug, Clone, Copy, Default)]
struct 検証結果の件数 {
    証明済み: usize,
    反証済み: usize,
    未決定: usize,
}

/// 検証の入口が答える合否。反証済みが1件でもあれば不合格である。
/// 未決定が合否へどう効くかは Issue #175 の設計の受理が決めるため、この型は現時点で未決定を不合格にしない写し方だけを持つ。
/// 判断を選択肢として持つのは、`ExitCode` が `PartialEq` を持たず、終了コードのままでは判断を試験で固定できないためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 設計の検証の合否 {
    /// 検証した命題のどれも反証されなかった。
    反証済みが1件も無い,
    /// 反証された命題が1件以上在る。
    反証済みが在る,
    /// 検証した命題が1件も無い。命題の集合が空であり、何も検証していない。
    検証した命題が1件も無い,
}

pub fn 設計の命題を検証する() -> ExitCode {
    let mut 件数 = 検証結果の件数::default();
    match 設計関係グラフを抽出する() {
        Ok(抽出したもの) => {
            println!("[xtask] design-verify: 設計関係グラフの内訳");
            extraction_report::抽出の内訳を表示する(&抽出したもの);
            // 欠落の件数を検証の前に表示する。表示しないと、検証器が不在を根拠にしてよいかの判断材料が読み手に見えない。
            let 欠落 = 抽出したもの.関係を落とした抽出の欠落へ写す();
            println!("  {}", 欠落.説明());
            println!("[xtask] design-verify: 設計関係へ参加していない概念の計測");
            print!("{}", 設計関係への参加の計測::設計関係への参加の計測::計測する(&抽出したもの, &欠落));
            let グラフの検証器 = 構造の検証器::生成する(&抽出したもの.グラフ, 欠落);
            let 集計 = structural_law::構造の法則の命題の集合を組む().全件を検証する(&グラフの検証器);
            // 見出しを分けるのは、構造の法則の結果が上の計測の区画の一部として読まれないためである。計測は命題へ接続していない。
            println!("[xtask] design-verify: 構造の法則の検証");
            println!("  構造の法則: {}", 集計.表記());
            for (名前, 反例) in &集計.反証済みの一覧 {
                println!("    反証済み: {名前}: {}", 反例.説明);
            }
            // 未決定の理由を件数だけで済ませない。何を解けなかったかを読めないと、抽出の欠落で未決定へ落ちた命題と
            // この検証器が扱わない命題を読み手が区別できない。
            for (名前, 理由) in &集計.未決定の一覧 {
                println!("    未決定: {名前}: {理由:?}");
            }
            件数.構造の集計を取り込む(&集計);
        }
        Err(破れ) => {
            eprintln!("[xtask] design-verify: 設計関係グラフを抽出できなかった: {破れ}");
            return ExitCode::FAILURE;
        }
    }
    件数.結果を表示して終了コードを答える()
}

impl 検証結果の件数 {
    /// 構造の法則の集計をこの件数へ足す。命題の集合が数えた結果を、入口の集計と別に持たない。
    fn 構造の集計を取り込む(&mut self, 集計: &検証の集計) {
        self.証明済み += 集計.証明済みの件数;
        self.反証済み += 集計.反証済みの件数;
        self.未決定 += 集計.未決定の件数;
    }

    /// 反証済みの件数から合否を答える。未決定の件数が合否へどう効くかは Issue #175 が決めるため、現時点ではこの判断へ効かない。
    /// **3つとも0件のときは合格を答えない。** 命題を1件も検証していない実行が合格を名乗ると、命題の集合が空になった事故が
    /// 検証に通った状態と見分けられなくなる(グローバルCLAUDE.md「検査器は解析できなかった入力を黙って対象から外してはならない」)。
    fn 合否を答える(&self) -> 設計の検証の合否 {
        if self.反証済み > 0 {
            return 設計の検証の合否::反証済みが在る;
        }
        if self.検証した命題の件数() == 0 {
            return 設計の検証の合否::検証した命題が1件も無い;
        }
        設計の検証の合否::反証済みが1件も無い
    }

    /// 結果ごとの件数の合計。合否の判断が、1件も検証していない実行をこの合計で見分ける。
    fn 検証した命題の件数(&self) -> usize {
        self.証明済み + self.反証済み + self.未決定
    }

    /// 結果ごとの件数を表示し、合否を写した終了コードを答える。
    fn 結果を表示して終了コードを答える(&self) -> ExitCode {
        println!("[xtask] design-verify: 証明済み{}件・反証済み{}件・未決定{}件", self.証明済み, self.反証済み, self.未決定);
        let 合否 = self.合否を答える();
        if 合否 == 設計の検証の合否::検証した命題が1件も無い {
            eprintln!("[xtask] design-verify: 検証した命題が1件も無い(命題の集合が空である)。検証していないことを合格として答えない");
        }
        合否.終了コードへ写す()
    }
}

impl 設計の検証の合否 {
    /// 合否をプロセスの終了コードへ写す。写すのはこの1箇所だけである。
    fn 終了コードへ写す(self) -> ExitCode {
        match self {
            Self::反証済みが1件も無い => ExitCode::SUCCESS,
            Self::反証済みが在る | Self::検証した命題が1件も無い => ExitCode::FAILURE,
        }
    }
}
