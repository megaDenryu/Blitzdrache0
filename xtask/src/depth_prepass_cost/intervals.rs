//! 計測するGPU計器の区間の一覧。担当するのは「どのパス名を何の役割の区間として読むか」だけである。
//!
//! 名前の正本は積む側にあり、`crates/blitz_render/src/vulkan/frame/record/pass_names.rs`が
//! パス宣言と合成区間の宣言の両方へ同じ語を配っている。

/// 深度プリパスを積む条件だけに立つ区間。
pub(super) const 深度プリパスの区間名: &str = "深度プリパス";

/// どの条件にも立つ色パスの区間。
pub(super) const 色パスの区間名: &str = "シーン描画";

/// 上の2区間をフレーム内で足した合成の区間。**両者の合計はこの区間の分位で語る**。
/// 分位の加法性は一般に成立しないため、2区間それぞれの分位を足した値は1フレームの合計の分位ではない。
/// 深度プリパスを積まない条件ではこの区間の標本が1つも立たない(足す相手が無いため)。
pub(super) const 合計の区間名: &str = "深度プリパスとシーン描画の合計";

/// 報告と生値に並べる全区間。深度プリパス・色パス・合計をこの順で並べる。
pub(super) const 全区間一覧: [&str; 3] = [深度プリパスの区間名, 色パスの区間名, 合計の区間名];
