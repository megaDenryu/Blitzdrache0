//! 分位の突き合わせの検査。生標本と合う報告を通し、合わない報告と件数の食い違いを落とすことを見る。
//! 併せて、最近傍順位法が補間せずに実在の標本そのものを選ぶことを反証する。

#![allow(clippy::unwrap_used)]

use super::super::intervals;
use super::super::record::{フレーム別の生値, 一標本, 区間の分布, 区間の観測};
use super::{報告の分位が生標本から再現されることを確かめる, 順位の値};

/// 4つの値を持つ窓。昇順に並べると0.10・0.20・0.30・0.40である。
/// 最近傍順位法の添字は`ceil(百分位 × 3 / 100)`であるため、p50は添字2の0.30、p95は添字3の0.40になる。
fn 生値一覧() -> Vec<フレーム別の生値> {
    [0.30, 0.10, 0.40, 0.20]
        .iter()
        .enumerate()
        .map(|(読み取り順, 値)| フレーム別の生値 {
            読み取り順: u64::try_from(読み取り順).unwrap(),
            区間名: intervals::色パスの区間名.to_string(),
            経過ミリ秒: *値,
        })
        .collect()
}

fn 標本(p50: f64, p95: f64, 標本数: u64) -> 一標本 {
    let 区間別 = intervals::全区間一覧
        .iter()
        .map(|区間名| {
            if *区間名 == intervals::色パスの区間名 {
                区間の観測::測れた(区間の分布 {
                    平均ミリ秒: 0.25,
                    第50百分位ミリ秒: p50,
                    第95百分位ミリ秒: p95,
                    標本数,
                })
            } else {
                区間の観測::積まない
            }
        })
        .collect();
    一標本 {
        実行番号: 0,
        周回番号: 0,
        順序位置: 0,
        条件名: "A",
        区間別,
        窓の標本数: 60,
        フレーム別の値一覧: 生値一覧(),
    }
}

#[test]
fn 生標本と合う報告を通す() {
    assert!(報告の分位が生標本から再現されることを確かめる(&[標本(0.30, 0.40, 4)]).is_ok());
}

#[test]
fn 生標本と合わない報告を落とす() {
    assert!(
        報告の分位が生標本から再現されることを確かめる(&[標本(0.25, 0.40, 4)]).is_err(),
        "p50の食い違いを見逃した"
    );
    assert!(
        報告の分位が生標本から再現されることを確かめる(&[標本(0.20, 0.35, 4)]).is_err(),
        "p95の食い違いを見逃した"
    );
}

/// 件数が合わないのは、生値の記録と窓の更新が別の列を見ている状態である。値が偶然一致しても通してはならない。
#[test]
fn 件数の食い違いを落とす() {
    assert!(報告の分位が生標本から再現されることを確かめる(&[標本(0.30, 0.40, 3)]).is_err());
}

/// 線形補間する求め方なら4件の窓の中央値は0.25になる。実在の標本そのものを選ぶことがこの値の違いに出ている。
#[test]
fn 最近傍順位法は実在の標本を選ぶ() {
    let 昇順 = [0.10, 0.20, 0.30, 0.40];
    assert!((順位の値(&昇順, 50) - 0.30).abs() < 1.0e-9);
    assert!((順位の値(&昇順, 95) - 0.40).abs() < 1.0e-9);
    assert!((順位の値(&[0.70], 50) - 0.70).abs() < 1.0e-9, "標本1件のときは値そのものを返す");
}
