//! 採れた値のファイルへの書き出し。受け取るのは書き先と標本の並び、返すものは無い。
//!
//! 生値と窓の集約を別のファイルへ分けるのは、1行が持つ意味が違うためである。
//! 生値の1行は1フレームの1区間の値であり、集約の1行は1実行ぶんの窓から求めた代表値である。
//! 混ぜると、読み手が列の中身からどちらの行かを判じることになる。
//!
//! どちらのファイルも先頭に構築の由来の注記を置く。値だけを見ても、どの基準から作ったバイナリで測ったかが
//! 後から分からないためである。未追跡のファイルが在れば、そのパスも1行1件で続けて置く(構築や実行の入力で
//! なかったことを後日読む人が自分で確かめられるようにするため)。井桁で始めるのは、表を読む道具が見出しより
//! 前の行を注記として飛ばせる形に揃えるためである。

use std::path::Path;

use crate::release_build::構築の由来;

use super::super::intervals;
use super::{一標本, 区間の観測};

pub(in super::super) fn 生値を書く(書き先: &Path, 標本一覧: &[一標本], 由来: &構築の由来) -> Result<(), String> {
    let mut 本文 = 由来の行(由来);
    本文.push_str("実行番号\t周回\t順序位置\t条件\t読み取り順\t区間\t経過ミリ秒\n");
    for 標本 in 標本一覧 {
        for 生値 in &標本.フレーム別の値一覧 {
            本文.push_str(&format!(
                "{}\t{}\t{}\t{}\t{}\t{}\t{:.4}\n",
                標本.実行番号, 標本.周回番号, 標本.順序位置, 標本.条件名, 生値.読み取り順, 生値.区間名, 生値.経過ミリ秒
            ));
        }
    }
    書く(書き先, &本文)
}

pub(in super::super) fn 窓の集約を書く(書き先: &Path, 標本一覧: &[一標本], 由来: &構築の由来) -> Result<(), String> {
    let mut 本文 = 由来の行(由来);
    本文.push_str("実行番号\t周回\t順序位置\t条件\t区間\t平均ミリ秒\tp50ミリ秒\tp95ミリ秒\t標本数\n");
    for 標本 in 標本一覧 {
        for (区間名, 観測) in intervals::全区間一覧.iter().zip(&標本.区間別) {
            本文.push_str(&行にする(標本, 区間名, *観測));
        }
    }
    書く(書き先, &本文)
}

fn 行にする(標本: &一標本, 区間名: &str, 観測: 区間の観測) -> String {
    let 前置き = format!("{}\t{}\t{}\t{}\t{区間名}", 標本.実行番号, 標本.周回番号, 標本.順序位置, 標本.条件名);
    match 観測 {
        区間の観測::積まない => format!("{前置き}\t積まない\t積まない\t積まない\t0\n"),
        区間の観測::測れた(分布) => format!(
            "{前置き}\t{:.4}\t{:.4}\t{:.4}\t{}\n",
            分布.平均ミリ秒, 分布.p50ミリ秒, 分布.p95ミリ秒, 分布.標本数
        ),
    }
}

fn 書く(書き先: &Path, 本文: &str) -> Result<(), String> {
    std::fs::write(書き先, 本文).map_err(|誤り| format!("{}を書けなかった: {誤り}", 書き先.display()))
}

/// 見出しより前に置く注記の行。計測に使ったバイナリの由来をここだけで確かめられるようにする。
fn 由来の行(由来: &構築の由来) -> String {
    format!(
        "# 計測に使ったバイナリ {}
",
        由来.一行にする()
    )
}
