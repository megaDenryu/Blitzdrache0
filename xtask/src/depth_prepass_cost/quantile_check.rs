//! 報告された分位を、フレーム別の生標本から独立に計算し直して突き合わせる工程。
//! 受け取るのは標本の並び、返すものは無く、1つでも合わなければ失敗にする。
//!
//! 突き合わせが要るのは、報告の分位が窓の集約であり、集約だけでは元の列を復元できないためである。
//! 生標本の列から同じ値が出ることを確かめて初めて、その列が報告の裏付けとして読める。
//!
//! 分位の求め方をこちらでもう一度書くのは、意図した重複である。報告する側の関数を呼んで比べると、
//! その関数が誤っていたときに両方が同じ誤り方をして必ず一致する。独立に書いた実装との一致だけが証拠になる。
//! 求め方は最近傍順位法(補間しない)であり、昇順に並べた標本の添字を`ceil(百分位 × (件数-1) / 100)`で選ぶ。
//!
//! 4桁へ丸めた生値から厳密に一致するのは、丸めが単調であり、最近傍順位法が実在の標本そのものを選ぶためである。
//! 単調な丸めは並び順を保つため、丸めた列の第k順位は元の列の第k順位を丸めた値と必ず等しい。

#[cfg(test)]
mod quantile_check_tests;

use super::intervals;
use super::record::{一標本, 区間の観測};

/// 4桁で書かれた値どうしの比較であるため、食い違いは丸めの誤差でなく計算の誤りである。
const 許容: f64 = 1.0e-9;

pub(super) fn 報告の分位が生標本から再現されることを確かめる(標本一覧: &[一標本]) -> Result<(), String> {
    for 標本 in 標本一覧 {
        for (区間名, 観測) in intervals::全区間一覧.iter().zip(&標本.区間別) {
            let 区間の観測::測れた(分布) = 観測 else {
                continue;
            };
            一区間を確かめる(標本, 区間名, *分布)?;
        }
    }
    Ok(())
}

fn 一区間を確かめる(標本: &一標本, 区間名: &str, 分布: super::record::区間の分布) -> Result<(), String> {
    let 窓: Vec<f64> = 標本
        .フレーム別の値一覧
        .iter()
        .filter(|生値| 生値.区間名 == 区間名)
        .map(|生値| 生値.経過ミリ秒)
        .rev()
        .take(標本.窓の標本数)
        .collect();
    let 前置き = format!("実行{}({})の区間{区間名}", 標本.実行番号, 標本.条件名);
    if 窓.len() != 分布.標本数を数へ() {
        return Err(format!(
            "{前置き}: 生標本から採れた窓の件数{}が報告の標本数{}と違う",
            窓.len(),
            分布.標本数
        ));
    }
    let mut 昇順 = 窓;
    昇順.sort_by(f64::total_cmp);
    突き合わせる(&前置き, "p50", 順位の値(&昇順, 50), 分布.p50ミリ秒)?;
    突き合わせる(&前置き, "p95", 順位の値(&昇順, 95), 分布.p95ミリ秒)
}

fn 突き合わせる(前置き: &str, 名前: &str, 計算し直した値: f64, 報告値: f64) -> Result<(), String> {
    if (計算し直した値 - 報告値).abs() <= 許容 {
        return Ok(());
    }
    Err(format!(
        "{前置き}: 生標本から計算し直した{名前}が{計算し直した値:.4}で、報告値{報告値:.4}と違う"
    ))
}

/// 昇順に並んだ標本の百分位。最近傍順位法であり、標本が1件のときはその値そのものを返す。
pub(super) fn 順位の値(昇順: &[f64], 百分位: usize) -> f64 {
    let 上限 = 昇順.len().saturating_sub(1);
    let 添字 = (百分位 * 上限).div_ceil(100);
    昇順.get(添字.min(上限)).copied().unwrap_or(0.0)
}
