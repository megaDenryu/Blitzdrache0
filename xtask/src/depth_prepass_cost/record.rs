//! 1回の実行から採れた値と、全標本の生値ファイルへの書き出し。担当するのは値の形と、順序を落とさずに残すことである。
//!
//! 生値を残すのは、表に出す代表値だけでは「どの順番で採った値か」が失われるためである。
//! 1周目と2周目の食い違いを後から疑うには、実行番号と条件名を付けた1行1区間の並びが要る。
//!
//! 注意: 1行が持つのは1実行ぶんの窓の集約(平均・p50・p95・標本数)であり、フレーム1枚ごとの値ではない。
//! フレーム別の証拠が要るときは、同じディレクトリに残る実行ごとの標準出力(`run_<番号>_<条件>.log`)が唯一の記録になる。

use std::path::Path;

use super::intervals;

#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 区間の分布 {
    pub(super) 平均ミリ秒: f64,
    pub(super) p50ミリ秒: f64,
    pub(super) p95ミリ秒: f64,
    pub(super) 標本数: u64,
}

/// その条件でその区間が観測されたかどうか。深度プリパスを積まない条件では、プリパスと合計の区間がそもそも立たない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 区間の観測 {
    /// その条件はその区間を積まない。値が無いことがその条件の性質である。
    積まない,
    測れた(区間の分布),
}

pub(super) struct 一標本 {
    /// 起動した順の通し番号。0から始まり、交互の並びがそのまま並ぶ。
    pub(super) 実行番号: usize,
    pub(super) 条件名: &'static str,
    /// 添字が`intervals::全区間一覧`の添字である。
    pub(super) 区間別: Vec<区間の観測>,
}

impl 一標本 {
    /// 標本の中身が並びの前提どおりかを確かめる検査だけが読む。表と生値は並びごと走査する。
    #[cfg(test)]
    pub(super) fn 区間を参照する(&self, 区間名: &str) -> Option<区間の観測> {
        let 添字 = intervals::全区間一覧.iter().position(|名前| *名前 == 区間名)?;
        self.区間別.get(添字).copied()
    }
}

pub(super) fn 生値を書く(書き先: &Path, 標本一覧: &[一標本]) -> Result<(), String> {
    let mut 本文 = String::from("実行番号\t条件\t区間\t平均ミリ秒\tp50ミリ秒\tp95ミリ秒\t標本数\n");
    for 標本 in 標本一覧 {
        for (区間名, 観測) in intervals::全区間一覧.iter().zip(&標本.区間別) {
            本文.push_str(&行にする(標本, 区間名, *観測));
        }
    }
    std::fs::write(書き先, 本文).map_err(|誤り| format!("{}を書けなかった: {誤り}", 書き先.display()))
}

fn 行にする(標本: &一標本, 区間名: &str, 観測: 区間の観測) -> String {
    match 観測 {
        区間の観測::積まない => format!("{}\t{}\t{区間名}\t積まない\t積まない\t積まない\t0\n", 標本.実行番号, 標本.条件名),
        区間の観測::測れた(分布) => format!(
            "{}\t{}\t{区間名}\t{:.4}\t{:.4}\t{:.4}\t{}\n",
            標本.実行番号, 標本.条件名, 分布.平均ミリ秒, 分布.p50ミリ秒, 分布.p95ミリ秒, 分布.標本数
        ),
    }
}
