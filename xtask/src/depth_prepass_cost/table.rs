//! 採れた値を表として並べる工程。受け取るのは標本の並びと同値性の観測、返すものは無く、標準出力へ書く。
//!
//! 深度プリパスを積まない条件で合計の行が空になるのは、足す相手が無いためである。その条件の1フレームの合計は
//! 色パスの区間そのものであり、別の値を作って埋めない。

use super::equality;
use super::intervals;
use super::record::{一標本, 区間の観測};

pub(super) fn 表示する(標本一覧: &[一標本], 観測一覧: &[equality::観測]) {
    println!("深度プリパスの費用(1実行の窓の集約、単位ミリ秒):");
    println!("実行\t周回\t順序位置\t条件\t区間\t平均\tp50\tp95\t標本数");
    for 標本 in 標本一覧 {
        for (区間名, 観測) in intervals::全区間一覧.iter().zip(&標本.区間別) {
            print_行(標本, 区間名, *観測);
        }
    }
    println!("同値性の検収(合否は判定しない。事実として残す):");
    println!("画像\t基準\t相手\t一致\t食い違いバイト数\t全バイト数");
    for 観測 in 観測一覧 {
        println!(
            "{}\t{}\t{}\t{}\t{}\t{}",
            観測.画像の呼び名,
            観測.基準の条件名,
            観測.相手の条件名,
            if 観測.一致するか { "する" } else { "しない" },
            観測.食い違いバイト数,
            観測.全バイト数
        );
    }
}

/// 周回と順序位置を条件の手前へ置くのは、同じ条件の3行が周回のどこで採られたかを、読み手が横へ目を動かさずに追えるようにするためである。
fn print_行(標本: &一標本, 区間名: &str, 観測: 区間の観測) {
    let 前置き = format!("{}\t{}\t{}\t{}\t{区間名}", 標本.実行番号, 標本.周回番号, 標本.順序位置, 標本.条件名);
    match 観測 {
        区間の観測::積まない => println!("{前置き}\t積まない\t積まない\t積まない\t0"),
        区間の観測::測れた(分布) => {
            println!(
                "{前置き}\t{:.4}\t{:.4}\t{:.4}\t{}",
                分布.平均ミリ秒, 分布.p50ミリ秒, 分布.p95ミリ秒, 分布.標本数
            );
        }
    }
}
