//! 同値性の検収。担当するのは、三条件の最終深度と提示前HDRを撮って、AとB・AとCをそれぞれ突き合わせ、観測を行にすることである。
//!
//! 深度と色を別々に見るのは、色が一致していても深度が違う状態が成立するためである。1つの判定へまとめると、
//! 条件の食い違いをどちらの側の破れとも決められない。
//! 3対すべてを突き合わせるのは、AとBの差とAとCの差だけではBとCが同じかどうかを読み手が決められないためである。
//! BとCの差は色パスの深度の比べ方だけから来るため、この対だけがCの不変性を直に示す。
//! 合否を出さないのは、正本が「Cの不変性が立たなくてもIIa-2以降を止めない」と定めているためである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。

mod compare;
mod dump_run;

use std::path::PathBuf;

use dump_run::ダンプの別;

use super::plan::実行の指定;
use super::schedule::{三条件, 実行条件};
use super::world;
use crate::acceptance::{描画フレーム数, 描画検収の実行環境, 検収の実行名};

/// 撮影に使うフレーム数。ストリーミングが定常へ入り、絵が条件だけで決まる状態まで進める本数である。
const 撮影のフレーム数: 描画フレーム数 = 描画フレーム数::生成する(120);

/// 1つの突き合わせの観測。どの画像をどの条件の対で比べたかと、その結果を持つ。
pub(super) struct 観測 {
    pub(super) 画像の呼び名: &'static str,
    pub(super) 基準の条件名: &'static str,
    pub(super) 相手の条件名: &'static str,
    pub(super) 一致するか: bool,
    pub(super) 食い違いバイト数: usize,
    pub(super) 全バイト数: usize,
}

pub(super) fn 検収する(出力先: PathBuf, 指定: &実行の指定) -> Result<Vec<観測>, String> {
    let 実行環境 = world::撮影の実行環境を作る(出力先)?;
    let mut 観測一覧 = Vec::new();
    for 別 in [ダンプの別::最終深度, ダンプの別::圧縮前のHDR] {
        for 条件 in &三条件 {
            println!("[xtask] depth-prepass-cost撮影: {}の{}", 条件.名前, 別.呼び名());
            dump_run::撮る(&実行環境, 条件, 別, 実行名を組む(別, 条件)?, 指定.一日内秒.as_ref(), 撮影のフレーム数)?;
        }
        for (基準の添字, 基準) in 三条件.iter().enumerate() {
            for 相手 in &三条件[基準の添字 + 1..] {
                観測一覧.push(対を突き合わせる(&実行環境, 別, 基準, 相手)?);
            }
        }
    }
    Ok(観測一覧)
}

fn 対を突き合わせる(
    実行環境: &描画検収の実行環境, 別: ダンプの別, 基準: &実行条件, 相手: &実行条件
) -> Result<観測, String> {
    let 形式 = 別.書き出しの形式();
    let 結果 = compare::突き合わせる(
        &実行環境.同じ置き場の書き出しのバイト列を読む(実行名を組む(別, 基準)?, 形式)?,
        &実行環境.同じ置き場の書き出しのバイト列を読む(実行名を組む(別, 相手)?, 形式)?,
    )?;
    Ok(観測 {
        画像の呼び名: 別.呼び名(),
        基準の条件名: 基準.名前,
        相手の条件名: 相手.名前,
        一致するか: 結果.一致するか,
        食い違いバイト数: 結果.食い違いバイト数,
        全バイト数: 結果.全バイト数,
    })
}

/// その画像とその条件の書き出しを指す名前。画像の別を前置きに使い、深度と色の書き出しが同じ名前を取らないようにする。
fn 実行名を組む(別: ダンプの別, 条件: &実行条件) -> Result<検収の実行名, crate::acceptance::検収エラー> {
    条件.実行名を組む(別.実行名の前置き())
}
