//! 機械判定。担当するのは、測った値が読める状態であることの確認だけである。
//!
//! 費用の合否は判定しない。予算との突き合わせはマイルストーンの定点で評価軸を更新するときに人が行う。
//! 同値性も合否にしない。正本が「Cの不変性が立たなくてもIIa-2以降を止めない」と定めているためである。
//! ここが持つのは1つだけであり、測れた区間の値がすべて有限であることである。
//! 残りの機械判定は別の場所にある。validationの指摘が0件であることは起動のたびに`run`と`equality`が、
//! 条件と実際に立った区間が食い違わないことは`parse`が、報告した分位がフレーム別の生標本から再現されることは
//! `quantile_check`が確かめる。

use super::intervals;
use super::record::{一標本, 区間の観測};

pub(super) fn 値が有限であることを確かめる(標本一覧: &[一標本]) -> Result<(), String> {
    for 標本 in 標本一覧 {
        for (区間名, 観測) in intervals::全区間一覧.iter().zip(&標本.区間別) {
            let 区間の観測::測れた(分布) = 観測 else {
                continue;
            };
            let 値一覧 = [分布.平均ミリ秒, 分布.p50ミリ秒, 分布.p95ミリ秒];
            if 値一覧.iter().any(|値| !値.is_finite()) {
                return Err(format!(
                    "実行{}({})の区間{区間名}に非有限の値がある: {値一覧:?}",
                    標本.実行番号, 標本.条件名
                ));
            }
        }
    }
    Ok(())
}
