//! 深度プリパスの費用計測エラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::深度プリパスの費用計測エラー;

impl fmt::Display for 深度プリパスの費用計測エラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::知らない引数を渡された { 語 } => {
                write!(書き手, "知らない引数({語})。使えるのは--framesと--time-of-dayである")
            }
            Self::引数の次に値が無い { 引数名 } => write!(書き手, "{引数名}の次に値が無い"),
            Self::引数の値を数として読めない { 引数名, 語 } => {
                write!(書き手, "{引数名}の値を数として読めない({語})")
            }
            Self::フレーム数が零である => write!(書き手, "--framesは1以上である必要がある"),
            Self::検証用アセットを生成できなかった => write!(書き手, "検証用アセットの生成に失敗した"),
            Self::出力先を作れなかった { 誤り } => write!(書き手, "出力先を作れなかった: {誤り}"),
            Self::実行の標準出力を書けなかった { パス, 誤り } | Self::計測の結果を書けなかった { パス, 誤り } => {
                write!(書き手, "{}を書けなかった: {誤り}", パス.display())
            }
            Self::計測用の構築が失敗した { 理由 } | Self::シェーダーの一時コピーを作れなかった { 理由 } => {
                write!(書き手, "{理由}")
            }
        }
    }
}
