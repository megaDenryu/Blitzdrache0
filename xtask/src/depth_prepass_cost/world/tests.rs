//! 3条件が同じ世界で走り、違うのは深度プリパスの方式だけであることを固定する。
//!
//! これが要るのは、3条件の目的が深度プリパスの費用対効果を分離することだからである。世界の側が条件ごとに
//! 違えば、測った差はプリパスの差ではなくなる。局所可視性補正の有無はその代表であり、補正を宣言した世界は
//! 深度プリパスの方式を引き上げるため、切り忘れると条件Aが型付きの失敗で起動すらしない。

use super::計測の起動指定を組み立てる;
use crate::acceptance::描画フレーム数;
use crate::depth_prepass_cost::schedule::起動の並び;

const 検査の枚数: 描画フレーム数 = 描画フレーム数::生成する(1);

#[test]
fn どの条件の起動指定も局所可視性補正を切る() {
    for (_, 条件) in 起動の並び() {
        let 指定 = 計測の起動指定を組み立てる(検査の枚数, 条件, None);
        assert!(指定.選択肢を含むか("--no-ssao"), "条件{}の起動指定に--no-ssaoが無い", 条件.名前);
    }
}

/// 3条件が3つの別々の深度プリパスの方式を選ぶことを見る。同じ方式が2つあれば、測った差は方式の差でなくなる。
#[test]
fn 条件ごとに違うのは深度プリパスの方式だけである() {
    let mut 方式の語一覧: Vec<&str> = 起動の並び().into_iter().map(|(_, 条件)| 条件.方式.起動指定の語()).collect();
    方式の語一覧.sort_unstable();
    方式の語一覧.dedup();
    assert_eq!(方式の語一覧.len(), 3, "3条件が3つの別々の方式を選んでいない: {方式の語一覧:?}");
}
