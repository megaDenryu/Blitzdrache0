//! 3条件が同じ世界で走り、違うのは深度プリパスの方式だけであることを固定する。
//!
//! これが要るのは、3条件の目的が深度プリパスの費用対効果を分離することだからである。世界の側が条件ごとに
//! 違えば、測った差はプリパスの差ではなくなる。局所可視性補正の有無はその代表であり、補正を宣言した世界は
//! 深度プリパスの方式を引き上げるため、切り忘れると条件Aが型付きの失敗で起動すらしない。

use super::{世界の引数, 条件の引数};
use crate::depth_prepass_cost::schedule::起動の並び;

#[test]
fn 世界の引数は局所可視性補正を切る() {
    assert!(世界の引数().iter().any(|語| 語 == "--no-ssao"), "世界の引数に--no-ssaoが無い");
}

/// 3条件が世界の引数を共有し、条件ごとの引数は深度プリパスの方式だけであることを見る。
#[test]
fn 条件ごとに違うのは深度プリパスの方式だけである() {
    let mut 方式の語一覧 = Vec::new();
    for (_, 条件) in 起動の並び() {
        let 引数 = 条件の引数(条件);
        assert_eq!(引数.len(), 2, "条件{}の引数が深度プリパスの指定だけでない: {引数:?}", 条件.名前);
        assert_eq!(引数[0], "--depth-prepass");
        方式の語一覧.push(引数[1].clone());
    }
    方式の語一覧.sort_unstable();
    方式の語一覧.dedup();
    assert_eq!(方式の語一覧.len(), 3, "3条件が3つの別々の方式を選んでいない: {方式の語一覧:?}");
}

/// 世界の引数が条件を1つも読まないことを、同じ呼び出しが常に同じ並びを返すことで固定する。
#[test]
fn 世界の引数は条件に依らない() {
    assert_eq!(世界の引数(), 世界の引数());
}
