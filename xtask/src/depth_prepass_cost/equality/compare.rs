//! 撮った2枚のバイト列を突き合わせる工程。受け取るのは2条件のダンプ先、返すのは一致の観測である。
//!
//! 一致を合否にしないのは、正本が「Cの不変性が立たなくてもIIa-2以降を止めない」と定めているためである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。ここは事実だけを残す。
//! 食い違いの件数を数えるのは、一致か不一致かだけでは「どの程度の破れか」が読み手に決められないためである。

use std::path::Path;

/// 2条件のバイト列の突き合わせの結果。
pub(super) struct 突き合わせ {
    pub(super) 一致するか: bool,
    /// 食い違ったバイトの数。一致していれば0である。
    pub(super) 食い違いバイト数: usize,
    pub(super) 全バイト数: usize,
}

pub(super) fn 突き合わせる(基準: &Path, 相手: &Path, 拡張子: &str) -> Result<突き合わせ, String> {
    let 基準の並び = 読む(基準, 拡張子)?;
    let 相手の並び = 読む(相手, 拡張子)?;
    if 基準の並び.len() != 相手の並び.len() {
        return Err(format!(
            "{}と{}のバイト長が違う: {}と{}",
            基準.display(),
            相手.display(),
            基準の並び.len(),
            相手の並び.len()
        ));
    }
    let 食い違いバイト数 = 基準の並び.iter().zip(&相手の並び).filter(|(左, 右)| 左 != 右).count();
    Ok(突き合わせ {
        一致するか: 食い違いバイト数 == 0,
        食い違いバイト数,
        全バイト数: 基準の並び.len(),
    })
}

fn 読む(ダンプ先: &Path, 拡張子: &str) -> Result<Vec<u8>, String> {
    let パス = ダンプ先.with_extension(拡張子);
    std::fs::read(&パス).map_err(|誤り| format!("{}を読めない: {誤り}", パス.display()))
}
