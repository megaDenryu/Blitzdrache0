//! 撮った2枚のバイト列を突き合わせる工程。受け取るのは2条件の書き出しのバイト列、返すのは一致の観測である。
//!
//! 一致を合否にしないのは、正本が「Cの不変性が立たなくてもIIa-2以降を止めない」と定めているためである
//! (参照: `_doc/設計/放射輝度問い合わせ階層.md`「IIaの実装設計」)。ここは事実だけを残す。
//! 食い違いの件数を数えるのは、一致か不一致かだけでは「どの程度の破れか」が読み手に決められないためである。

use crate::acceptance::{判定の名前, 判定の破れ};

/// 突き合わせる2枚のバイト長が同じことを見る判定。長さが違えば同じ添字が2枚で別の場所を指す。
const 突き合わせる2つの書き出しのバイト長: 判定の名前 = 判定の名前::定数から生成する("突き合わせる2つの書き出しのバイト長");

/// 2条件のバイト列の突き合わせの結果。
pub(super) struct 突き合わせ {
    pub(super) 一致するか: bool,
    /// 食い違ったバイトの数。一致していれば0である。
    pub(super) 食い違いバイト数: usize,
    pub(super) 全バイト数: usize,
}

pub(super) fn 突き合わせる(基準の並び: &[u8], 相手の並び: &[u8]) -> Result<突き合わせ, 判定の破れ> {
    突き合わせる2つの書き出しのバイト長.一致を課す(相手の並び.len(), 基準の並び.len())?;
    let 食い違いバイト数 = 基準の並び.iter().zip(相手の並び).filter(|(左, 右)| 左 != 右).count();
    Ok(突き合わせ {
        一致するか: 食い違いバイト数 == 0,
        食い違いバイト数,
        全バイト数: 基準の並び.len(),
    })
}
