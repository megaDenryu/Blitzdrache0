//! 終了時報告から1標本ぶんの値を取り出す工程。受け取るのは終了時報告と実行番号と条件、返すのは区間ごとの観測を持つ標本である。
//!
//! GPU時間の行の綴りは`crates/blitz_app/src/reports/gpu_time_table.rs`の出力と一致させている。
//! 「平均 (p50 X / p95 Y / 標本N)」の形であり、平均は区間名の鍵の次の1語、分位は開き括弧が触れた鍵の次の1語、
//! 標本数は鍵に続く残りである。
//!
//! 積むはずの区間が欠けていたら失敗にする。積まないはずの区間が立っていても失敗にする。
//! どちらも「測ろうとした条件と実際に走った条件が違う」ことを意味しており、値が採れないまま表だけが出る事態を避ける。

mod frame_samples;
#[cfg(test)]
mod parse_tests;

use super::intervals;
use super::record::{一標本, 区間の分布, 区間の観測};
use super::schedule::{周回の位置, 実行条件};
use crate::acceptance::{判定の名前, 報告の区画, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 表の見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間");
/// 分位の鍵。分布の行では開き括弧が鍵へ触れているため、末尾一致で探す。
const 中央値の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p50");
const 第95百分位の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("p95");
/// 標本数は「標本60)」の形で1語に続くため、鍵の後ろの残りから閉じ括弧を落として読む。
const 標本数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("標本");

pub(super) fn 標本を取り出す(
    報告: &終了時報告, 実行番号: usize, 位置: 周回の位置, 条件: &実行条件
) -> Result<一標本, 検収エラー> {
    let 積むか = 条件.方式.深度プリパスを積むか();
    let 表 = 報告.見出しの区画(表の見出し)?;
    let mut 区間別 = Vec::new();
    for 区間名 in intervals::全区間一覧 {
        let 立つはず = 区間名 == intervals::色パスの区間名 || 積むか;
        区間別.push(区間を読む(&表, 区間名, 条件.名前, 立つはず)?);
    }
    let 生標本 = frame_samples::読む(報告, 条件.名前)?;
    Ok(一標本 {
        実行番号,
        周回番号: 位置.周回番号,
        順序位置: 位置.順序位置,
        条件名: 条件.名前,
        区間別,
        窓の標本数: 生標本.窓の標本数,
        フレーム別の値一覧: 生標本.生値一覧,
    })
}

fn 区間を読む(表: &報告の区画, 区間名: &str, 条件名: &str, 立つはず: bool) -> Result<区間の観測, 検収エラー> {
    let 接頭辞 = 報告の見出し::組み立てた綴りから生成する(format!("{区間名}:"));
    let 行 = 表.接頭辞の行(&接頭辞).ok();
    if 立つはず {
        let Some(行) = 行 else {
            return Err(積むはずの区間の判定名(条件名, 区間名).あるはずのものが無い破れ().into());
        };
        return Ok(区間の観測::測れた(分布を読む(行, 区間名)?));
    }
    積まないはずの区間の判定名(条件名, 区間名).零件であることを課す(u64::from(行.is_some()))?;
    Ok(区間の観測::積まない)
}

fn 分布を読む(行: &報告の行, 区間名: &str) -> Result<区間の分布, 検収エラー> {
    let 平均の鍵 = 報告の行の鍵::組み立てた綴りから生成する(format!("{区間名}:"));
    Ok(区間の分布 {
        平均ミリ秒: 行.鍵に結ばれた数(&平均の鍵, 鍵に値が結ばれる形::次の語が値である)?,
        p50ミリ秒: 行.鍵に結ばれた数(&中央値の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)?,
        p95ミリ秒: 行.鍵に結ばれた数(&第95百分位の鍵, 鍵に値が結ばれる形::この綴りで終わる語の次が値である)?,
        標本数: 行.鍵に結ばれた語から数字だけを読む(&標本数の鍵, 鍵に値が結ばれる形::この綴りに続く残りが値である)?,
    })
}

fn 積むはずの区間の判定名(条件名: &str, 区間名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}のパス別GPU時間の表の区間{区間名}"))
}

fn 積まないはずの区間の判定名(条件名: &str, 区間名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}が積まない条件である区間{区間名}の表への現れ"))
}
