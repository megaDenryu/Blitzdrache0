//! 終了時報告からフレーム別の生標本を読む工程。受け取るのは終了時報告と条件名、返すのは窓の標本数と、読み取り順に並んだ生値である。
//!
//! 行の綴りは`crates/blitz_app/src/reports/gpu_frame_samples.rs`の出力と一致させている。
//! 見出しが「パス別GPU時間のフレーム別生値 窓の標本数=N 分位=最近傍順位法 件数=M」であり、
//! 続く各行が「  生値」で始まる4つの語(生値・読み取り順・区間名・経過ミリ秒)のタブ区切りである。
//!
//! 窓の標本数を見出しから読むのは、報告する側の窓の長さをこちらがもう1つの台帳として持たないためである。
//! 台帳を2つ持つと、窓の長さを変えたときに検査だけが古い前提で通り続ける。
//!
//! 1行の中をタブで切るのは行の原文からである。器の鍵は空白で語を切るため、区間名に空白が入った日に
//! 別の位置を値として読む。この行だけは区切り文字がタブであることを、ここが1箇所で知る。

use super::super::record::フレーム別の生値;
use crate::acceptance::{判定の名前, 報告の行, 検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

const 見出し: 報告の見出し = 報告の見出し::定数から生成する("パス別GPU時間のフレーム別生値");
const 窓の標本数の鍵: 報告の行の鍵 = 報告の行の鍵::定数から生成する("窓の標本数");
/// 生値の行の見出し。タブまで含めるのは、見出しの語だけで始まる別の行を拾わないためである。
const 生値の行の見出し: 報告の見出し = 報告の見出し::定数から生成する("生値\t");
/// 生値の1行が持つ語の数。生値・読み取り順・区間名・経過ミリ秒の4つである。
const 生値の行の語の数: usize = 4;

pub(crate) struct 生標本の読み取り {
    pub(crate) 窓の標本数: usize,
    pub(crate) 生値一覧: Vec<フレーム別の生値>,
}

pub(crate) fn 読む(報告: &終了時報告, 条件名: &str) -> Result<生標本の読み取り, 検収エラー> {
    let 窓の標本数 = 報告
        .見出しの1行(&見出し)?
        .鍵に結ばれた数(&窓の標本数の鍵, 鍵に値が結ばれる形::等号の後ろが値である)?;
    let mut 生値一覧 = Vec::new();
    for 行 in 報告.見出しで始まる行の一覧(&生値の行の見出し) {
        生値一覧.push(一行を読む(&行)?);
    }
    if 生値一覧.is_empty() {
        return Err(生値の行の判定名(条件名).あるはずのものが無い破れ().into());
    }
    Ok(生標本の読み取り {
        窓の標本数, 生値一覧
    })
}

fn 一行を読む(行: &報告の行) -> Result<フレーム別の生値, 検収エラー> {
    let 判定名 = 生値の1行の判定名(行);
    let 語一覧: Vec<&str> = 行.原文().trim_start().split('\t').collect();
    判定名.一致を課す(語一覧.len(), 生値の行の語の数)?;
    Ok(フレーム別の生値 {
        読み取り順: 判定名.材料を数として読む(語一覧[1])?,
        区間名: 語一覧[2].to_string(),
        経過ミリ秒: 判定名.材料を数として読む(語一覧[3])?,
    })
}

fn 生値の行の判定名(条件名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{条件名}のフレーム別生値の行"))
}

fn 生値の1行の判定名(行: &報告の行) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("フレーム別生値の行「{}」のタブ区切りの語", 行.原文()))
}
