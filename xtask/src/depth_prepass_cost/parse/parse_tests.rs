//! 標準出力からの標本の取り出しの検査。積む条件が三区間を読むこと、積まない条件でプリパスと合計が積まないと読まれること、
//! 条件と実際に走った内容の食い違いが落ちること、合成区間の分位が内訳の分位の和と別の値であること、
//! フレーム別の生値と窓の標本数を読むことを見る。

#![allow(clippy::unwrap_used)]

use super::super::intervals;
use super::super::record::区間の観測;
use super::super::schedule::{三条件, 周回の位置};
use super::標本を取り出す;
use crate::acceptance::{検収の実行名, 終了時報告};

const 標本の実行名: 検収の実行名 = 検収の実行名::定数から生成する("depth_prepass_cost_parse");

/// 窓の集約の綴り。標本数を1にしてあるのは、続く生値の行数と辻褄を合わせるためである。
const 積む集約: &str = "パス別GPU時間(直近60フレームの窓):\n  深度プリパス: 0.2000 (p50 0.2100 / p95 0.2200 / 標本1)\n  シーン描画: 1.0000 (p50 1.0100 / p95 1.0200 / 標本1)\n  深度プリパスとシーン描画の合計: 1.2000 (p50 1.1900 / p95 1.3000 / 標本1)\n";
const 積まない集約: &str = "パス別GPU時間(直近60フレームの窓):\n  シーン描画: 1.4000 (p50 1.4100 / p95 1.4200 / 標本1)\n";
const 生値: &str = "パス別GPU時間のフレーム別生値 窓の標本数=60 分位=最近傍順位法 件数=3\n  生値\t0\t深度プリパス\t0.2100\n  生値\t0\tシーン描画\t1.0100\n  生値\t0\t深度プリパスとシーン描画の合計\t1.1900\n";

const 先頭の位置: 周回の位置 = 周回の位置 {
    周回番号: 0, 順序位置: 0
};

/// 生値の見出しと行は窓の集約と同じ標準出力に並ぶ。検査ではその並びを組んで報告にする。
fn 報告(集約: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, format!("{集約}{生値}"), String::new())
}

/// 生値の見出しが無い標準出力を組む。報告の指定を渡し忘れた実行がこの形になる。
fn 集約だけの報告(集約: &str) -> 終了時報告 {
    終了時報告::取り込む(&標本の実行名, 集約.to_string(), String::new())
}

#[test]
fn 積む条件は三区間を読む() {
    let 標本値 = 標本を取り出す(&報告(積む集約), 1, 先頭の位置, &三条件[1]).unwrap();
    let 区間の観測::測れた(合計) = 標本値.区間を参照する(intervals::合計の区間名).unwrap() else {
        panic!("合計の区間が測れていない");
    };
    assert!((合計.第50百分位ミリ秒 - 1.19).abs() < 1.0e-9, "{}", 合計.第50百分位ミリ秒);
}

/// 合成区間の分位は、内訳の分位を足した値と別である。分位の加法性が成立しないことがこの差に出ている。
#[test]
fn 合成区間の分位は区間別分位の和と別の値である() {
    let 標本値 = 標本を取り出す(&報告(積む集約), 1, 先頭の位置, &三条件[1]).unwrap();
    let (区間の観測::測れた(プリパス), 区間の観測::測れた(色), 区間の観測::測れた(合計)) = (
        標本値.区間を参照する(intervals::深度プリパスの区間名).unwrap(),
        標本値.区間を参照する(intervals::色パスの区間名).unwrap(),
        標本値.区間を参照する(intervals::合計の区間名).unwrap(),
    ) else {
        panic!("区間が測れていない");
    };
    assert!((合計.第50百分位ミリ秒 - (プリパス.第50百分位ミリ秒 + 色.第50百分位ミリ秒)).abs() > 1.0e-9);
}

#[test]
fn 積まない条件はプリパスと合計を積まないとして読む() {
    let 標本値 = 標本を取り出す(&報告(積まない集約), 0, 先頭の位置, &三条件[0]).unwrap();
    assert_eq!(標本値.区間を参照する(intervals::深度プリパスの区間名).unwrap(), 区間の観測::積まない);
    assert_eq!(標本値.区間を参照する(intervals::合計の区間名).unwrap(), 区間の観測::積まない);
}

#[test]
fn フレーム別の生値と窓の標本数を読む() {
    let 標本値 = 標本を取り出す(&報告(積む集約), 2, 先頭の位置, &三条件[1]).unwrap();
    assert_eq!(標本値.窓の標本数, 60);
    assert_eq!(標本値.フレーム別の値一覧.len(), 3);
    assert_eq!(標本値.フレーム別の値一覧[0].区間名, intervals::深度プリパスの区間名);
    assert!((標本値.フレーム別の値一覧[0].経過ミリ秒 - 0.21).abs() < 1.0e-9);
}

#[test]
fn 条件と実際に走った内容の食い違いを落とす() {
    assert!(
        標本を取り出す(&報告(積まない集約), 1, 先頭の位置, &三条件[1]).is_err(),
        "積むはずの区間の欠けを見逃した"
    );
    assert!(
        標本を取り出す(&報告(積む集約), 0, 先頭の位置, &三条件[0]).is_err(),
        "積まないはずの区間の出現を見逃した"
    );
}

/// 生値の見出しが無い標準出力は、報告の指定を渡し忘れた実行である。分位を裏付ける列が無いまま表だけが出るのを防ぐ。
#[test]
fn 生値の見出しが無い標準出力を落とす() {
    assert!(標本を取り出す(&集約だけの報告(積む集約), 0, 先頭の位置, &三条件[1]).is_err());
}
