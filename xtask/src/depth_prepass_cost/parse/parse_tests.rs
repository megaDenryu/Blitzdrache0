//! 標準出力からの標本の取り出しの検査。積む条件が三区間を読むこと、積まない条件でプリパスと合計が積まないと読まれること、
//! 条件と実際に走った内容の食い違いが落ちること、合成区間の分位が内訳の分位の和と別の値であることを見る。

#![allow(clippy::unwrap_used)]

use super::super::intervals;
use super::super::record::区間の観測;
use super::super::schedule::交互の並び;
use super::標本を取り出す;

const 積む標本: &str = "パス別GPU時間(直近60フレームの窓):\n  深度プリパス: 0.2000 (p50 0.2100 / p95 0.2200 / 標本60)\n  シーン描画: 1.0000 (p50 1.0100 / p95 1.0200 / 標本60)\n  深度プリパスとシーン描画の合計: 1.2000 (p50 1.1900 / p95 1.3000 / 標本60)\n";
const 積まない標本: &str = "パス別GPU時間(直近60フレームの窓):\n  シーン描画: 1.4000 (p50 1.4100 / p95 1.4200 / 標本60)\n";

#[test]
fn 積む条件は三区間を読む() {
    let 標本値 = 標本を取り出す(積む標本, 1, &交互の並び[1]).unwrap();
    let 区間の観測::測れた(合計) = 標本値.区間を参照する(intervals::合計の区間名).unwrap() else {
        panic!("合計の区間が測れていない");
    };
    assert!((合計.p50ミリ秒 - 1.19).abs() < 1.0e-9, "{}", 合計.p50ミリ秒);
}

/// 合成区間の分位は、内訳の分位を足した値と別である。分位の加法性が成立しないことがこの差に出ている。
#[test]
fn 合成区間の分位は区間別分位の和と別の値である() {
    let 標本値 = 標本を取り出す(積む標本, 1, &交互の並び[1]).unwrap();
    let (区間の観測::測れた(プリパス), 区間の観測::測れた(色), 区間の観測::測れた(合計)) = (
        標本値.区間を参照する(intervals::深度プリパスの区間名).unwrap(),
        標本値.区間を参照する(intervals::色パスの区間名).unwrap(),
        標本値.区間を参照する(intervals::合計の区間名).unwrap(),
    ) else {
        panic!("区間が測れていない");
    };
    assert!((合計.p50ミリ秒 - (プリパス.p50ミリ秒 + 色.p50ミリ秒)).abs() > 1.0e-9);
}

#[test]
fn 積まない条件はプリパスと合計を積まないとして読む() {
    let 標本値 = 標本を取り出す(積まない標本, 0, &交互の並び[0]).unwrap();
    assert_eq!(標本値.区間を参照する(intervals::深度プリパスの区間名).unwrap(), 区間の観測::積まない);
    assert_eq!(標本値.区間を参照する(intervals::合計の区間名).unwrap(), 区間の観測::積まない);
}

#[test]
fn 条件と実際に走った内容の食い違いを落とす() {
    assert!(標本を取り出す(積まない標本, 1, &交互の並び[1]).is_err(), "積むはずの区間の欠けを見逃した");
    assert!(標本を取り出す(積む標本, 0, &交互の並び[0]).is_err(), "積まないはずの区間の出現を見逃した");
}
