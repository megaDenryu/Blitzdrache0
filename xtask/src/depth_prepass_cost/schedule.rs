//! どの条件をどの順で起動するかを決める工程。受け取るものは無く、返すのは条件の並びである。
//!
//! A・B・C・A'・B'・C'の交互周回に固定するのは、同じ条件を続けて回すと機材の状態の移り変わりが条件の差に化けるためである。
//! 1周目と2周目の同じ条件の食い違いが、そのまま「この計測日の機材の揺れ」の大きさになる。
//! 3条件を1周ずつ回してから2周目へ入るのは、条件の順序が温まりの影響を等しく受けるようにするためである。

/// その実行が使う深度プリパスの方式。値はblitz_appの`--depth-prepass`へそのまま渡る語である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 方式 {
    積まない,
    色は同値以下,
    色は等値,
}

impl 方式 {
    pub(super) const fn 起動指定の語(self) -> &'static str {
        match self {
            Self::積まない => "none",
            Self::色は同値以下 => "less-equal",
            Self::色は等値 => "equal",
        }
    }

    pub(super) const fn 深度プリパスを積むか(self) -> bool {
        match self {
            Self::積まない => false,
            Self::色は同値以下 | Self::色は等値 => true,
        }
    }
}

pub(super) struct 実行条件 {
    pub(super) 名前: &'static str,
    pub(super) 方式: 方式,
}

pub(super) const 交互の並び: [実行条件; 6] = [
    実行条件 {
        名前: "A",
        方式: 方式::積まない,
    },
    実行条件 {
        名前: "B",
        方式: 方式::色は同値以下,
    },
    実行条件 {
        名前: "C",
        方式: 方式::色は等値,
    },
    実行条件 {
        名前: "A2",
        方式: 方式::積まない,
    },
    実行条件 {
        名前: "B2",
        方式: 方式::色は同値以下,
    },
    実行条件 {
        名前: "C2",
        方式: 方式::色は等値,
    },
];

/// 同値性の検収で撮る3条件。周回でなく1条件1枚ずつであり、周回の2周目は撮らない。
pub(super) const 三条件: [実行条件; 3] = [
    実行条件 {
        名前: "A",
        方式: 方式::積まない,
    },
    実行条件 {
        名前: "B",
        方式: 方式::色は同値以下,
    },
    実行条件 {
        名前: "C",
        方式: 方式::色は等値,
    },
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 交互の並びは三条件を二周する() {
        let 方式一覧: Vec<方式> = 交互の並び.iter().map(|条件| 条件.方式).collect();
        assert_eq!(&方式一覧[..3], &方式一覧[3..], "1周目と2周目で条件の並びが違う");
    }

    /// 周回の条件名が全部違うことは、生値と表で採った順番を見分ける根拠である。
    #[test]
    fn 周回の条件名は重複しない() {
        let mut 名前一覧: Vec<&str> = 交互の並び.iter().map(|条件| 条件.名前).collect();
        名前一覧.sort_unstable();
        名前一覧.dedup();
        assert_eq!(名前一覧.len(), 交互の並び.len());
    }
}
