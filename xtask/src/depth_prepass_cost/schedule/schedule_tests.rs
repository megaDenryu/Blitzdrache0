//! 起動の並びの検査。各条件が全部の順序位置をちょうど1回ずつ取ること、1つの周回が3条件を重複なく1回ずつ含むことを見る。
//! この2つが成り立って初めて、周回の中の温まりとドリフトが3条件へ等しく配られたと言える。

use super::{三条件, 周回数, 起動の並び};

/// 各条件が先頭・2番目・3番目をちょうど1回ずつ取ることが、順序の効果を均衡させたことの実体である。
#[test]
fn 各条件が全部の順序位置をちょうど一回ずつ取る() {
    let 並び = 起動の並び();
    assert_eq!(並び.len(), 周回数 * 三条件.len());
    for 条件 in &三条件 {
        let mut 位置一覧: Vec<usize> = 並び
            .iter()
            .filter(|(_, 実行)| 実行.名前 == 条件.名前)
            .map(|(位置, _)| 位置.順序位置)
            .collect();
        位置一覧.sort_unstable();
        assert_eq!(位置一覧, vec![0, 1, 2], "条件{}の順序位置が均衡していない", 条件.名前);
    }
}

/// 1つの周回は3条件を重複なく1回ずつ含む。含まないと、その周回の中で条件を比べる根拠が消える。
#[test]
fn 一周回は三条件を重複なく含む() {
    let 並び = 起動の並び();
    for 周回番号 in 0..周回数 {
        let mut 名前一覧: Vec<&str> = 並び
            .iter()
            .filter(|(位置, _)| 位置.周回番号 == 周回番号)
            .map(|(_, 実行)| 実行.名前)
            .collect();
        名前一覧.sort_unstable();
        assert_eq!(名前一覧, vec!["A", "B", "C"], "周回{周回番号}が3条件を1回ずつ含まない");
    }
}
