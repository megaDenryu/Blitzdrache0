//! 計測と検収が使う世界の起動引数。担当するのは、費用を測る起動と絵を撮る起動が同じ世界を同じ条件で開くことである。
//!
//! `indirect-cost`と同じ世界・同じ先読み半径・同じカメラ俯角にするのは、既に採ってある色パスの費用と並べて読めるようにするためである。
//! 別の構図で測ると、深度プリパスが足す費用の大きさを既存の値と比べる根拠が消える。
//! 時間再構成は`--no-taa`で外す。段3b以前に採った値と並べて読むため、パスを1本足した条件へ計測窓を変えない。

#[cfg(test)]
mod tests;

use std::path::PathBuf;

use super::schedule::実行条件;
use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 世界を読ませて報告を採る実行環境, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収エラー,
    検収シーン名,
};
use crate::verify::検証の出力ルート;

/// 計測がこの世界を叩くときの起こし方。GPU時間の窓へcargoのビルド判定を混ぜないため、構築済みのリリース版を直に起こす。
const 起こし方: アプリの起こし方 = アプリの起こし方::構築済みのリリース版を直に起動する;
const シーン名: 検収シーン名 = 検収シーン名::生成する("terrain_origin");
const 先読み半径: &str = "2";
const 容量上限バイト: &str = "16777216";
const カメラ俯角差分度: &str = "-25";

/// 費用を測る実行のための実行環境。絵を1枚も書き出さない。
pub(super) fn 計測の実行環境を作る() -> 世界を読ませて報告を採る実行環境 {
    世界を読ませて報告を採る実行環境::作る(
        起こし方,
        実行時アセットルート::パスから生成する(
            検証の出力ルート::既定().名前が指す置き場(crate::compile_assets::地形の世界の実行時形式の置き場),
        ),
    )
}

/// 同値性の絵を撮る実行のための実行環境。
pub(super) fn 撮影の実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        起こし方,
        実行時アセットルート::パスから生成する(
            検証の出力ルート::既定().名前が指す置き場(crate::compile_assets::地形の世界の実行時形式の置き場),
        ),
        出力ディレクトリ,
    )
}

/// 計測窓として描く起動の指定。世界とカメラと条件までを積み、報告の求めは呼び出し側が続けて足す。
pub(super) fn 計測の起動指定を組み立てる(
    フレーム数: 描画フレーム数,
    条件: &実行条件,
    一日内秒: Option<&String>,
) -> アプリの起動指定 {
    条件と時刻を積む(アプリの起動指定::シーンと計測の枚数を決める(シーン名, フレーム数), 条件, 一日内秒)
}

/// 絵を撮る起動の指定。フレームダンプが最終フレームでだけ働くため、スモーク実行の枚数で描く。
pub(super) fn 撮影の起動指定を組み立てる(
    フレーム数: 描画フレーム数,
    条件: &実行条件,
    一日内秒: Option<&String>,
) -> アプリの起動指定 {
    条件と時刻を積む(アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数), 条件, 一日内秒)
}

/// 世界とカメラと条件と時刻を積む。
///
/// 局所可視性補正を切るのは、3条件の目的が深度プリパスの費用対効果を分離することだからである。補正を宣言した
/// 世界は深度プリパスの方式を引き上げるため、切らないと条件Aの`使わない`が型付きの失敗になって条件列が成立しない。
/// 補正込みの費用は通常実行の計器で別に採る。
fn 条件と時刻を積む(指定: アプリの起動指定, 条件: &実行条件, 一日内秒: Option<&String>) -> アプリの起動指定 {
    let 積んだ指定 = 指定
        .選択肢を足す("--no-ssao")
        .選択肢を足す("--streaming")
        .値を持つ選択肢を足す("--streaming-preload-radius", 先読み半径)
        .値を持つ選択肢を足す("--streaming-ram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--streaming-vram-limit", 容量上限バイト)
        .値を持つ選択肢を足す("--camera-pitch", カメラ俯角差分度)
        .選択肢を足す("--no-taa")
        .値を持つ選択肢を足す("--depth-prepass", 条件.方式.起動指定の語());
    let Some(秒) = 一日内秒 else {
        return 積んだ指定;
    };
    積んだ指定.値を持つ選択肢を足す("--time-of-day", 秒)
}
