//! 段3bの検収入口。目視見本の庭を時間再構成付きで描き、履歴を無効にした直後の1フレーム目が今のフレームの色と
//! 画素で一致すること、同じ条件の2実行が同じ結果を出すこと、静止カメラでのフレーム間差分がどこまで落ちるかを見る。
//!
//! 2回走らせるのは決定性のためである。画素内ずらしの列が決定的であり、フレーム数の決まった実行はカメラを1度も
//! 動かさないため、同じ起動指定の2実行は同じ絵を出さなければならない
//! (`参照: _doc/設計/時間再構成.md`「検収戦略(判断g)」の5)。
//!
//! 静止カメラの安定化だけは判定値を持たない観測である。画素内ずらしが回り続けるため、定常状態は1つの絵へ止まる
//! 不動点でなく列の長さを周期とする周期軌道になる。閾値は実測からオーナーが制定するため、この入口は最大と
//! 最後の1周ぶんの値を並べるところまでを行う。
//!
//! 合成した入力の注入によるCPU正本との突き合わせ(判断gの2)はこの入口にまだ無い。未実装であることは
//! `_doc/設計/時間再構成.md`「段割りと各段の完了条件」の段3bに残してある。

mod judgment;
mod observation;
mod run;

use std::process::ExitCode;

pub fn 実行する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] temporal-reconstruction成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] temporal-reconstruction失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, String> {
    crate::visual_sample_world::用意する()?;
    let 一回目 = observation::取り出す(&run::観測を採る("1回目")?, "1回目")?;
    let 二回目 = observation::取り出す(&run::観測を採る("2回目")?, "2回目")?;
    judgment::判定する(&一回目, &二回目)?;
    Ok(observation::要約を組む(&一回目))
}
