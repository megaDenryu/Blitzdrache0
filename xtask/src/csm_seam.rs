//! OW5第5段の検収入口。多段の距離区分の継ぎ目が絵に段差として出ないことを画素で確かめる。
//!
//! 長い受光面(検証用地形世界の5×5チャンク)と反復する遮蔽物(各チャンクの植生の群)を、低い太陽と寝かせた視線で描く。
//! この構図では4つの距離区分の境界がすべて画面を横切る。同じ条件を2回描き、1回は本番の色、もう1回は
//! 「どの距離区分を参照したか」と「影の中か」の可視化を出す。距離区分の領域は可視化から読み、輝度の段差は本番の絵から測る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「検証の設計」)。
//!
//! 判定は3つである。どの距離区分にも影の画素があること、境界を挟む両側それぞれに影の画素があること、
//! 境界の輝度段差が同じ幅ぶん内側へ入った位置との差(距離区分の内側の勾配)を超えないことである。
//! 遷移域の重みが単調で和1であることは`blitz_render`のユニットテストが持つ。

mod band_map;
mod boundary;
mod composition;
mod error;
mod judgment;
mod run;

use std::path::PathBuf;

use std::process::ExitCode;

use composition::継ぎ目を見る構図;
use error::距離区分の継ぎ目の検収エラー;

use crate::acceptance::{判定の名前, 検収の実行名};

/// 2条件の書き出しの基準名。絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
const 本番の実行名: 検収の実行名 = 検収の実行名::定数から生成する("scene");
const 可視化の実行名: 検収の実行名 = 検収の実行名::定数から生成する("bands");

/// 境界の数。距離区分数4に対して3つである(xtaskはエンジンのクレートへ依存しないため値を二重に持つ)。
const 境界の数: usize = 3;
/// 境界からの距離で、近傍とみなす画素の幅(画素)。狭すぎると標本が足りず、広すぎると境界から離れた陰影を混ぜる。
const 近傍の幅: usize = 6;
/// 境界の近傍で片側に要る影の画素数の下限。これを下回ると「その側に影がある」と言えない。
const 影画素数の下限: usize = 100;
/// 輝度段差の絶対上限(8bit)。距離区分の内側の勾配が小さい構図でも、これを超える段差は目に見える継ぎ目である。
const 段差の絶対上限: f64 = 12.0;
/// 2条件の絵を同じ座標で突き合わせるための前提。寸法が違えば距離区分の地図と本番の絵で同じ添字が別の位置を指す。
const 本番と可視化の寸法: 判定の名前 = 判定の名前::定数から生成する("本番と可視化の読み戻し寸法が同じであること");

pub fn 実行する(引数一覧: &[String]) -> ExitCode {
    match 検収する(引数一覧) {
        Ok(要約) => {
            println!("[xtask] csm-seam成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] csm-seam失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する(引数一覧: &[String]) -> Result<String, 距離区分の継ぎ目の検収エラー> {
    let 構図 = 継ぎ目を見る構図::引数を読む(引数一覧)?;
    if 構図 == 継ぎ目を見る構図::検証用地形世界
        && (!crate::gen_source_assets::生成する() || !crate::compile_assets::地形世界を既定で生成する())
    {
        return Err(距離区分の継ぎ目の検収エラー::検証用アセットを生成できなかった);
    }
    let 実行環境 = run::実行環境を作る(構図, PathBuf::from(構図.出力ディレクトリ()))?;

    let 本番の実行 = 実行環境.描いて読み戻す(本番の実行名, &run::起動指定を組み立てる(構図, false))?;
    let 可視化の実行 = 実行環境.描いて読み戻す(可視化の実行名, &run::起動指定を組み立てる(構図, true))?;
    let (本番, 可視化) = (本番の実行.画像(), 可視化の実行.画像());
    本番と可視化の寸法.真であることを課す(本番.寸法が同じか(可視化))?;
    let 地図 = band_map::距離区分の地図::読み取る(可視化);

    let 四区分の成立 = if 構図.影の画素で四区分の成立を見るか() {
        judgment::全距離区分に影があることを検査する(&地図)?
    } else {
        judgment::全距離区分に受光画素があることを検査する(&地図)?
    };
    let 境界の影 = judgment::境界の両側に影があることを検査する(&地図)?;
    let 段差 = judgment::境界の輝度段差を検査する(&地図, 本番)?;

    let 本番png = 本番の実行.書き出し先().目視用の絵へ変換する()?;
    let 可視化png = 可視化の実行.書き出し先().目視用の絵へ変換する()?;
    let 段差の記述: Vec<String> = 段差
        .iter()
        .enumerate()
        .map(|(番号, &(段差, 勾配))| format!("境界{番号}は段差{段差:.2}(距離区分の内側の勾配{勾配:.2})"))
        .collect();
    Ok(format!(
        "距離区分別の{}{四区分の成立:?}、境界の両側の影画素数{境界の影:?}、{}、絵は{}と{}",
        if 構図.影の画素で四区分の成立を見るか() {
            "影画素数"
        } else {
            "受光画素数"
        },
        段差の記述.join("・"),
        本番png.display(),
        可視化png.display()
    ))
}
