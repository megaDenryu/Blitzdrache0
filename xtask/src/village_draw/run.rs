//! 集落1回ぶんの起動の指定と、終了時報告の書き出し。受け取るのは無く、返すのは実行環境へ渡す起動指定である。
//! 起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! シーン名を`prop_village`にすることが、集落を見下ろす初期カメラと、書き換えもピクセル判定も持たない検収計画を選ばせる。
//! 空は`--sky`で明示する。世界の方針が空ありになるのは名前が`terrain`で始まる世界だけであり、この世界はそこへ入らないためである。
//! 監視対象シェーダーは指定しない。指定しないと埋め込みシェーダーで走り、リポジトリの`shaders/`へ監視の入口が向かない。

use std::path::PathBuf;

use crate::acceptance::{
    アプリの起こし方, アプリの起動指定, 実行時アセットルート, 描画フレーム数, 描画検収の実行環境, 検収の実行名, 検収エラー, 検収シーン名,
};
use crate::report_heading::報告の見出し;

const アセットルート: &str = "target/village_assets";
const シーン名: 検収シーン名 = 検収シーン名::生成する("prop_village");
const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(180);

/// 書き出しの基準名。絵のファイル名になり、失敗の文面もこの名前で実行を名指す。
pub(super) const 集落の実行名: 検収の実行名 = 検収の実行名::定数から生成する("village");

/// 一日内時刻17時。太陽が低く、小物の影が地面を長く横切るため、起伏と物の高さが影の形で読み取れる。
const 一日内秒: &str = "61200";

const 報告を出させる選択肢: [&str; 5] = [
    "--sky",
    "--report-gpu-times",
    "--report-frame-times",
    "--report-draw-issue",
    "--report-memory",
];

/// 終了時報告のうち、この入口が読ませたい部分の見出し。行の先頭から一致を見る。
const 報告の見出し一覧: [報告の見出し; 5] = [
    報告の見出し::定数から生成する("描画発行内訳"),
    報告の見出し::定数から生成する("CPU側フレーム間隔"),
    報告の見出し::定数から生成する("パス別GPU時間"),
    報告の見出し::定数から生成する("Vulkanメモリ確保"),
    crate::validation_count::検証層の指摘件数の見出し,
];

pub(super) fn 実行環境を作る(出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        実行時アセットルート::綴りから生成する(アセットルート),
        出力ディレクトリ,
    )
}

pub(super) fn 起動指定を組み立てる() -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(シーン名, フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢をまとめて足す(&報告を出させる選択肢)
}

/// 報告の見出しとその内訳の行を並べ直して出す。内訳は見出しより深く字下げされているため、
/// 見出しに続く字下げ行を同じ塊として拾えば、報告ごとの読み方を持たずに全体を写せる。
pub(super) fn 報告を書き出す(標準出力: &str) {
    let mut 報告の内側 = false;
    for 行 in 標準出力.lines() {
        if 報告の見出し一覧.iter().any(|見出し| 見出し.行の始まりか(行)) {
            報告の内側 = true;
        } else if !行.starts_with(' ') {
            報告の内側 = false;
        }
        if 報告の内側 {
            println!("[village-draw] {行}");
        }
    }
}
