//! 両方の様式が共通で渡す起動指定。受け取るのは構図、返すのはシーンと枚数と時刻と構図別の指定まで積んだ起動指定である。
//! 様式ごとの指定はそれぞれの側(`run`と`final_color`)が続けて足す。
//!
//! 枚数と一日内時刻をここが1つ持つのは、数えた絵と目で見る絵を同じ条件の絵にするためである。
//! 時刻17時は太陽が低く、影が受光面を長く横切る(`csm-seam`が継ぎ目の検収に使う時刻と同じである)。

use super::scene_choice::構図;
use crate::acceptance::{アプリの起動指定, 描画フレーム数};

const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(160);
const 一日内秒: &str = "61200";

pub(super) fn 共通の起動指定を組み立てる(構図: 構図) -> アプリの起動指定 {
    アプリの起動指定::シーンと枚数を決める(構図.シーン名(), フレーム数)
        .値を持つ選択肢を足す("--time-of-day", 一日内秒)
        .選択肢をまとめて足す(構図.追加の起動指定())
}
