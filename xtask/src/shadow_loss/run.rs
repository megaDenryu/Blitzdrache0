//! 1条件ぶんの起動の指定と、その実行の診断画像の取り込み。受け取るのは実行環境と構図と候補の起動指定、
//! 返すのは読み取り済みの診断画像である。起こす手順そのものは検収の共通語彙の実行環境が持つ。
//!
//! 影の欠落計器の枝で描くため、空とポスト処理は外す。診断の値は本番の色でなく評価そのものであり、
//! 明るさの圧縮や霞を通すと符号化した値が壊れるためである。フレーム数と一日内時刻は最終色の様式と同じ写しを使う。
//! 時間再構成は`--no-taa`で外す。この入口の判定がバイト一致に依るため、フレームをまたぐ混合が入ると前のフレームの残りが絵に混ざる。

use std::path::PathBuf;

use super::scene_choice::構図;
use crate::acceptance::{アプリの起こし方, アプリの起動指定, 描画検収の実行環境, 検収の実行名, 検収エラー};
use crate::shadow_diagnostic_image::診断画像;

const 診断の枝を選ぶ選択肢: [&str; 4] = ["--no-sky", "--no-post", "--no-taa", "--debug-shadow-loss"];

/// 構図1つぶんの実行環境。構図ごとにシーンもアセットルートも変わるため、構図ごとに1つ作る。
pub(super) fn 実行環境を作る(構図: 構図, 出力ディレクトリ: PathBuf) -> Result<描画検収の実行環境, 検収エラー> {
    描画検収の実行環境::作る(
        アプリの起こし方::毎回cargoに構築させて起動する,
        構図.アセットルートを作る(),
        出力ディレクトリ,
    )
}

pub(super) fn 描画する(
    実行環境: &描画検収の実行環境,
    実行名の綴り: &str,
    構図: 構図,
    候補の起動指定: &[String],
) -> Result<診断画像, 検収エラー> {
    let 実行 = 実行環境.描いて読み戻す(検収の実行名::生成する(実行名の綴り)?, &起動指定を組み立てる(構図, 候補の起動指定))?;
    Ok(診断画像::読み取る(実行.画像()))
}

fn 起動指定を組み立てる(構図: 構図, 候補の起動指定: &[String]) -> アプリの起動指定 {
    super::launch::共通の起動指定を組み立てる(構図)
        .選択肢をまとめて足す(&診断の枝を選ぶ選択肢)
        .選択肢をまとめて足す(&候補の起動指定.iter().map(String::as_str).collect::<Vec<&str>>())
}
