//! 影の欠落計器の引数の読み取りが返す型付きエラー。破れうる前提を枝で数え上げ、どの前提が破れたかを型で言う。
//!
//! xtaskは外部のクレートへ依存しないため、thiserrorを使わず手書きのenumと`Display`で書く。
//! 様式は`acceptance/error.rs`に倣う。
//!
//! 引数の読み取りが構図・軸・距離の3つのファイルへ分かれているのに型を1つにするのは、
//! どれも「打ち直す語をその場で名指す」という同じ役目を持ち、呼び出し側が段ごとに変換を書かずに済むためである。

use std::fmt;

#[derive(Debug)]
pub(super) enum 影の欠落計器の引数の破れ {
    語の次に値が無い {
        語: String,
    },
    構図の指定が2回ある,
    知らない構図を渡された {
        語: String,
        選べる構図: String,
    },
    知らない引数を渡された {
        語: String,
    },
    候補の指定が2つある {
        先に読んだ候補: &'static str,
        後の候補: &'static str,
    },
    候補の指定が1つも無い {
        選べる軸: String,
    },
    構図が候補の軸を受けない {
        構図: &'static str,
        候補: &'static str,
        受け入れる軸: String,
    },
    距離を数として読めない {
        綴り: String,
        誤り: std::num::ParseFloatError,
    },
    距離が正の有限値でない {
        綴り: String,
    },
}

impl std::error::Error for 影の欠落計器の引数の破れ {}

impl fmt::Display for 影の欠落計器の引数の破れ {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::語の次に値が無い { 語 } => write!(書き手, "{語}の次に値が無い"),
            Self::構図の指定が2回ある => {
                write!(書き手, "--layoutが2回ある。1回の実行で描く構図は1つだけである")
            }
            Self::知らない構図を渡された { 語, 選べる構図 } => {
                write!(書き手, "知らない構図である({語})。{選べる構図}のいずれかを指定する")
            }
            Self::知らない引数を渡された { 語 } => write!(書き手, "知らない引数である({語})"),
            Self::候補の指定が2つある {
                先に読んだ候補, 後の候補
            } => write!(
                書き手,
                "候補の指定が2つある({先に読んだ候補}と{後の候補})。同時に変えると、どちらの軸が絵を動かしたか分けられない"
            ),
            Self::候補の指定が1つも無い { 選べる軸 } => write!(
                書き手,
                "候補の指定が1つ要る({選べる軸})。ちょうど1つだけ受けるのは、αとβを同時に変えないためである"
            ),
            Self::構図が候補の軸を受けない {
                構図, 候補, 受け入れる軸
            } => write!(書き手, "構図{構図}は{候補}の候補を受けない。この構図が受けるのは{受け入れる軸}である"),
            Self::距離を数として読めない { 綴り, 誤り } => {
                write!(書き手, "距離を数として読めない({綴り}): {誤り}")
            }
            Self::距離が正の有限値でない { 綴り } => {
                write!(書き手, "距離は正の有限値でなければならない({綴り})")
            }
        }
    }
}
