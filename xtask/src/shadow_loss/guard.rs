//! 計器が下す判定。持つのは2つである。1つは比較そのものが成立する前提の判定であり、両方の構図に効く。
//! もう1つは負の対照として作った構図の期待の判定であり、検収世界にだけ効く。
//! 判定を計器の本体から分けるのは、地形の代表世界では失われる量に正解が無く、期待を判定するのが検収世界だけだからである。

use super::candidate_axis::候補の計測指定;
use super::compare::比較結果;
use super::range_world;
use super::scene_choice;

/// 遠方キャスターの領域で欠落が支配的だとみなす百分率の下限。
const 遠方キャスターの欠落の下限百分率: u64 = 90;
/// 近距離対照の領域で影が残ったとみなす百分率の下限。
const 近距離対照の残存の下限百分率: u64 = 90;

/// 比較が成立する前提の判定。食い違った画素は帯ごとの集計から外れるため、非0のまま数を出すと母集団を欠いた
/// 欠落と余分をそのまま裁定材料にしてしまう。1件でも失敗にする。
pub(super) fn 前提を確かめる(比較: &比較結果) -> Result<(), String> {
    if 比較.幾何の食い違い画素数 != 0 {
        return Err(format!(
            "幾何の食い違いが{}画素ある。基準と候補が同じカメラと同じ幾何を描いておらず、比較が成立しない",
            比較.幾何の食い違い画素数
        ));
    }
    if 比較.帯の食い違い画素数 != 0 {
        return Err(format!(
            "帯の食い違いが{}画素ある。固定刻みの受光距離帯は候補の指定で動かないはずであり、比較が成立しない",
            比較.帯の食い違い画素数
        ));
    }
    Ok(())
}

/// 絵を見なくても分かる破れの判定。2回の描画は費用が大きいため、描く前に落とせるものはここで落とす。
pub(super) fn 描く前に確かめる(構図: scene_choice::構図, 候補: &候補の計測指定) -> Result<(), String> {
    if 構図.期待() != scene_choice::構図の期待::負の対照として判定する {
        return Ok(());
    }
    let 候補の計測指定::影の視距離(切断距離) = 候補 else {
        return Err("影視距離の検収世界へ最大影距離の候補が渡った。引数の受理がαを拒む契約が破れている".to_string());
    };
    range_world::切断の距離を確かめる(切断距離.値())
}

/// 負の対照として作った構図だけを判定する。遠方キャスターの影が落ちる領域と近距離対照の影が落ちる領域を
/// 別々に数え、前者で欠落が支配的であることと、後者で影が残ることを直接見る。
pub(super) fn 負の対照を判定する(構図: scene_choice::構図, 比較: &比較結果) -> Result<(), String> {
    if 構図.期待() != scene_choice::構図の期待::負の対照として判定する {
        return Ok(());
    }
    range_world::画面の寸法を確かめる(比較.幅, 比較.高さ)?;
    領域別に判定する(比較)
}

fn 領域別に判定する(比較: &比較結果) -> Result<(), String> {
    let 遠方 = range_world::遠方キャスターの影の領域.数える(比較)?;
    let 近距離 = range_world::近距離対照の影の領域.数える(比較)?;
    let 遠方の欠落 = 百分率を求める(遠方.欠落画素数, 遠方.基準の影画素数, "遠方キャスターの影の領域")?;
    let 近距離の残存 = 百分率を求める(近距離.候補の影画素数, 近距離.基準の影画素数, "近距離対照の影の領域")?;
    if 遠方の欠落 < 遠方キャスターの欠落の下限百分率 {
        return Err(format!(
            "遠方キャスターの影の領域で消えたのは基準の影{}画素のうち{}パーセントであり、切断がその影へ届いていない",
            遠方.基準の影画素数, 遠方の欠落
        ));
    }
    if 近距離の残存 < 近距離対照の残存の下限百分率 {
        return Err(format!(
            "近距離対照の影の領域に残ったのは基準の影{}画素のうち{}パーセントであり、切断が近距離対照の影まで消している",
            近距離.基準の影画素数, 近距離の残存
        ));
    }
    余分が無いことを確かめる(比較)?;
    println!(
        "  負の対照の判定: 遠方キャスターの影の領域は基準の影{}画素の{遠方の欠落}パーセントが消え、近距離対照の影の領域は基準の影{}画素の{近距離の残存}パーセントが残った(余分は0)",
        遠方.基準の影画素数, 近距離.基準の影画素数
    );
    Ok(())
}

/// 余分が出ないことを見るのは、切断が「候補を減らす」操作であり、影が増えることが原理的に起こらないためである。
fn 余分が無いことを確かめる(比較: &比較結果) -> Result<(), String> {
    let 余分 = 比較.帯別.iter().map(|集計| 集計.余分画素数).sum::<u64>();
    if 余分 != 0 {
        return Err(format!(
            "候補で影が増えた画素が{余分}件ある。切断は候補を減らす操作であり増えてはならない"
        ));
    }
    Ok(())
}

fn 百分率を求める(該当数: u64, 母数: u64, 領域の名: &str) -> Result<u64, String> {
    if 母数 == 0 {
        return Err(format!("{領域の名}に基準の影が1画素も無い。世界かカメラか光の向きが想定と違う"));
    }
    Ok(該当数 * 100 / 母数)
}

