//! 計器が下す判定のうち、どちらの構図にも効くもの。担当するのは、比較そのものが成立する前提の判定と、
//! 描く前に絵を見なくても分かる破れの判定である。
//! 判定を計器の本体から分けるのは、地形の代表世界では失われる量に正解が無く、期待を判定するのが検収世界だけだからである。
//!
//! 負の対照として作った構図にだけ効く期待の判定は`negative_control`が持つ。効く構図が違い、
//! 見る値も比較結果の全体でなく受光面の2つの矩形だけであるためである。

mod negative_control;

#[cfg(test)]
mod judgment_tests;

pub(super) use negative_control::負の対照を判定する;

use super::candidate_axis::{候補の計測指定, 計測軸};
use super::compare::比較結果;
use super::range_world;
use super::scene_choice;
use crate::acceptance::{判定の名前, 判定の破れ};

const 幾何の食い違い画素数: 判定の名前 = 判定の名前::定数から生成する(
    "基準と候補で幾何の食い違った画素数(1画素でもあれば同じカメラと同じ幾何を描いておらず、比較が成立しない)",
);
const 帯の食い違い画素数: 判定の名前 = 判定の名前::定数から生成する(
    "基準と候補で受光距離帯の食い違った画素数(固定刻みの帯は候補の指定で動かないため、1画素でもあれば比較が成立しない)",
);
const 影視距離の検収世界が受ける候補の軸: 判定の名前 =
    判定の名前::定数から生成する("影視距離の検収世界へ渡った候補の軸(αが渡っているなら、引数の受理がαを拒む契約が破れている)");

/// 比較が成立する前提の判定。食い違った画素は帯ごとの集計から外れるため、非0のまま数を出すと母集団を欠いた
/// 欠落と余分をそのまま裁定材料にしてしまう。1件でも失敗にする。
pub(super) fn 前提を確かめる(比較: &比較結果) -> Result<(), 判定の破れ> {
    幾何の食い違い画素数.零件であることを課す(比較.幾何の食い違い画素数)?;
    帯の食い違い画素数.零件であることを課す(比較.帯の食い違い画素数)
}

/// 絵を見なくても分かる破れの判定。2回の描画は費用が大きいため、描く前に落とせるものはここで落とす。
pub(super) fn 描く前に確かめる(構図: scene_choice::構図, 候補: &候補の計測指定) -> Result<(), 判定の破れ> {
    if 構図.期待() != scene_choice::構図の期待::負の対照として判定する {
        return Ok(());
    }
    let 候補の計測指定::影の視距離(切断距離) = 候補 else {
        return 影視距離の検収世界が受ける候補の軸.綴りの一致を課す(候補.綴り(), 計測軸::影の視距離.綴り());
    };
    range_world::切断の距離を確かめる(切断距離.値())
}
