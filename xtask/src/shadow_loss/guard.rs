//! 負の対照として作った構図の期待の判定。受け取るのは構図と比較結果、返すのは期待を満たしたかどうかである。
//! 判定を計器の本体から分けるのは、地形の代表世界では失われる量に正解が無く、判定するのが検収世界だけだからである。

use super::compare::比較結果;
use super::scene_choice;

/// 負の対照として作った構図だけを判定する。基準に影があり、そのうちの一部が候補で消え、消え残った影が残ることを見る。
/// 余分が出ないことも見るのは、切断が「候補を減らす」操作であり、影が増えることが原理的に起こらないためである。
pub(super) fn 負の対照を判定する(構図: scene_choice::構図, 比較: &比較結果) -> Result<(), String> {
    if 構図.期待() != scene_choice::構図の期待::負の対照として判定する {
        return Ok(());
    }
    let 基準の影 = 比較.帯別.iter().map(|集計| 集計.基準の影画素数).sum::<u64>();
    let 候補の影 = 比較.帯別.iter().map(|集計| 集計.候補の影画素数).sum::<u64>();
    let 欠落 = 比較.帯別.iter().map(|集計| 集計.欠落画素数).sum::<u64>();
    let 余分 = 比較.帯別.iter().map(|集計| 集計.余分画素数).sum::<u64>();
    if 基準の影 == 0 {
        return Err("基準に影の画素が1つも無い。遠方キャスターも近距離対照も影を落としていない".to_string());
    }
    if 欠落 == 0 {
        return Err("候補で消えた影が1画素も無い。切断が遠方キャスターへ届いていない".to_string());
    }
    if 候補の影 == 0 {
        return Err("候補に影の画素が1つも残っていない。近距離対照の影まで消えている".to_string());
    }
    if 余分 != 0 {
        return Err(format!(
            "候補で影が増えた画素が{余分}件ある。切断は候補を減らす操作であり増えてはならない"
        ));
    }
    println!("  負の対照の判定: 基準の影{基準の影}画素のうち{欠落}画素が消え、{候補の影}画素が残った(余分は0)");
    Ok(())
}
