//! 帯番号の符号化と読み戻しが往復することの固定。シェーダーが載せる値をここで作り直し、
//! 8ビットへ量子化してから読み戻して同じ番号へ戻ることを全帯について見る。
//! 往復が壊れる原因は、帯の数の写しの食い違いか、伝達関数の取り違えか、量子化の幅の不足である。
//! どれも絵には出ず、欠落の数が黙って別の帯へ計上される形で現れる。

#![allow(clippy::as_conversions)]
#![allow(clippy::unwrap_used)]

use super::{帯数, 帯数の実数, 帯番号を戻す, 線形へ戻す};

/// シェーダーと同じ符号化。線形値を交換チェーンのsRGB符号化にかけて8ビットへ量子化する。
fn 符号化する(線形: f64) -> u8 {
    let 符号化 = if 線形 <= 0.003_130_8 {
        線形 * 12.92
    } else {
        1.055 * 線形.powf(1.0 / 2.4) - 0.055
    };
    (符号化 * 255.0).round().clamp(0.0, 255.0) as u8
}

#[test]
fn 全帯の符号化と読み戻しが往復する() {
    for 番号 in 0..帯数 {
        let 線形 = (番号 as f64 + 1.0) / 帯数の実数;
        assert_eq!(帯番号を戻す(符号化する(線形)), 番号, "帯{番号}が往復しない");
    }
}

#[test]
fn 影可視度は符号化して戻すと元の値に近い() {
    for 目盛り in 0..=10 {
        let 実数 = f64::from(目盛り) / 10.0;
        let 戻り = 線形へ戻す(符号化する(実数));
        assert!((戻り - 実数).abs() < 0.01, "影可視度{実数}が{戻り}へずれた");
    }
}
