//! 影の欠落計器のエラーを人が読む1文へ写すトレイト実装。枝ごとに、どの前提がどう破れたかを出す。
//! 実装を型の定義と分けるのは、外部トレイトの実装が型自身の持ち物とは別の軸であるためである。

use std::fmt;

use super::影の欠落計器のエラー;

impl fmt::Display for 影の欠落計器のエラー {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::検収の器が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::判定が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::引数が破れた(破れ) => write!(書き手, "{破れ}"),
            Self::検証用アセットを生成できなかった => write!(書き手, "検証用アセットの生成に失敗した"),
            Self::前の実行の差分画像を消せなかった { パス, 誤り } => {
                write!(書き手, "前の実行の差分画像を消せなかった({}): {誤り}", パス.display())
            }
            Self::差分画像を書けなかった { パス, 誤り } => {
                write!(書き手, "差分画像を書けなかった({}): {誤り}", パス.display())
            }
            Self::差分画像の寸法を書けなかった { パス, 誤り } => {
                write!(書き手, "差分画像の寸法を書けなかった({}): {誤り}", パス.display())
            }
        }
    }
}
