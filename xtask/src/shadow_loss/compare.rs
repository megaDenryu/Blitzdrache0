//! 基準と候補の診断画像を受光距離帯ごとに突き合わせる工程。受け取るのは2枚、返すのは帯ごとの欠落と余分の集計である。
//!
//! 欠落は「基準で影の中、候補で影の外」であり、影が失われた画素である。余分はその逆であり、影が増えた画素である。
//! 数だけでなく影可視度の弱まりと強まりも足すのは、PCFが中間の値を返すため、閾値をまたがない薄まり方も起こるためである。
//! 帯が2枚で食い違った画素を別に数えるのは、同じカメラと同じ幾何で描いた2枚では帯が一致するはずであり、
//! 食い違いが出たらその実行が比較の前提を満たしていないことの証拠になるためである。

use super::diagnostic_image::{帯数, 診断画像};

#[derive(Clone, Copy, Default)]
pub(super) struct 帯の集計 {
    pub(super) 基準の影画素数: u64,
    pub(super) 候補の影画素数: u64,
    pub(super) 欠落画素数: u64,
    pub(super) 余分画素数: u64,
    /// 候補で影可視度が上がった量の合計。影が薄れた総量である。
    pub(super) 影の弱まり量: f64,
    /// 候補で影可視度が下がった量の合計。影が濃くなった総量である。
    pub(super) 影の強まり量: f64,
}

pub(super) struct 比較結果 {
    pub(super) 帯別: [帯の集計; 帯数],
    /// どちらか一方だけが幾何を持った画素の数。カメラと幾何が同じなら0である。
    pub(super) 幾何の食い違い画素数: u64,
    /// 両方が幾何を持ちながら帯が違った画素の数。固定刻みの帯は候補の指定で動かないため0である。
    pub(super) 帯の食い違い画素数: u64,
    /// 欠落した画素を印にした並び。差分画像の書き出しが読む。
    pub(super) 欠落の印: Vec<bool>,
    pub(super) 余分の印: Vec<bool>,
}

pub(super) fn 比べる(基準: &診断画像, 候補: &診断画像) -> Result<比較結果, String> {
    if 基準.幅 != 候補.幅 || 基準.高さ != 候補.高さ {
        return Err("基準と候補の読み戻し寸法が違う".to_string());
    }
    let 画素数 = 基準.画素数();
    let mut 結果 = 比較結果 {
        帯別: [帯の集計::default(); 帯数],
        幾何の食い違い画素数: 0,
        帯の食い違い画素数: 0,
        欠落の印: vec![false; 画素数],
        余分の印: vec![false; 画素数],
    };
    for 添字 in 0..画素数 {
        let (Some(基準画素), Some(候補画素)) = (基準.画素(添字), 候補.画素(添字)) else {
            if 基準.画素(添字).is_some() != 候補.画素(添字).is_some() {
                結果.幾何の食い違い画素数 += 1;
            }
            continue;
        };
        if 基準画素.受光距離帯 != 候補画素.受光距離帯 {
            結果.帯の食い違い画素数 += 1;
            continue;
        }
        let Some(集計) = 結果.帯別.get_mut(基準画素.受光距離帯) else {
            continue;
        };
        積む(集計, 基準画素.影の中か(), 候補画素.影の中か(), 基準画素.影可視度, 候補画素.影可視度);
        if 基準画素.影の中か() && !候補画素.影の中か() {
            結果.欠落の印[添字] = true;
        }
        if !基準画素.影の中か() && 候補画素.影の中か() {
            結果.余分の印[添字] = true;
        }
    }
    Ok(結果)
}

fn 積む(集計: &mut 帯の集計, 基準の影: bool, 候補の影: bool, 基準の可視度: f64, 候補の可視度: f64) {
    集計.基準の影画素数 += u64::from(基準の影);
    集計.候補の影画素数 += u64::from(候補の影);
    集計.欠落画素数 += u64::from(基準の影 && !候補の影);
    集計.余分画素数 += u64::from(!基準の影 && 候補の影);
    let 差 = 候補の可視度 - 基準の可視度;
    if 差 > 0.0 {
        集計.影の弱まり量 += 差;
    } else {
        集計.影の強まり量 -= 差;
    }
}
