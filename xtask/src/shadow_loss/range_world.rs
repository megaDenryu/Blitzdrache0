//! 影視距離の検収世界の幾何の写し。担当するのは、2体それぞれのカメラからの距離と、2体の影が落ちる受光面の矩形である。
//! 写しを持つのはxtaskが他クレートへ依存しない規律のためであり、正本は
//! `crates/blitz_asset_compiler/src/vegetation/shadow_range_placement.rs`の配置と、
//! `crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラと、
//! `crates/blitz_app/src/app/scene_lighting.rs`の検収用ライト方針である。
//!
//! カメラは注視点(50, 0, 50)を距離45メートル・俯角60度で見下ろすため、視点は(50, 38.97, 72.5)にある。
//! 可視判定が読む距離は個体の境界球の中心までであり、その中心は原型の直方体(水平半辺0.8メートル・高さ3メートル)の
//! 中心を配置で写した点である。近距離対照は(50, 1.5, 62)で視点から38.9メートル、遠方キャスターは倍率12で
//! (150, 18, 50)となり視点から104.6メートルにある。
//!
//! 方向光は(-1, -0.4, 0)のほぼ水平であり、影は個体のZを保ったまま-X方向へ伸びる。2体のZは12メートル離れているため、
//! 2つの影は床の上で交わらない2本の帯になる。見下ろす構図では、カメラに近い近距離対照の帯が画面の下、
//! 遠方キャスターの帯が画面の上に写る。下の2つの矩形はその2本の帯の内側に余白を取って置いた。

use super::region_count::受光面の領域;

/// 矩形が指す画面の寸法。矩形を画素で固定しているため、別の寸法で描いた絵では同じ矩形が別の場所を指す。
const 想定する画面の幅: usize = 1280;
const 想定する画面の高さ: usize = 720;

/// 近距離対照の境界球の中心から視点までの距離。
const 近距離対照のカメラ距離メートル: f64 = 38.9;
/// 遠方キャスターの境界球の中心から視点までの距離。
const 遠方キャスターのカメラ距離メートル: f64 = 104.6;
/// 切断の距離に要る余裕。この写しの丸めと、エンジンがf32で組み立てる距離との微差を吸収する。
const 距離の余裕メートル: f64 = 1.0;

/// 遠方キャスターの長い影が落ちる帯の内側。
pub(super) const 遠方キャスターの影の領域: 受光面の領域 = 受光面の領域::生成する(800, 1200, 300, 450);
/// 近距離対照の短い影が落ちる帯の内側。
pub(super) const 近距離対照の影の領域: 受光面の領域 = 受光面の領域::生成する(510, 624, 515, 537);

pub(super) fn 画面の寸法を確かめる(幅: usize, 高さ: usize) -> Result<(), String> {
    if 幅 != 想定する画面の幅 || 高さ != 想定する画面の高さ {
        return Err(format!(
            "読み戻し画像が{幅}×{高さ}である。受光面の領域は{想定する画面の幅}×{想定する画面の高さ}の画面へ固定した矩形であり、別の寸法では別の場所を指す"
        ));
    }
    Ok(())
}

/// 切断の距離が2体のあいだにあることを確かめる。外にあると2体とも消えるか2体とも残るかになり、
/// 「遠方キャスターの影だけが消える」という負の対照が成立しない。
pub(super) fn 切断の距離を確かめる(切断距離: f64) -> Result<(), String> {
    let 下限 = 近距離対照のカメラ距離メートル + 距離の余裕メートル;
    let 上限 = 遠方キャスターのカメラ距離メートル - 距離の余裕メートル;
    if 切断距離 < 下限 || 切断距離 > 上限 {
        return Err(format!(
            "影の視距離{切断距離}メートルはこの世界では負の対照にならない。近距離対照が{近距離対照のカメラ距離メートル}メートル、遠方キャスターが{遠方キャスターのカメラ距離メートル}メートルにあり、切断は{下限}から{上限}メートルの範囲に要る"
        ));
    }
    Ok(())
}

