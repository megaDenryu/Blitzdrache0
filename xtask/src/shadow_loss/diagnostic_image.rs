//! 影の欠落計器の診断画像1枚の読み取り。受け取るのは読み戻し画像、返すのは画素ごとの影可視度と受光距離帯である。
//!
//! 符号化は`shaders/pixel_diagnostic.slang`の`shadowLossDiagnosticColor`が作る。赤が影可視度、緑が受光距離帯、青が幾何の印である。
//! 出力は交換チェーンのsRGB符号化を通るため、ここで同じ伝達関数の逆をかけて線形へ戻す。
//! 注意: 帯の刻みと帯の数はエンジンのクレートを参照せずここに写しを持つ(xtaskは他クレートへ依存しない規律)。
//! 値の正本は`crates/blitz_render/src/cascade/diagnostic.rs`であり、slangの写しとの一致は`cargo xtask conform`が見る。

#[cfg(test)]
mod band_tests;

use crate::acceptance::{画素の番号, 読み戻し画像};

/// 受光距離帯の数。`受光距離帯数`の写しである。
pub(super) const 帯数: usize = 16;
/// 受光距離帯の数を実数で持ったもの。帯の境界を割り算で作るために持ち、上の`帯数`と同じ値でなければならない。
/// 2つが食い違うと帯番号の読み戻しがずれるため、下のテストが往復で固定する。
const 帯数の実数: f64 = 16.0;
/// 受光距離帯1つの幅。`受光距離帯の幅メートル`の写しである。
pub(super) const 帯の幅メートル: f64 = 25.0;
/// 幾何の印とみなす青の下限。背景は既定のクリア色(青成分0.12)であり、この下限に遠く届かない。
const 幾何の印の下限: u8 = 250;
/// 影の中とみなす影可視度の上限。PCFは3x3の平均であるため中間の値が出る。半分より暗い画素を影とする。
const 影とみなす影可視度: f64 = 0.5;

#[derive(Clone, Copy)]
pub(super) struct 診断画素 {
    pub(super) 影可視度: f64,
    /// 0から始まる受光距離帯の番号。最後の帯は上限を持たない。
    pub(super) 受光距離帯: usize,
}

impl 診断画素 {
    pub(super) fn 影の中か(self) -> bool {
        self.影可視度 < 影とみなす影可視度
    }
}

pub(super) struct 診断画像 {
    pub(super) 幅: usize,
    pub(super) 高さ: usize,
    /// 幾何の印が立っていない画素(背景)は`None`である。
    画素一覧: Vec<Option<診断画素>>,
}

impl 診断画像 {
    pub(super) fn 読み取る(読み戻し: &読み戻し画像) -> Self {
        Self {
            幅: 読み戻し.幅().画素数(),
            高さ: 読み戻し.高さ().画素数(),
            画素一覧: (0..読み戻し.画素数())
                .map(|添字| 判別する(読み戻し.番号の画素(画素の番号::生成する(添字))))
                .collect(),
        }
    }

    pub(super) fn 画素(&self, 添字: usize) -> Option<診断画素> {
        self.画素一覧.get(添字).copied().flatten()
    }

    pub(super) fn 画素数(&self) -> usize {
        self.画素一覧.len()
    }
}

fn 判別する(色: [u8; 3]) -> Option<診断画素> {
    let [赤, 緑, 青] = 色;
    if 青 < 幾何の印の下限 {
        return None;
    }
    Some(診断画素 {
        影可視度: 線形へ戻す(赤),
        受光距離帯: 帯番号を戻す(緑),
    })
}

/// 緑の値から帯番号を戻す。シェーダーは(帯+1)/帯数を載せるため、隣り合う帯の中点と順に比べれば丸めの縮小変換を持ち込まずに戻せる。
fn 帯番号を戻す(緑: u8) -> usize {
    let 値 = 線形へ戻す(緑);
    let 刻み = 1.0 / 帯数の実数;
    let mut 番号 = 0;
    let mut 中点 = 刻み * 1.5;
    while 番号 + 1 < 帯数 && 値 >= 中点 {
        番号 += 1;
        中点 += 刻み;
    }
    番号
}

/// sRGBの伝達関数の逆。交換チェーンが書き出しで掛けた符号化をここで打ち消す。
fn 線形へ戻す(値: u8) -> f64 {
    let 符号化 = f64::from(値) / 255.0;
    if 符号化 <= 0.040_448_236 {
        return 符号化 / 12.92;
    }
    ((符号化 + 0.055) / 1.055).powf(2.4)
}
