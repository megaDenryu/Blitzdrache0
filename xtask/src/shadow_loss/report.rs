//! 比較結果を人が読める表にする工程。受け取るのは比較結果、出すのは標準出力への行だけである。
//! 合否の裁定は行わない。どこまでの欠落を許すかはオーナーが決める値であり、この計器は数を出すことだけを担う。

use super::compare::比較結果;
use super::diagnostic_image::{帯の幅メートル, 帯数};

pub(super) fn 表示する(比較: &比較結果) {
    println!();
    println!("受光距離帯 / 基準の影画素数 / 候補の影画素数 / 欠落 / 余分 / 影の弱まり量 / 影の強まり量");
    let mut 帯の下限 = 0.0;
    for (番号, 集計) in 比較.帯別.into_iter().enumerate() {
        let 帯の上限 = 帯の下限 + 帯の幅メートル;
        if 集計.基準の影画素数 != 0 || 集計.候補の影画素数 != 0 {
            println!(
                "  {} / {} / {} / {} / {} / {:.1} / {:.1}",
                帯の呼び名(番号, 帯の下限, 帯の上限),
                集計.基準の影画素数,
                集計.候補の影画素数,
                集計.欠落画素数,
                集計.余分画素数,
                集計.影の弱まり量,
                集計.影の強まり量
            );
        }
        帯の下限 = 帯の上限;
    }
    println!(
        "  合計 / {} / {} / {} / {} / {:.1} / {:.1}",
        合計(比較, 基準の影),
        合計(比較, 候補の影),
        合計(比較, 欠落),
        合計(比較, 余分),
        実数の合計(比較, 弱まり),
        実数の合計(比較, 強まり)
    );
    println!("  幾何の食い違い画素数: {}", 比較.幾何の食い違い画素数);
    println!("  帯の食い違い画素数: {}", 比較.帯の食い違い画素数);
}

/// 帯の呼び名。最後の帯は上限を持たず、それより遠い受光点をすべて受けるため、上限を書かない。
fn 帯の呼び名(番号: usize, 下限: f64, 上限: f64) -> String {
    if 番号 + 1 == 帯数 {
        return format!("{下限:.0}メートル以上");
    }
    format!("{下限:.0}から{上限:.0}メートル")
}

fn 合計(比較: &比較結果, 取り出す: fn(&super::compare::帯の集計) -> u64) -> u64 {
    比較.帯別.iter().map(取り出す).sum()
}

fn 実数の合計(比較: &比較結果, 取り出す: fn(&super::compare::帯の集計) -> f64) -> f64 {
    比較.帯別.iter().map(取り出す).sum()
}

fn 基準の影(集計: &super::compare::帯の集計) -> u64 {
    集計.基準の影画素数
}

fn 候補の影(集計: &super::compare::帯の集計) -> u64 {
    集計.候補の影画素数
}

fn 欠落(集計: &super::compare::帯の集計) -> u64 {
    集計.欠落画素数
}

fn 余分(集計: &super::compare::帯の集計) -> u64 {
    集計.余分画素数
}

fn 弱まり(集計: &super::compare::帯の集計) -> f64 {
    集計.影の弱まり量
}

fn 強まり(集計: &super::compare::帯の集計) -> f64 {
    集計.影の強まり量
}
