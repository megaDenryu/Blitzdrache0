//! 受光面の1つの矩形と、その中の影の数え上げ。受け取るのは矩形と比較結果、返すのはその矩形だけの集計である。
//!
//! 全画面の合計では「遠方キャスターの影が消えて近距離対照の影が残った」と「近距離対照の影が消えて別の影が残った」を
//! 区別できない。どちらも「一部が消え一部が残った」になるためである。落ちる場所で分けて数えるのがこの工程の役目であり、
//! どの矩形をどう解釈するかは`range_world`が持つ。

use super::compare::比較結果;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 受光面の画素矩形。終端は含まない。
pub(super) struct 受光面の領域 {
    x開始: usize,
    x終端: usize,
    y開始: usize,
    y終端: usize,
}

pub(super) struct 領域の集計 {
    pub(super) 基準の影画素数: u64,
    pub(super) 候補の影画素数: u64,
    pub(super) 欠落画素数: u64,
}

impl 受光面の領域 {
    pub(super) const fn 生成する(x開始: usize, x終端: usize, y開始: usize, y終端: usize) -> Self {
        Self {
            x開始, x終端, y開始, y終端
        }
    }

    /// 矩形が覆う画素の添字。数え上げと、判定の固定が印を塗る側の両方がこの1つの並べ方を使う。
    pub(super) fn 画素の添字(&self, 幅: usize) -> impl Iterator<Item = usize> {
        let (x開始, x終端) = (self.x開始, self.x終端);
        (self.y開始..self.y終端).flat_map(move |y| (x開始..x終端).map(move |x| y * 幅 + x))
    }

    pub(super) fn 数える(&self, 比較: &比較結果) -> Result<領域の集計, 判定の破れ> {
        let 判定名 = 領域が読む画素を持つ印の本数の判定名(比較);
        let mut 集計 = 領域の集計 {
            基準の影画素数: 0,
            候補の影画素数: 0,
            欠落画素数: 0,
        };
        for 添字 in self.画素の添字(比較.幅) {
            let 基準の影 = 印を読む(&比較.基準の影の印, 添字, &判定名)?;
            let 候補の影 = 印を読む(&比較.候補の影の印, 添字, &判定名)?;
            集計.基準の影画素数 += u64::from(基準の影);
            集計.候補の影画素数 += u64::from(候補の影);
            集計.欠落画素数 += u64::from(基準の影 && !候補の影);
        }
        Ok(集計)
    }
}

/// 印の並びから1画素ぶんを読む。並びがその添字まで届いていなければ、矩形が読み戻し画像の外を指している。
///
/// 注意: 添字での読み出しは、直前の下限の判定が通った後だけに置く。判定が通れば並びはその添字まで届いており、
/// 添字が並びの外を指すことは到達しないバグである。
fn 印を読む(印一覧: &[bool], 添字: usize, 判定名: &判定の名前) -> Result<bool, 判定の破れ> {
    判定名.下限を課す(印一覧.len(), 添字 + 1)?;
    Ok(印一覧[添字])
}

fn 領域が読む画素を持つ印の本数の判定名(比較: &比較結果) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "受光面の領域が読む画素を持つ影の印の本数(読み戻し画像は{}×{}であり、届かなければ矩形がその外を指している)",
        比較.幅, 比較.高さ
    ))
}

