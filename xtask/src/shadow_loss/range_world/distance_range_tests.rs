//! 切断の距離の範囲と画面の寸法の固定。担当するのは、受け入れる距離の境目が2体のカメラ距離から
//! 余裕を取った位置にあることを固定することである。境目が動くと、負の対照にならないDを黙って受けるか、
//! 成立するDを拒むかのどちらかになる。

use super::{切断の距離を確かめる, 想定する画面の幅, 想定する画面の高さ, 画面の寸法を確かめる};

#[test]
fn 二体のあいだの距離は受ける() {
    assert!(切断の距離を確かめる(80.0).is_ok(), "設計正本が記録した実測の水準である");
    assert!(切断の距離を確かめる(39.91).is_ok(), "近距離対照38.9メートルに余裕1メートルを足した内側");
    assert!(
        切断の距離を確かめる(103.59).is_ok(),
        "遠方キャスター104.6メートルから余裕1メートルを引いた内側"
    );
}

#[test]
fn 近距離対照より内側の距離は拒む() {
    assert!(切断の距離を確かめる(39.89).is_err(), "近距離対照の影まで消える側である");
    assert!(切断の距離を確かめる(10.0).is_err());
}

#[test]
fn 遠方キャスターより外側の距離は拒む() {
    assert!(切断の距離を確かめる(103.61).is_err(), "遠方キャスターの影が消えない側である");
    assert!(切断の距離を確かめる(120.0).is_err(), "この距離では欠落が0になることを実測している");
    assert!(切断の距離を確かめる(200.0).is_err());
}

#[test]
fn 想定した寸法だけを受ける() {
    assert!(画面の寸法を確かめる(想定する画面の幅, 想定する画面の高さ).is_ok());
    assert!(画面の寸法を確かめる(想定する画面の幅 * 2, 想定する画面の高さ).is_err());
    assert!(画面の寸法を確かめる(想定する画面の幅, 想定する画面の高さ / 2).is_err());
}
