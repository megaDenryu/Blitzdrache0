//! 矩形の数え上げの固定。担当するのは、添字の組み立て(縦の位置に幅を掛けて横の位置を足す)が正しいことと、
//! 基準と候補の印の組み合わせが基準の影・候補の影・欠落の3つへ正しく振り分くことである。
//! 添字の組み立てを間違えると、判定は落ちずに別の場所を数えた値で通ってしまう。

use super::受光面の領域;
use crate::shadow_loss::comparison_fixture::影の無い比較結果;

const 幅: usize = 8;
const 高さ: usize = 6;

#[test]
fn 矩形の外の画素は数えない() {
    let mut 比較 = 影の無い比較結果(幅, 高さ);
    for 添字 in 0..幅 * 高さ {
        比較.基準の影の印[添字] = true;
    }
    let 領域 = 受光面の領域::生成する(2, 5, 1, 3);
    let 集計 = 領域.数える(&比較).unwrap_or_else(|誤り| panic!("数え上げが失敗した: {誤り}"));
    assert_eq!(集計.基準の影画素数, 6, "矩形は横3画素・縦2行である");
}

#[test]
fn 基準と候補の印を欠落へ振り分ける() {
    let mut 比較 = 影の無い比較結果(幅, 高さ);
    let 領域 = 受光面の領域::生成する(2, 5, 1, 3);
    // 縦1行目の3画素は基準だけ影(欠落)、縦2行目の3画素は両方が影(残存)にする。
    for 添字 in [幅 + 2, 幅 + 3, 幅 + 4] {
        比較.基準の影の印[添字] = true;
    }
    for 添字 in [2 * 幅 + 2, 2 * 幅 + 3, 2 * 幅 + 4] {
        比較.基準の影の印[添字] = true;
        比較.候補の影の印[添字] = true;
    }
    let 集計 = 領域.数える(&比較).unwrap_or_else(|誤り| panic!("数え上げが失敗した: {誤り}"));
    assert_eq!(集計.基準の影画素数, 6);
    assert_eq!(集計.候補の影画素数, 3);
    assert_eq!(集計.欠落画素数, 3);
}

#[test]
fn 画像の外へ出る矩形は失敗する() {
    let 比較 = 影の無い比較結果(幅, 高さ);
    let 領域 = 受光面の領域::生成する(2, 5, 4, 8);
    assert!(領域.数える(&比較).is_err(), "縦8行目は高さ6の画像に無い");
}
