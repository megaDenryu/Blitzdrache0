//! 負の対照として作った構図にだけ効く期待の判定。担当するのは、受光面の2つの矩形それぞれで
//! 影がどれだけ消えどれだけ残るべきかの判定値と、その判定と、読み手へ出す1行である。
//! 見るのは比較結果のうち影の印だけであり、帯ごとの集計は余分の合計しか読まない。
//!
//! 遠方キャスターの影が落ちる領域と近距離対照の影が落ちる領域を別々に数えるのは、全画面の合計では
//! 「遠方キャスターの影が消えて近距離対照の影が残った」と「近距離対照の影が消えて別の影が残った」を区別できないためである。

use super::super::compare::比較結果;
use super::super::range_world;
use super::super::scene_choice;
use crate::acceptance::{判定の名前, 判定の破れ};

/// 遠方キャスターの領域で欠落が支配的だとみなす百分率の下限。
const 遠方キャスターの欠落の下限百分率: u64 = 90;
/// 近距離対照の領域で影が残ったとみなす百分率の下限。
const 近距離対照の残存の下限百分率: u64 = 90;

const 遠方キャスターの影の領域で消えた百分率: 判定の名前 =
    判定の名前::定数から生成する("遠方キャスターの影の領域で基準の影のうち消えた百分率(下限を割るなら切断がその影へ届いていない)");
const 近距離対照の影の領域で残った百分率: 判定の名前 =
    判定の名前::定数から生成する("近距離対照の影の領域で基準の影のうち残った百分率(下限を割るなら切断が近距離対照の影まで消している)");
const 候補で影が増えた画素数: 判定の名前 =
    判定の名前::定数から生成する("候補で影が増えた画素数(切断は候補を減らす操作であり、影が増えることは原理的に起こらない)");
const 遠方キャスターの影の領域にある基準の影の画素: 判定の名前 =
    判定の名前::定数から生成する("遠方キャスターの影の領域にある基準の影の画素(1画素も無ければ世界かカメラか光の向きが想定と違う)");
const 近距離対照の影の領域にある基準の影の画素: 判定の名前 =
    判定の名前::定数から生成する("近距離対照の影の領域にある基準の影の画素(1画素も無ければ世界かカメラか光の向きが想定と違う)");

/// 負の対照として作った構図だけを判定する。遠方キャスターの影が落ちる領域と近距離対照の影が落ちる領域を
/// 別々に数え、前者で欠落が支配的であることと、後者で影が残ることを直接見る。
pub(in crate::shadow_loss) fn 負の対照を判定する(構図: scene_choice::構図, 比較: &比較結果) -> Result<(), 判定の破れ> {
    if 構図.期待() != scene_choice::構図の期待::負の対照として判定する {
        return Ok(());
    }
    range_world::画面の寸法を確かめる(比較.幅, 比較.高さ)?;
    領域別に判定する(比較)
}

fn 領域別に判定する(比較: &比較結果) -> Result<(), 判定の破れ> {
    let 遠方 = range_world::遠方キャスターの影の領域.数える(比較)?;
    let 近距離 = range_world::近距離対照の影の領域.数える(比較)?;
    let 遠方の欠落 = 百分率を求める(遠方.欠落画素数, 遠方.基準の影画素数, &遠方キャスターの影の領域にある基準の影の画素)?;
    let 近距離の残存 = 百分率を求める(近距離.候補の影画素数, 近距離.基準の影画素数, &近距離対照の影の領域にある基準の影の画素)?;
    遠方キャスターの影の領域で消えた百分率.下限を課す(遠方の欠落, 遠方キャスターの欠落の下限百分率)?;
    近距離対照の影の領域で残った百分率.下限を課す(近距離の残存, 近距離対照の残存の下限百分率)?;
    余分が無いことを確かめる(比較)?;
    println!(
        "  負の対照の判定: 遠方キャスターの影の領域は基準の影{}画素の{遠方の欠落}パーセントが消え、近距離対照の影の領域は基準の影{}画素の{近距離の残存}パーセントが残った(余分は0)",
        遠方.基準の影画素数, 近距離.基準の影画素数
    );
    Ok(())
}

/// 余分が出ないことを見るのは、切断が「候補を減らす」操作であり、影が増えることが原理的に起こらないためである。
fn 余分が無いことを確かめる(比較: &比較結果) -> Result<(), 判定の破れ> {
    候補で影が増えた画素数.零件であることを課す(比較.帯別.iter().map(|集計| 集計.余分画素数).sum::<u64>())
}

/// 百分率の母数が1画素も無ければ0で割ることになる。割る前に、母数が無いことをそのまま破れとして返す。
fn 百分率を求める(該当数: u64, 母数: u64, 母数の判定名: &判定の名前) -> Result<u64, 判定の破れ> {
    if 母数 == 0 {
        return Err(母数の判定名.あるはずのものが無い破れ());
    }
    Ok(該当数 * 100 / 母数)
}
