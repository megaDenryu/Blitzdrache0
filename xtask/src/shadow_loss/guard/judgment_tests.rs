//! 判定の正例と負例の固定。GPUを回さず、比較結果へ手で印を塗って判定関数へ渡す。
//! 主目的は、全画面の合計では区別できない退行(近距離対照の影が消えて遠方キャスターの影が残る)が落ちることの固定である。

use super::{前提を確かめる, 負の対照を判定する};
use crate::shadow_loss::comparison_fixture::{
    候補に残す画素を先頭から作る, 固定の幅, 固定の高さ, 影の無い比較結果, 影を塗る, 負の対照が成り立つ比較結果, 領域の画素数,
};
use crate::shadow_loss::range_world::{近距離対照の影の領域, 遠方キャスターの影の領域};
use crate::shadow_loss::scene_choice::構図;

#[test]
fn 負の対照が成り立つ実行は通る() {
    assert!(負の対照を判定する(構図::影視距離の検収, &負の対照が成り立つ比較結果()).is_ok());
}

#[test]
fn 遠方キャスターの影が残ると落ちる() {
    let mut 比較 = 負の対照が成り立つ比較結果();
    影を塗る(&mut 比較, &遠方キャスターの影の領域, true);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err(), "切断が届いていない");
}

/// 全画面の合計では「一部が消え一部が残った」になり、是正前の判定はこの退行を通していた。
#[test]
fn 近距離対照が消えて遠方キャスターが残る退行を落とす() {
    let mut 比較 = 負の対照が成り立つ比較結果();
    影を塗る(&mut 比較, &遠方キャスターの影の領域, true);
    影を塗る(&mut 比較, &近距離対照の影の領域, false);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err());
}

#[test]
fn 遠方キャスターの領域に基準の影が無ければ落ちる() {
    let mut 比較 = 影の無い比較結果(固定の幅, 固定の高さ);
    影を塗る(&mut 比較, &近距離対照の影の領域, true);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err());
}

#[test]
fn 欠落が下限ちょうどなら通る() {
    let mut 比較 = 負の対照が成り立つ比較結果();
    候補に残す画素を先頭から作る(&mut 比較, &遠方キャスターの影の領域, 領域の画素数(&遠方キャスターの影の領域) / 10);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_ok(), "欠落90パーセント");
}

#[test]
fn 欠落が下限を下回ると落ちる() {
    let mut 比較 = 負の対照が成り立つ比較結果();
    候補に残す画素を先頭から作る(&mut 比較, &遠方キャスターの影の領域, 領域の画素数(&遠方キャスターの影の領域) / 10 + 1);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err(), "欠落89パーセント");
}

#[test]
fn 残存が下限を下回ると落ちる() {
    let mut 比較 = 負の対照が成り立つ比較結果();
    候補に残す画素を先頭から作る(&mut 比較, &近距離対照の影の領域, 領域の画素数(&近距離対照の影の領域) * 89 / 100);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err(), "残存88パーセント");
}

#[test]
fn 余分が1画素でもあれば落ちる() {
    let mut 比較 = 負の対照が成り立つ比較結果();
    if let Some(集計) = 比較.帯別.first_mut() {
        集計.余分画素数 = 1;
    }
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err());
}

#[test]
fn 画面の寸法が違えば落ちる() {
    let 比較 = 影の無い比較結果(固定の幅 / 2, 固定の高さ / 2);
    assert!(負の対照を判定する(構図::影視距離の検収, &比較).is_err(), "矩形が別の場所を指す");
}

#[test]
fn 地形の構図は期待を判定しない() {
    let 比較 = 影の無い比較結果(固定の幅, 固定の高さ);
    assert!(負の対照を判定する(構図::地形, &比較).is_ok(), "失われる量に正解が無い構図である");
}

#[test]
fn 幾何の食い違いがあれば前提が破れる() {
    let mut 比較 = 影の無い比較結果(固定の幅, 固定の高さ);
    比較.幾何の食い違い画素数 = 1;
    assert!(前提を確かめる(&比較).is_err());
}

#[test]
fn 帯の食い違いがあれば前提が破れる() {
    let mut 比較 = 影の無い比較結果(固定の幅, 固定の高さ);
    比較.帯の食い違い画素数 = 1;
    assert!(前提を確かめる(&比較).is_err());
}

#[test]
fn どちらの食い違いも無ければ前提は満たされる() {
    assert!(前提を確かめる(&影の無い比較結果(固定の幅, 固定の高さ)).is_ok());
}
