//! 影の欠落計器の引数解釈。担当するのは、引数の語から構図の選択とちょうど1つの候補の指定を作ることである。
//!
//! 候補をちょうど1つだけ受けるのは、設計の正本が「αとβを同時に変えない」と定めるためである。
//! 1つも渡らない実行も、2つ渡った実行も、同じ軸を2回渡した実行もここで失敗にする。
//! 参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「シャドウ性能の是正(フェーズ2性能課題、2026-08-03着手)」

use super::argument_error::影の欠落計器の引数の破れ;
use super::candidate_axis::{候補の計測指定, 計測軸};
use super::scene_choice;

/// 1回の実行で計器が何をするか。数える様式と撮る様式は出す成果物も描く条件も違うため、同じ実行で兼ねない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 計器の様式 {
    /// 診断出力を読み、受光距離帯ごとの欠落と余分を数える。
    影の欠落を数える,
    /// 本番の見た目で2枚を撮る。比較も判定もしない。
    最終色の絵を撮る,
}

pub(super) struct 指定 {
    pub(super) 構図: scene_choice::構図,
    pub(super) 候補: 候補の計測指定,
    pub(super) 様式: 計器の様式,
}

pub(super) fn 引数を読む(引数一覧: &[String]) -> Result<指定, 影の欠落計器の引数の破れ> {
    let mut 構図: Option<scene_choice::構図> = None;
    let mut 候補: Option<候補の計測指定> = None;
    let mut 様式 = 計器の様式::影の欠落を数える;
    let mut 残り = 引数一覧.iter();
    while let Some(語) = 残り.next() {
        if 語 == "--layout" {
            let 値 = 残り.next().ok_or_else(|| 値が無い破れ(語))?;
            if 構図.is_some() {
                return Err(影の欠落計器の引数の破れ::構図の指定が2回ある);
            }
            構図 = Some(scene_choice::綴りから読む(値)?);
            continue;
        }
        if 語 == "--final-color" {
            様式 = 計器の様式::最終色の絵を撮る;
            continue;
        }
        let 軸 =
            計測軸::綴りから読む(語).ok_or_else(|| 影の欠落計器の引数の破れ::知らない引数を渡された { 語: 語.clone() })?;
        let 値 = 残り.next().ok_or_else(|| 値が無い破れ(語))?;
        if let Some(先に読んだ候補) = &候補 {
            return Err(影の欠落計器の引数の破れ::候補の指定が2つある {
                先に読んだ候補: 先に読んだ候補.綴り(),
                後の候補: 軸.綴り(),
            });
        }
        候補 = Some(軸.値を添える(値)?);
    }
    組み立てる(構図.unwrap_or(scene_choice::構図::地形), 候補, 様式)
}

fn 値が無い破れ(語: &str) -> 影の欠落計器の引数の破れ {
    影の欠落計器の引数の破れ::語の次に値が無い { 語: 語.to_string() }
}

fn 組み立てる(
    構図: scene_choice::構図, 候補: Option<候補の計測指定>, 様式: 計器の様式
) -> Result<指定, 影の欠落計器の引数の破れ> {
    let 候補 = 候補.ok_or_else(|| 影の欠落計器の引数の破れ::候補の指定が1つも無い {
        選べる軸: 計測軸::綴りを並べる(&計測軸::全軸),
    })?;
    let 受け入れる軸 = 構図.受け入れる軸();
    if !受け入れる軸.contains(&候補.軸()) {
        return Err(影の欠落計器の引数の破れ::構図が候補の軸を受けない {
            構図: 構図.綴り(),
            候補: 候補.綴り(),
            受け入れる軸: 計測軸::綴りを並べる(受け入れる軸),
        });
    }
    Ok(指定 { 構図, 候補, 様式 })
}

