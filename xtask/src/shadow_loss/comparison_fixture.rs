//! 判定の固定が使う比較結果の組み立て。受け取るのは寸法と塗る領域、返すのは印を塗った比較結果である。
//!
//! GPUを回さずに判定だけを固定するために置く。判定の入力は比較結果1つだけであり、そこへ手で印を塗れば
//! 描画を伴わずに正例と負例を作れる。領域別の判定の固定と、矩形の数え上げの固定の両方がこの組み立てを使う。

use super::compare::{帯の集計, 比較結果};
use super::diagnostic_image::帯数;
use super::range_world;
use super::region_count::受光面の領域;

/// 固定が使う読み戻し画像の寸法。受光面の矩形がこの寸法へ固定されているため、固定も同じ寸法で作る。
pub(super) const 固定の幅: usize = 1280;
pub(super) const 固定の高さ: usize = 720;

pub(super) fn 影の無い比較結果(幅: usize, 高さ: usize) -> 比較結果 {
    let 画素数 = 幅 * 高さ;
    比較結果 {
        幅,
        高さ,
        帯別: [帯の集計::default(); 帯数],
        幾何の食い違い画素数: 0,
        帯の食い違い画素数: 0,
        基準の影の印: vec![false; 画素数],
        候補の影の印: vec![false; 画素数],
        欠落の印: vec![false; 画素数],
        余分の印: vec![false; 画素数],
    }
}

/// 遠方キャスターの領域は基準だけが影(全欠落)、近距離対照の領域は基準も候補も影(全残存)の比較結果。
pub(super) fn 負の対照が成り立つ比較結果() -> 比較結果 {
    let mut 比較 = 影の無い比較結果(固定の幅, 固定の高さ);
    影を塗る(&mut 比較, &range_world::遠方キャスターの影の領域, false);
    影を塗る(&mut 比較, &range_world::近距離対照の影の領域, true);
    比較
}

/// 矩形が覆う画素の数。欠落と残存の割合を狙った値へ置くために使う。
pub(super) fn 領域の画素数(領域: &受光面の領域) -> usize {
    領域.画素の添字(固定の幅).count()
}

/// 矩形の全画素へ基準の影を塗り、候補に残すかどうかで候補の影と欠落の印を決める。
pub(super) fn 影を塗る(比較: &mut 比較結果, 領域: &受光面の領域, 候補に残す: bool) {
    候補に残す画素を先頭から作る(比較, 領域, if 候補に残す { 領域の画素数(領域) } else { 0 });
    for 添字 in 領域.画素の添字(比較.幅) {
        比較.基準の影の印[添字] = true;
    }
}

/// 矩形の先頭から数えた画素数だけ候補にも影を残す。欠落の割合を狙った値へ置くために使う。
pub(super) fn 候補に残す画素を先頭から作る(比較: &mut 比較結果, 領域: &受光面の領域, 残す画素数: usize) {
    for (順番, 添字) in 領域.画素の添字(比較.幅).enumerate() {
        let 残す = 順番 < 残す画素数;
        比較.候補の影の印[添字] = 残す;
        比較.欠落の印[添字] = !残す;
    }
}
