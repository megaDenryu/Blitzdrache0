//! 段3aの動きベクトルの確認入口。シーン描画と空のパスが書いた動きベクトル画像を読み戻し、カメラを止めた実行では
//! 1画素ぶんの幅を超える画素が1つも無いこと、カメラを1フレームで動かした実行ではその画素が現れることを確かめる。
//!
//! 対で採るのは、片方だけでは「書かれていない」と「動いていないから零である」を区別できないためである。
//! 動きベクトルは色にも深度にも影響しないため、この画像を直に読む以外にその区別を付ける手立てが無い。
//!
//! 判定に使う量を1画素ぶんの正規化装置座標の幅に採るのは、その量が画面の寸法から一意に決まり、制定を要る
//! 閾値でないためである。解析導出との許容付きの比較は段3bの検収が持つ
//! (参照: `_doc/設計/時間再構成.md`「検収戦略(判断g)」)。

mod condition;
mod observation;
mod run;

use std::process::ExitCode;

use condition::条件;
use observation::観測;

pub fn 実行する() -> ExitCode {
    match 検収する() {
        Ok(要約) => {
            println!("[xtask] motion-vector成功: {要約}");
            ExitCode::SUCCESS
        }
        Err(理由) => {
            eprintln!("[xtask] motion-vector失敗: {理由}");
            ExitCode::FAILURE
        }
    }
}

fn 検収する() -> Result<String, String> {
    crate::visual_sample_world::用意する()?;
    let 静止 = run::観測を採る(条件::カメラを止める)?;
    let 移動 = run::観測を採る(条件::カメラを動かす)?;
    判定する(&静止, &移動)?;
    Ok(format!(
        "静止は全画素{}のうち1画素の幅{:.6}を超えた画素0(最大{:.6})、移動は超えた画素{}(最大{:.6})、どちらも非有限画素0",
        静止.全画素数, 静止.一画素の幅, 静止.最大の大きさ, 移動.超えた画素数, 移動.最大の大きさ
    ))
}

fn 判定する(静止: &観測, 移動: &観測) -> Result<(), String> {
    if 静止.超えた画素数 != 0 {
        return Err(format!(
            "カメラを止めた実行で1画素の幅{:.6}を超えた画素が{}あった(最大{:.6})",
            静止.一画素の幅, 静止.超えた画素数, 静止.最大の大きさ
        ));
    }
    if 移動.超えた画素数 == 0 {
        return Err(format!(
            "カメラを動かした実行で1画素の幅{:.6}を超えた画素が1つも無かった(最大{:.6})。動きベクトルが書かれていない",
            移動.一画素の幅, 移動.最大の大きさ
        ));
    }
    for 観測 in [静止, 移動] {
        if 観測.非有限画素数 != 0 {
            return Err(format!("動きベクトルに非数か無限大の画素が{}あった", 観測.非有限画素数));
        }
    }
    if 静止.全画素数 != 移動.全画素数 {
        return Err(format!("2条件の画素数が違う(静止{}・移動{})", 静止.全画素数, 移動.全画素数));
    }
    Ok(())
}
