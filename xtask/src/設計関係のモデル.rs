//! Rustのソースから設計関係グラフを抽出する木(Issue #170。層1と層2の抽出)。
//!
//! Rustのソースの構文と、`blitz_design` の設計解釈マーカーと、関数の役割の型引数の組から、プリミティブな宣言と設計解釈マーカーの宣言の一覧を抽出する。
//! 抽出器は関係を直接出さない。設計関係と保持する関係は、`blitz_design_verification` の定義の式が宣言から導く(Issue #193 の段階2)。
//! 関係を導く宣言が書かれてよい構文は `抽出元の構文` が数え上げた4つだけであり、生の `fn f(a: A) -> B` からは何も抽出しない。
//! マーカーの実装と上位トレイトの宣言からは関係を出さず、設計解釈マーカーの宣言の一覧(`blitz_design_verification::設計解釈マーカーの宣言の一覧`)を出す。
//!
//! **この木は検証系の信頼基盤である。** 抽出が誤ったDグラフを作れば、その上で示した命題の成立は意味を持たない。
//! そのため抽出の規則1つごとに「このRustの構文からこの関係が出る」を固定する回帰試験を置く。宣言から関係を導く定義の式の試験は `blitz_design_verification` が持つ。
//! 構文の読み取りは `super::conform::設計オントロジーの規約検査` の構文解析器(`定義を探す`・`モジュールパス`・`クレート構文検査`)を借り、複製を作らない。
//! Rustの項目の名前空間のノードで、識別子のモジュールパスが空であることは、その型の定義をたどれなかったことを表す取り決めである。
//! モジュールパスが空のノードを落とさないのは、落とすと「関係が無い」と読まれて偽の反証が出るためであり、そのとき抽出器は同じ1件を `抽出できなかった行` として数える。
//!
//! 設計概念・設計関係・設計関係グラフの型そのものは `blitz_design_verification` が所有する。`xtask` はそれらを組み立てる側であり、
//! ここで再公開するのは、抽出の側の利用箇所がグラフの語彙をこの木の名前で読めるようにするためである。
//! 参照: `_doc/設計/設計オントロジー.md` 第6節。

#[path = "設計関係のモデル/設計関係の抽出.rs"]
