pub use blitz_design_verification::{
    Rustの項目の種類, プリミティブな関係の種類, プリミティブな関係エッジ, 同一性の衝突, 抽出の出どころ, 抽出元の構文, 設計概念の種類, 設計概念の識別子, 設計概念への参照, 設計概念ノード, 設計関係の結び付き方, 設計関係グラフ,
};
pub use 設計関係の抽出::{保証範囲の外の構文, 抽出した設計関係グラフと抽出の欠け, 抽出できなかった理由, 抽出できなかった行, 設計関係グラフを抽出する};
