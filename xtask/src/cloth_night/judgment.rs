//! 布の領域を切り出して平均輝度を測る工程と、その輝度が時刻に追従していることの判定。
//! 受け取るのは布ありと布なしの2枚、返すのは布の画素数と平均輝度、および合否の要約である。
//!
//! 布の領域を色で決めず2枚の差で決めるのは、布の色が時刻ごとの光で変わるためである。
//! 同じ時刻の布ありと布なしを比べれば、差が出る画素はその時刻に布が覆った画素だけになる。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};

/// 布が覆ったと数える成分差の下限。読み戻しの量子化ゆらぎを除く。
const 成分差下限: u8 = 4;

/// 夜の布の平均輝度の上限(8bit)。実測は5.8(第3段階で布が局所光を読むようになる前は5.7)であり、方向光強度を掛けず環境光も固定値だった是正前は156.7だった。
/// 60はその2つの間を10倍以上・2.6倍以上の余裕で分ける値である。
/// 注意: 布の画素は実行のたびに揺れる(同じ実行ファイルの2回で昼841画素・成分差の最大215)ため、画素の一致は求められない。
const 夜の平均輝度上限: f64 = 60.0;
/// 夜の布が真っ黒でないことの下限。0だと「環境光にも追従していない」状態を見逃す。
const 夜の平均輝度下限: f64 = 1.0;
/// 昼が夜より明るいと認める倍率。実測は3.62である。
/// 布は縦に垂れており法線が太陽の向きと大きくずれるため、直接光の寄与は環境光と同じ桁までしか伸びない。
/// この判定は「是正で直接光ごと消していない」ことを見るためのものであり、方向光が夜に残る欠陥を捕まえる主判定は夜の平均輝度上限のほうである。
const 昼と夜の輝度比下限: f64 = 1.5;

const 布ありと布なしで違った画素: 判定の名前 =
    判定の名前::定数から生成する("布ありと布なしの読み戻し画像で違った画素(布が描かれていれば1画素以上ある)");
const 布の画素数の写し: 判定の名前 = 判定の名前::定数から生成する("布の画素数(平均を求める割る数がu32へ収まるはずである)");
const 夜の布の平均輝度が上限に収まること: 判定の名前 =
    判定の名前::定数から生成する("夜の布の平均輝度(超えるなら布へ方向光が残っている)");
const 夜の布の平均輝度が下限に届くこと: 判定の名前 =
    判定の名前::定数から生成する("夜の布の平均輝度(届かないなら布が環境光にも追従していない)");
const 昼と夜の平均輝度の比: 判定の名前 =
    判定の名前::定数から生成する("昼と夜の布の平均輝度の比(届かないなら方向光が時刻で変わっていない)");

pub(super) struct 布領域 {
    pub(super) 画素数: usize,
    pub(super) 平均輝度: f64,
}

pub(super) fn 布領域を測る(布あり: &読み戻し画像, 布なし: &読み戻し画像) -> Result<布領域, 判定の破れ> {
    寸法が同じであることの判定名(布あり, 布なし).真であることを課す(布あり.寸法が同じか(布なし))?;
    let mut 画素数 = 0usize;
    let mut 輝度合計 = 0.0_f64;
    for (左, 右) in 布あり.画素列().zip(布なし.画素列()) {
        let 差 = 左.iter().zip(右.iter()).take(3).map(|(&p, &q)| p.abs_diff(q)).max().unwrap_or(0);
        if 差 < 成分差下限 {
            continue;
        }
        画素数 += 1;
        輝度合計 += (f64::from(左[0]) + f64::from(左[1]) + f64::from(左[2])) / 3.0;
    }
    if 画素数 == 0 {
        return Err(布ありと布なしで違った画素.あるはずのものが無い破れ());
    }
    布の画素数の写し.上限を課す(画素数, usize::try_from(u32::MAX).unwrap_or(usize::MAX))?;
    let 割る数 = u32::try_from(画素数).unwrap_or(u32::MAX);
    Ok(布領域 {
        画素数,
        平均輝度: 輝度合計 / f64::from(割る数),
    })
}

/// 夜と昼の布の平均輝度が、方向光と環境光の時刻変化に追従していることを判定する。返すのは実測の要約である。
pub(super) fn 明るさの時刻への追従を判定する(夜: &布領域, 昼: &布領域) -> Result<String, 判定の破れ> {
    夜の布の平均輝度が上限に収まること.上限を課す(夜.平均輝度, 夜の平均輝度上限)?;
    夜の布の平均輝度が下限に届くこと.下限を課す(夜.平均輝度, 夜の平均輝度下限)?;
    let 比 = 昼.平均輝度 / 夜.平均輝度;
    昼と夜の平均輝度の比.下限を課す(比, 昼と夜の輝度比下限)?;
    Ok(format!(
        "布の平均輝度は夜{:.1}(上限{夜の平均輝度上限})・昼{:.1}で比{比:.2}(下限{昼と夜の輝度比下限})、布の画素は夜{}・昼{}",
        夜.平均輝度, 昼.平均輝度, 夜.画素数, 昼.画素数
    ))
}

fn 寸法が同じであることの判定名(布あり: &読み戻し画像, 布なし: &読み戻し画像) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "布ありと布なしの読み戻し寸法が同じであること(布あり{}、布なし{})",
        布あり.寸法の綴り(),
        布なし.寸法の綴り()
    ))
}
