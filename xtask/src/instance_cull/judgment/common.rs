//! 可視判定のオンとオフの両方の実行で共通に成り立つべき条件。受け取るのは実行の対、返すのは合否である。
//! 見るのは3つであり、読み戻し画像がバイト一致すること、各パスの可視数が積んだ発行のインスタンス数と一致すること、
//! validationが0件であることである。
//! 2つ目は出どころの違う2つの数の突き合わせであり、判定した集合と実際に描いた集合が食い違っていないことを示す。
//!
//! バイト長と違うバイトの数を別の判定として課すのは、長さの違う2枚を先頭から重ねて比べると、
//! 重なった範囲が一致しただけの2枚を一致と読んでしまうためである。

use super::実行の対;
use crate::acceptance::{判定の名前, 判定の破れ};
use crate::report_parse::全パスを並べる;

pub(super) fn 両方の実行に共通の条件を検査する(対: &実行の対) -> Result<(), 判定の破れ> {
    読み戻し画像のバイト長の判定名(&対.シーン名).一致を課す(対.オン.バイト列().len(), 対.オフ.バイト列().len())?;
    let 違うバイト数 = 対.オン.バイト列().iter().zip(対.オフ.バイト列()).filter(|(左, 右)| 左 != 右).count();
    可視判定の有無で違ったバイトの判定名(&対.シーン名).零件であることを課す(違うバイト数)?;
    for (実行名, 計数) in [("可視判定オン", &対.オン計数), ("可視判定オフ", &対.オフ計数)] {
        crate::count_consistency::計数の整合を検査する(実行名, 計数)?;
        for (パス名, パス) in 全パスを並べる(計数) {
            可視数と積んだ個体数の判定名(実行名, &パス名).一致を課す(パス.可視数, パス.個体数)?;
        }
        validationの指摘の判定名(実行名).零件であることを課す(計数.validation件数)?;
    }
    Ok(())
}

fn 読み戻し画像のバイト長の判定名(シーン名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{シーン名}の読み戻し画像のバイト長(可視判定の有無で一致するはずである)"))
}

fn 可視判定の有無で違ったバイトの判定名(シーン名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{シーン名}の読み戻し画像が可視判定の有無で違ったバイト"))
}

fn 可視数と積んだ個体数の判定名(実行名: &str, パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の{パス名}の可視数(積んだ発行のインスタンス数と一致するはずである)"))
}

fn validationの指摘の判定名(実行名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("{実行名}の実行で出た検証層の指摘"))
}
