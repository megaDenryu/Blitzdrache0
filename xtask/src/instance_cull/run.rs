//! 同じシーンを可視判定のオンとオフで1回ずつ起こす工程。受け取るのは実行環境とシーンとシェーダー入口、
//! 返すのは2回ぶんの読み戻し画像と計数を束ねた実行の対である。判定はこの対だけを見る。
//!
//! 起動の選択肢をここが持つのは、オンとオフの違いが`--no-instance-cull`を足すかどうかだけであり、
//! その1つの違いを2つの引数の並びとして固定する場所が要るためである。

use std::path::Path;

use super::error::植生個体の可視判定の検収エラー;
use super::judgment::実行の対;
use crate::acceptance::{描画フレーム数, 描画検収の実行環境, 検収の1回の実行, 検収の実行名, 検収シーン名};
use crate::vegetation_run;

const フレーム数: 描画フレーム数 = 描画フレーム数::生成する(12);
// メモリ報告(--report-memory)は観測であり判定値ではない。資源を常設する軸(局所可視性・時間再構成)が増えると確保数が動くが、判定は読み戻し画像のバイト一致と可視数だけが持つ。
const 可視判定オンの引数: [&str; 3] = ["--no-post", "--report-draw-issue", "--report-memory"];
const 可視判定オフの引数: [&str; 4] = ["--no-post", "--report-draw-issue", "--report-memory", "--no-instance-cull"];

pub(super) fn 対で描く(
    実行環境: &描画検収の実行環境,
    シーン名: 検収シーン名,
    シーン名の綴り: &str,
    シェーダー入口: &Path,
) -> Result<実行の対, 植生個体の可視判定の検収エラー> {
    let オン = 一条件を描く(実行環境, シーン名, &format!("{シーン名の綴り}_on"), シェーダー入口, &可視判定オンの引数)?;
    let オフ = 一条件を描く(実行環境, シーン名, &format!("{シーン名の綴り}_off"), シェーダー入口, &可視判定オフの引数)?;
    let オン計数 = crate::report_parse::取り出す(オン.報告())?;
    let オフ計数 = crate::report_parse::取り出す(オフ.報告())?;
    Ok(実行の対 {
        シーン名: シーン名の綴り.to_string(),
        オン: オン.画像を取り出す(),
        オフ: オフ.画像を取り出す(),
        オン計数,
        オフ計数,
    })
}

fn 一条件を描く(
    実行環境: &描画検収の実行環境,
    シーン名: 検収シーン名,
    実行名の綴り: &str,
    シェーダー入口: &Path,
    起動引数: &[&str],
) -> Result<検収の1回の実行, 植生個体の可視判定の検収エラー> {
    let 実行 = 実行環境.描いて読み戻す(
        検収の実行名::生成する(実行名の綴り)?,
        &vegetation_run::植生世界の起動指定を組み立てる(シーン名, フレーム数, シェーダー入口, 起動引数),
    )?;
    実行.報告().画面へ流す();
    Ok(実行)
}
