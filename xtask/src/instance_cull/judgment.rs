//! 可視判定のオンとオフの対に対する判定。受け取るのは2回の実行結果と計数、返すのは合否である。
//! 正の判定は「全個体が画面にもライト視錐台にも入る世界では可視判定の有無で読み戻し画像がバイト一致し、
//! どちらのパスも1体も減らない」であり、負の対照は「視錐台外の個体を持つ世界では各パスの可視数が
//! そのパスの視錐台の外にある個体だけ減り、それでも画像はバイト一致する」である。
//! バイト一致が同時に影の保全でもある。画面外の影投げ個体がシャドウパスから落ちれば、床の暗部が消えて画像が変わるためである。

use super::pixel_check;
use crate::report_parse::計数報告;
use crate::vegetation_run::実行結果;

/// 負対照の世界でシャドウパスから落ちる個体の数。ライト視錐台の外に置いた番兵1体だけである。
/// この個体は正射影の範囲の外にあって元から影を落とさないため、落ちても画素は1つも変わらない。
const ライト視錐台外の番兵数: u64 = 1;

pub(super) struct 実行の対 {
    pub(super) シーン名: String,
    pub(super) オン: 実行結果,
    pub(super) オフ: 実行結果,
    pub(super) オン計数: 計数報告,
    pub(super) オフ計数: 計数報告,
}

pub(super) fn 正の判定を検査する(対: &実行の対) -> Result<(), String> {
    共通を検査する(対)?;
    for (パス名, パス) in [("シーン", &対.オン計数.シーン), ("シャドウ", &対.オン計数.シャドウ)] {
        if パス.可視数 != パス.候補数 {
            return Err(format!(
                "{}は全個体が画面にもライト視錐台にも入る世界だが、{パス名}パスの可視数{}が候補数{}より少ない",
                対.シーン名, パス.可視数, パス.候補数
            ));
        }
    }
    Ok(())
}

pub(super) fn 負の対照と影を検査する(対: &実行の対) -> Result<pixel_check::影の画素数, String> {
    共通を検査する(対)?;
    if 対.オン計数.シーン.可視数 >= 対.オン計数.シーン.候補数 {
        return Err(format!(
            "視錐台外の個体があるのにシーンパスの可視数が減っていない: 候補{}体、可視{}体",
            対.オン計数.シーン.候補数, 対.オン計数.シーン.可視数
        ));
    }
    let 期待シャドウ可視数 = 対.オン計数.シャドウ.候補数 - ライト視錐台外の番兵数;
    if 対.オン計数.シャドウ.可視数 != 期待シャドウ可視数 {
        return Err(format!(
            "シャドウパスの可視数{}が期待の{期待シャドウ可視数}体と違う: 候補{}体のうちライト視錐台の外は番兵{ライト視錐台外の番兵数}体だけである",
            対.オン計数.シャドウ.可視数, 対.オン計数.シャドウ.候補数
        ));
    }
    for (パス名, パス) in [("シーン", &対.オフ計数.シーン), ("シャドウ", &対.オフ計数.シャドウ)] {
        if パス.可視数 != パス.候補数 {
            return Err(format!(
                "可視判定を止めた実行の{パス名}パスで全個体が描かれていない: 候補{}体、可視{}体",
                パス.候補数, パス.可視数
            ));
        }
    }
    pixel_check::影を数える(&対.オン)
}

/// 両方の実行で共通に成り立つべき条件。画像のバイト一致、各パスの可視数と積んだ発行のインスタンス数の一致、
/// validationが0件であることの3つである。
/// 2つ目は出どころの違う2つの数の突き合わせであり、判定した集合と実際に描いた集合が食い違っていないことを示す。
fn 共通を検査する(対: &実行の対) -> Result<(), String> {
    if 対.オン.rgba8 != 対.オフ.rgba8 {
        let 差分数 = 対.オン.rgba8.iter().zip(&対.オフ.rgba8).filter(|(左, 右)| 左 != 右).count();
        return Err(format!("{}の読み戻し画像が可視判定の有無で一致しない: {差分数}バイトが違う", 対.シーン名));
    }
    for (実行名, 計数) in [("可視判定オン", &対.オン計数), ("可視判定オフ", &対.オフ計数)] {
        for (パス名, パス) in [("シーン", &計数.シーン), ("シャドウ", &計数.シャドウ)] {
            if パス.可視数 != パス.個体数 {
                return Err(format!(
                    "{実行名}の{パス名}パスの可視数{}が積んだ個体数{}と違う",
                    パス.可視数, パス.個体数
                ));
            }
        }
        if 計数.validation件数 != 0 {
            return Err(format!("{実行名}でvalidationが{}件発生した", 計数.validation件数));
        }
    }
    Ok(())
}
