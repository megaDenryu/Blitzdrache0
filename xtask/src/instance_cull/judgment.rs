//! 可視判定のオンとオフの対に対する判定。受け取るのは2回の実行結果と計数、返すのは合否である。
//! 正の判定は「全個体が画面にも影の範囲にも入る世界では可視判定の有無で読み戻し画像がバイト一致し、
//! シーンからも影からも1体も落ちない」であり、負の対照は「視錐台外の個体を持つ世界では可視数が
//! その範囲の外にある個体だけ減り、それでも画像はバイト一致する」である。
//! バイト一致が同時に影の保全でもある。画面外の影投げ個体が影から落ちれば、床の暗部が消えて画像が変わるためである。
//!
//! 影の側は距離区分0から距離区分3の4つに分かれる。距離区分別の可視数を足した値は複数の距離区分へ属する個体を重複して数えるため、
//! 「影を落とすべき個体が1体も落ちていない」ことは可視個体の選別の計数の距離区分の和集合の可視数で見る。
//! 距離区分別に絞られたことと、レンダラーと可視個体の選別の2つの計器が整合することは`count_consistency`が見る
//! (参照: `_doc/設計/空と時間帯と遠距離シャドウ.md`「可視ID列の距離区分別の区間(4区分並べの後継)」)。
//!
//! オンとオフの両方の実行に共通して成り立つべき条件は`common`が持つ。

mod common;

use super::pixel_check;
use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};
use crate::report_parse::{全パスを並べる, 計数報告};

/// 負対照の世界で影の範囲から落ちる個体の数。ライト視錐台の外に置いた番兵1体だけである。
/// この個体は正射影の範囲の外にあって元から影を落とさないため、落ちても画素は1つも変わらない。
const ライト視錐台外の番兵数: u64 = 1;

pub(super) struct 実行の対 {
    pub(super) シーン名: String,
    pub(super) オン: 読み戻し画像,
    pub(super) オフ: 読み戻し画像,
    pub(super) オン計数: 計数報告,
    pub(super) オフ計数: 計数報告,
}

pub(super) fn 正の判定を検査する(対: &実行の対) -> Result<(), 判定の破れ> {
    common::両方の実行に共通の条件を検査する(対)?;
    let シーン = &対.オン計数.シーン;
    全個体が画面に入る世界のシーン可視数の判定名(&対.シーン名).一致を課す(シーン.可視数, シーン.候補数)?;
    let 可視個体の選別 = &対.オン計数.可視個体の選別;
    全個体が影の範囲に入る世界の和集合の判定名(&対.シーン名, 可視個体の選別.候補数)
        .一致を課す(可視個体の選別.距離区分の和集合の可視数, 可視個体の選別.候補数)
}

pub(super) fn 負の対照と影を検査する(対: &実行の対) -> Result<pixel_check::影の画素数, 判定の破れ> {
    common::両方の実行に共通の条件を検査する(対)?;
    let シーン = &対.オン計数.シーン;
    視錐台外の個体で減るシーン可視数の判定名(シーン.可視数, シーン.候補数).真であることを課す(シーン.可視数 < シーン.候補数)?;
    let 可視個体の選別 = &対.オン計数.可視個体の選別;
    let 期待する距離区分の和集合 = 可視個体の選別.候補数 - ライト視錐台外の番兵数;
    番兵だけが影から落ちる和集合の判定名(可視個体の選別.候補数).一致を課す(可視個体の選別.距離区分の和集合の可視数, 期待する距離区分の和集合)?;
    crate::count_consistency::距離区分別に絞られたことを検査する("可視判定オン", &対.オン計数)?;
    // 可視判定を止めた実行では、シーンも全距離区分も全個体を描く。これが距離区分別の可視個体の選別の負の対照である。
    for (パス名, パス) in 全パスを並べる(&対.オフ計数) {
        可視判定を止めた実行が全個体を描くことの判定名(&パス名).一致を課す(パス.可視数, パス.候補数)?;
    }
    pixel_check::影を数える(&対.オン)
}

fn 全個体が画面に入る世界のシーン可視数の判定名(シーン名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{シーン名}のシーンパスの可視数(全個体が画面に入る世界のため候補数と一致するはずである)"
    ))
}

fn 全個体が影の範囲に入る世界の和集合の判定名(シーン名: &str, 候補数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "{シーン名}でいずれかの距離区分へ影を落とす個体の数(全個体が影の範囲に入る世界のため候補{候補数}体と一致するはずである)"
    ))
}

/// 比べの形を下限でなく真偽で課すのは、この判定が候補数に等しい可視数を破れの側へ置くためである。
/// 上限の口は等号を通すため、そのまま置き換えると1体も落ちていない実行が境界でだけ通る。
fn 視錐台外の個体で減るシーン可視数の判定名(可視数: u64, 候補数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!("視錐台外の個体があるシーンパスの可視数{可視数}が候補{候補数}体を下回ること"))
}

fn 番兵だけが影から落ちる和集合の判定名(候補数: u64) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "いずれかの距離区分へ影を落とす個体の数(候補{候補数}体のうちライト視錐台の外は番兵{ライト視錐台外の番兵数}体だけである)"
    ))
}

fn 可視判定を止めた実行が全個体を描くことの判定名(パス名: &str) -> 判定の名前 {
    判定の名前::組み立てた綴りから生成する(format!(
        "可視判定を止めた実行の{パス名}の可視数(全個体を描くため候補数と一致するはずである)"
    ))
}
