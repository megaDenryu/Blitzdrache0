//! 可視判定のオンとオフの対に対する判定。受け取るのは2回の実行結果と計数、返すのは合否である。
//! 正の判定は「全個体が画面に入る世界では可視判定の有無で読み戻し画像がバイト一致し、1体も減らない」であり、
//! 負の対照は「視錐台外の個体を持つ世界ではシーンパスの可視数が候補数より減り、それでも画像はバイト一致する」である。
//! バイト一致が同時に影の保全でもある。画面外の影投げ個体がシャドウパスから落ちれば、床の暗部が消えて画像が変わるためである。

use super::pixel_check;
use crate::report_parse::計数報告;
use crate::vegetation_run::実行結果;

pub(super) struct 実行の対 {
    pub(super) シーン名: String,
    pub(super) オン: 実行結果,
    pub(super) オフ: 実行結果,
    pub(super) オン計数: 計数報告,
    pub(super) オフ計数: 計数報告,
}

pub(super) fn 正の判定を検査する(対: &実行の対) -> Result<(), String> {
    共通を検査する(対)?;
    if 対.オン計数.シーン.可視数 != 対.オン計数.シーン.候補数 {
        return Err(format!(
            "{}は全個体が画面に入る世界だが、可視数{}が候補数{}より少ない",
            対.シーン名, 対.オン計数.シーン.可視数, 対.オン計数.シーン.候補数
        ));
    }
    Ok(())
}

pub(super) fn 負の対照と影を検査する(対: &実行の対) -> Result<pixel_check::影の画素数, String> {
    共通を検査する(対)?;
    if 対.オン計数.シーン.可視数 >= 対.オン計数.シーン.候補数 {
        return Err(format!(
            "視錐台外の個体があるのにシーンパスの可視数が減っていない: 候補{}体、可視{}体",
            対.オン計数.シーン.候補数, 対.オン計数.シーン.可視数
        ));
    }
    if 対.オフ計数.シーン.可視数 != 対.オフ計数.シーン.候補数 {
        return Err(format!(
            "可視判定を止めた実行で全個体が描かれていない: 候補{}体、可視{}体",
            対.オフ計数.シーン.候補数, 対.オフ計数.シーン.可視数
        ));
    }
    pixel_check::影を数える(&対.オン)
}

/// 両方の実行で共通に成り立つべき条件。画像のバイト一致、シャドウパスが全個体を描くこと、validationが0件であること。
fn 共通を検査する(対: &実行の対) -> Result<(), String> {
    if 対.オン.rgba8 != 対.オフ.rgba8 {
        let 差分数 = 対.オン.rgba8.iter().zip(&対.オフ.rgba8).filter(|(左, 右)| 左 != 右).count();
        return Err(format!("{}の読み戻し画像が可視判定の有無で一致しない: {差分数}バイトが違う", 対.シーン名));
    }
    for (名前, 計数) in [("可視判定オン", &対.オン計数), ("可視判定オフ", &対.オフ計数)] {
        if 計数.シャドウ.可視数 != 計数.シャドウ.候補数 || 計数.シャドウ.個体数 != 計数.シャドウ.候補数 {
            return Err(format!(
                "{名前}のシャドウパスが全個体を描いていない: 候補{}体、可視{}体、個体{}体",
                計数.シャドウ.候補数, 計数.シャドウ.可視数, 計数.シャドウ.個体数
            ));
        }
        if 計数.validation件数 != 0 {
            return Err(format!("{名前}でvalidationが{}件発生した", 計数.validation件数));
        }
    }
    Ok(())
}
