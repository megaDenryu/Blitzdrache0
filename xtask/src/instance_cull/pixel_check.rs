//! 読み戻し画像の影の分類。画面外の個体が落とす影が本当に画面へ出ていることを確かめ、判定が空振りでないことを示す。
//! 2つの領域は`crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラ、
//! `crates/blitz_app/src/app/scene_lighting.rs`の検収用ライト方針、1280×720画面を前提に固定している。
//!
//! 暗部領域が写す床の大域座標はおよそX=70から90、Z=45から55である。そこに立つ個体は無く、
//! 画面内の4個体の影は方向光の向きによりX=36から49へ伸びるため届かない。この領域を暗くできるのは画面外の影投げ個体だけである。

use crate::vegetation_run::実行結果;

/// 画面外の個体の影が落ちる床の領域。
const 暗部領域: 画面領域 = 画面領域 {
    x開始: 750,
    x終端: 1200,
    y開始: 370,
    y終端: 470,
};

/// 影の掛からない床の領域。同じ床が明るく描かれていることを対にして示す。
const 明部領域: 画面領域 = 画面領域 {
    x開始: 150,
    x終端: 450,
    y開始: 300,
    y終端: 360,
};

/// 影の内側と外側を分ける明度。実測は暗部が48、明部が112から120である。
const 暗部の上限: u8 = 80;
const 明部の下限: u8 = 100;

struct 画面領域 {
    x開始: usize,
    x終端: usize,
    y開始: usize,
    y終端: usize,
}

pub(super) struct 影の画素数 {
    pub(super) 暗部画素数: u64,
    pub(super) 明部画素数: u64,
}

pub(super) fn 影を数える(画像: &実行結果) -> Result<影の画素数, String> {
    let 暗部画素数 = 明度が範囲内の画素を数える(画像, &暗部領域, 0, 暗部の上限)?;
    let 期待暗部 = 領域の画素数(&暗部領域);
    if 暗部画素数 != 期待暗部 {
        return Err(format!(
            "画面外の個体の影が落ちる領域が暗くない: 暗い画素{暗部画素数}、領域の画素{期待暗部}"
        ));
    }
    let 明部画素数 = 明度が範囲内の画素を数える(画像, &明部領域, 明部の下限, u8::MAX)?;
    let 期待明部 = 領域の画素数(&明部領域);
    if 明部画素数 != 期待明部 {
        return Err(format!(
            "影の掛からない床の領域が明るくない: 明るい画素{明部画素数}、領域の画素{期待明部}"
        ));
    }
    Ok(影の画素数 {
        暗部画素数, 明部画素数
    })
}

fn 領域の画素数(領域: &画面領域) -> u64 {
    let 幅 = 領域.x終端 - 領域.x開始;
    let 高さ = 領域.y終端 - 領域.y開始;
    u64::try_from(幅 * 高さ).unwrap_or(u64::MAX)
}

fn 明度が範囲内の画素を数える(画像: &実行結果, 領域: &画面領域, 下限: u8, 上限: u8) -> Result<u64, String> {
    if 領域.x終端 > 画像.幅 || 領域.y終端 > 画像.高さ {
        return Err(format!("判定領域が読み戻し画像({}×{})の外にある", 画像.幅, 画像.高さ));
    }
    let mut 件数 = 0u64;
    for y in 領域.y開始..領域.y終端 {
        for x in 領域.x開始..領域.x終端 {
            let 位置 = (y * 画像.幅 + x) * 4;
            let 明度 = 画像.rgba8[位置];
            if 明度 >= 下限 && 明度 <= 上限 {
                件数 += 1;
            }
        }
    }
    Ok(件数)
}
