//! 読み戻し画像の影の分類。画面外の個体が落とす影が本当に画面へ出ていることを確かめ、判定が空振りでないことを示す。
//! 数え方は`pixel_region`が持ち、ここは領域と明度の境目を決める。
//! 2つの領域は`crates/blitz_app/src/app/scene_camera.rs`の植生シーンの初期カメラ、
//! `crates/blitz_app/src/app/scene_lighting.rs`の検収用ライト方針、1280×720画面を前提に固定している。
//!
//! 暗部領域が写す床の大域座標はおよそX=70から90、Z=45から55である。そこに立つ個体は無く、
//! 画面内の4個体の影は方向光の向きによりX=36から49へ伸びるため届かない。この領域を暗くできるのは画面外の影投げ個体だけである。

use crate::acceptance::{判定の名前, 判定の破れ, 読み戻し画像};
use crate::pixel_region::{全画素が範囲内かを確かめる, 画面領域};

/// 画面外の個体の影が落ちる床の領域。
const 暗部領域: 画面領域 = 画面領域 {
    x開始: 750,
    x終端: 1200,
    y開始: 370,
    y終端: 470,
};

/// 影の掛からない床の領域。同じ床が明るく描かれていることを対にして示す。
const 明部領域: 画面領域 = 画面領域 {
    x開始: 150,
    x終端: 450,
    y開始: 300,
    y終端: 360,
};

/// 影の内側と外側を分ける明度。実測は暗部が48、明部が112から120である。
const 暗部の上限: u8 = 80;
const 明部の下限: u8 = 100;

const 影が落ちる領域の暗い画素: 判定の名前 =
    判定の名前::定数から生成する("画面外の個体の影が落ちる領域で暗い画素の数(領域の全画素が暗いはずである)");
const 影の掛からない床の明るい画素: 判定の名前 =
    判定の名前::定数から生成する("影の掛からない床の領域で明るい画素の数(領域の全画素が明るいはずである)");

pub(super) struct 影の画素数 {
    pub(super) 暗部画素数: u64,
    pub(super) 明部画素数: u64,
}

pub(super) fn 影を数える(画像: &読み戻し画像) -> Result<影の画素数, 判定の破れ> {
    let 暗部画素数 = 全画素が範囲内かを確かめる(画像, &暗部領域, 0, 暗部の上限, &影が落ちる領域の暗い画素)?;
    let 明部画素数 = 全画素が範囲内かを確かめる(画像, &明部領域, 明部の下限, u8::MAX, &影の掛からない床の明るい画素)?;
    Ok(影の画素数 {
        暗部画素数, 明部画素数
    })
}
