//! 報告の1行から値を取り出す工程。受け取るのは終了時報告と見出し、返すのは数である。
//! 報告の構造(どの見出しが何を意味するか)は親モジュールが持ち、ここは見出しから読む口を組むことだけを担う。
//!
//! 見出しの綴りを実行時に組み立てるのは、パス別の行が「シーン発行数:」「シャドウ距離区分0発行数:」のように
//! パス名を頭に載せて並ぶためである。

use crate::acceptance::{検収エラー, 終了時報告};
use crate::report_heading::報告の見出し;
use crate::report_line_key::{報告の行の鍵, 鍵に値が結ばれる形};

pub(super) fn 値を読む(報告: &終了時報告, 見出し: &str) -> Result<u64, 検収エラー> {
    報告.見出しに続く数(&見出しを組む(見出し))
}

/// 「見出し: 名前=値 名前=値」の1行から、指定した名前の値を取り出す。添字でなく名前で引くのは、
/// 並びの順に意味が無く、行へ項目を足しても既存の読み取りが動かないためである。
pub(super) fn 名前付きの数を読む(報告: &終了時報告, 見出し: &str, 名前: &'static str) -> Result<u64, 検収エラー> {
    報告
        .見出しの1行(&見出しを組む(見出し))?
        .鍵に結ばれた数(&報告の行の鍵::定数から生成する(名前), 鍵に値が結ばれる形::等号の後ろが値である)
}

/// 「0=9 1=6」の形の行を添字順の一覧へ写す。項が1つも無い実行は「なし」と出るため空の一覧になる。
pub(super) fn 添字付きの数を読む(報告: &終了時報告, 見出し: &str) -> Result<Vec<u64>, 検収エラー> {
    報告.見出しに続く添字順の数一覧(&見出しを組む(見出し))
}

fn 見出しを組む(綴り: &str) -> 報告の見出し {
    報告の見出し::組み立てた綴りから生成する(綴り.to_string())
}
