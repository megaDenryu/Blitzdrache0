//! アプリの終了時報告を1つの計数報告へ写す工程。受け取るのは終了時報告、返すのは計数報告である。
//! 行の綴りは`crates/blitz_app/src/reports/draw_issue.rs`の出力と一致させている。

use super::line_read::{値を読む, 名前付きの数を読む, 添字付きの数を読む};
use super::{パス別描画発行, 可視個体の選別の計数, 計数報告, 距離区分数};
use crate::acceptance::{検収エラー, 終了時報告};

pub fn 取り出す(報告: &終了時報告) -> Result<計数報告, 検収エラー> {
    let mut 距離区分別のシャドウ = Vec::with_capacity(距離区分数);
    for 番号 in 0..距離区分数 {
        距離区分別のシャドウ.push(パス別を読む(報告, &format!("シャドウ距離区分{番号}"))?);
    }
    Ok(計数報告 {
        シーン: パス別を読む(報告, "シーン")?,
        距離区分別のシャドウ,
        可視個体の選別: 可視個体の選別を読む(報告)?,
        現在確保数: 値を読む(報告, "現在確保数:")?,
        最大同時確保数: 値を読む(報告, "最大同時確保数:")?,
        段切替回数: 値を読む(報告, "個体LOD段切替回数:")?,
        可視材料登録数: 値を読む(報告, "可視材料登録数:")?,
        起動後シーン読込回数: 値を読む(報告, "起動後シーン読込回数:")?,
        セット別束縛回数: 添字付きの数を読む(報告, "セット別ディスクリプタ束縛回数:")?,
        材質件数: 名前付きの数を読む(報告, "材質資源表:", "材質件数")?,
        常駐画像枚数: 名前付きの数を読む(報告, "材質資源表:", "常駐画像枚数")?,
        validation件数: 報告.検証層の指摘件数()?,
    })
}

fn 可視個体の選別を読む(報告: &終了時報告) -> Result<可視個体の選別の計数, 検収エラー> {
    Ok(可視個体の選別の計数 {
        候補数: 値を読む(報告, "選別候補数:")?,
        個体判定数: 値を読む(報告, "選別個体判定数:")?,
        シーン可視数: 値を読む(報告, "選別シーン可視数:")?,
        距離区分別の可視数: 添字付きの数を読む(報告, "選別距離区分別の可視数:")?,
        距離区分の和集合の可視数: 値を読む(報告, "選別距離区分の和集合の可視数:")?,
    })
}

fn パス別を読む(報告: &終了時報告, パス名: &str) -> Result<パス別描画発行, 検収エラー> {
    Ok(パス別描画発行 {
        発行数: 値を読む(報告, &format!("{パス名}発行数:"))?,
        候補数: 値を読む(報告, &format!("{パス名}候補数:"))?,
        可視数: 値を読む(報告, &format!("{パス名}可視数:"))?,
        個体数: 値を読む(報告, &format!("{パス名}個体数:"))?,
        段別個体数: 添字付きの数を読む(報告, &format!("{パス名}段別個体数:"))?,
        投入インデックス数: 値を読む(報告, &format!("{パス名}投入インデックス数:"))?,
        描画数: 値を読む(報告, &format!("{パス名}描画数:"))?,
        パイプライン切替: 値を読む(報告, &format!("{パス名}パイプライン切替:"))?,
        材質切替: 値を読む(報告, &format!("{パス名}材質切替:"))?,
    })
}
